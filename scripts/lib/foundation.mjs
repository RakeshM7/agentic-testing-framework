const citeComment = (e, indent = "  ") => (e?.cite ? `${indent}// ${e.module ? `${e.module}: ` : ""}${e.cite.join(", ")}\n` : `${indent}// default (template)\n`);
const notesMd = (o) => ((o.notes ?? []).length ? (o.notes ?? []).map((n) => `- **${n.topic}**: ${n.text} (${n.cite.join(", ")})`).join("\n") + "\n" : "None.\n");
const requestsMd = (o) =>
  (o.requests ?? []).length
    ? (o.requests ?? []).map((r) => `- ${r.kind}${r.requestedBy ? ` from ${r.requestedBy}` : ""}: ${r.text}${(r.files ?? []).length ? ` -> ${r.files.join(", ")}` : ""}${(r.exports ?? []).length ? ` (exports ${r.exports.join(", ")})` : ""}`).join("\n") + "\n"
    : "None.\n";

// The default auth of the API and k6 sides: the run-config's api.auth_header (a header and a variable NAME), if any.
function defaultAuth(cfg) {
  const h = cfg.api?.auth_header;
  if (!h) return { scheme: "none", header: null, prefix: "", env: null, cookie: null };
  return { scheme: /^authorization$/i.test(h.name) ? "bearer" : "api-key", header: h.name, prefix: h.prefix ?? "", env: h.env ?? null, cookie: null };
}
function resolveAuth(cfg, auth, { k6 = false } = {}) {
  const d = defaultAuth(cfg);
  if (!auth) return d;
  const sameScheme = auth.scheme === d.scheme;
  const scheme = auth.scheme;
  const header = auth.header ?? (sameScheme ? d.header : scheme === "bearer" || scheme === "oauth2" ? "Authorization" : null);
  const prefix = auth.prefix ?? (sameScheme ? d.prefix : scheme === "bearer" || scheme === "oauth2" ? "Bearer " : "");
  const env = k6 ? null : auth.env ?? (sameScheme && d.env ? d.env : scheme === "api-key" ? "API_KEY" : scheme === "bearer" || scheme === "oauth2" ? "API_TOKEN" : null);
  return { scheme, header, prefix, env, cookie: auth.cookie ?? null };
}

// The values each side's templates are filled with. -> {values, parts?}
function valuesFor(ctx, side, overlay) {
  const o = overlay ?? {};
  const cfg = ctx.cfg;
  const values = { product: ctx.product };
  if (side === "repo") {
    const conf = { ...DEFAULTS.repo };
    for (const r of o.requests ?? []) if (r.kind === "config") conf[r.name] = r.value;
    Object.assign(values, {
      testTimeoutMs: conf.testTimeoutMs,
      expectTimeoutMs: conf.expectTimeoutMs,
      retries: conf.retries,
      workers: conf.workers === null ? "undefined" : conf.workers,
      fullyParallel: conf.fullyParallel,
    });
    const envNames = [...new Set([...(cfg.api?.auth_header?.env ? [cfg.api.auth_header.env] : []), ...(o.requests ?? []).filter((r) => r.kind === "env").map((r) => r.name)])].filter((n) => !ENV_NAMES.includes(n));
    values.extraEnv = envNames.length ? `\n# Requested by the foundation (repo overlay) or the run-config's api.auth_header\n${envNames.map((n) => `${n}=`).join("\n")}\n` : "";
    values.extraAccessors = envNames.map((n) => `  ${n.toLowerCase().replace(/_([a-z0-9])/g, (_, c) => c.toUpperCase())}: (): string | undefined => optional(${lit(n)}),\n`).join("");
    const ignores = [...new Set((o.requests ?? []).filter((r) => r.kind === "gitignore").map((r) => String(r.pattern ?? "").trim()).filter(Boolean))];
    values.extraIgnores = ignores.length ? `# Requested in the repo overlay\n${ignores.join("\n")}\n` : "";
  }
  if (side === "ui") {
    const s = o.settings ?? {};
    const sel = (e) => (e ? lit({ role: e.role, name: e.name }) : "null");
    const login = o.login ? loginForm(ctx, o.login) : null;
    const loginValue = login && !login.problems.length ? lit({ path: login.path, username: o.login.username, password: o.login.password, submit: o.login.submit }) : "null";
    values.entries = [
      `${citeComment(s.actionTimeoutMs)}  actionTimeoutMs: ${s.actionTimeoutMs?.value ?? DEFAULTS.ui.actionTimeoutMs},\n`,
      `${citeComment(s.navigationTimeoutMs)}  navigationTimeoutMs: ${s.navigationTimeoutMs?.value ?? DEFAULTS.ui.navigationTimeoutMs},\n`,
      `${citeComment(s.viewport)}  viewport: ${lit(s.viewport?.value ?? DEFAULTS.ui.viewport)},\n`,
      `${s.loadingIndicator ? citeComment(s.loadingIndicator) : "  // none observed\n"}  loadingIndicator: ${sel(s.loadingIndicator)},\n`,
      `${s.cookieBanner ? citeComment(s.cookieBanner) : "  // none observed\n"}  cookieBanner: ${sel(s.cookieBanner)},\n`,
      `${o.login ? citeComment(o.login) : "  // no plain login form recorded: STORAGE_STATE only\n"}  login: ${loginValue},\n`,
    ].join("");
    values.notes = notesMd(o);
    values.requests = requestsMd(o);
    values.loginBlock = loginValue === "null" ? "{{noLogin}}" : "{{login}}";
    values.loginCite = o.login?.cite?.join(", ") ?? "";
    values.loginState = o.login?.state ?? "";
  }
  if (side === "api") {
    const auth = resolveAuth(cfg, o.auth);
    const basePaths = Object.fromEntries((o.basePaths ?? []).map((b) => [b.name, b.path]));
    const headers = { ...DEFAULTS.api.defaultHeaders, ...Object.fromEntries((o.defaultHeaders ?? []).map((h) => [h.name, h.value])) };
    const identities = [...(cfg.authorizations?.identities ?? [])]
      .sort((a, b) => a.name.localeCompare(b.name))
      .map((i) => ({ name: i.name, role: i.role, sessionStateFile: i.session_state_file ?? null, credentialsFile: i.credentials_file ?? null }));
    values.entries = [
      `${(o.basePaths ?? []).length ? (o.basePaths ?? []).map((b) => citeComment(b)).join("") : "  // none recorded: paths are relative to API_BASE_URL\n"}  basePaths: ${lit(basePaths)},\n`,
      `${(o.defaultHeaders ?? []).length ? (o.defaultHeaders ?? []).map((h) => citeComment(h)).join("") : "  // default (template)\n"}  defaultHeaders: ${lit(headers)},\n`,
      `${citeComment(o.timeoutMs)}  timeoutMs: ${o.timeoutMs?.value ?? DEFAULTS.api.timeoutMs},\n`,
      `${o.auth ? citeComment(o.auth) : cfg.api?.auth_header ? "  // the run-config's api.auth_header\n" : "  // default (template)\n"}  auth: ${lit(auth)},\n`,
      `  // the run-config's authorizations.identities (file paths only)\n  identities: ${lit(identities)},\n`,
    ].join("");
    values.notes = notesMd(o);
    values.requests = requestsMd(o);
  }
  if (side === "k6") {
    const auth = resolveAuth(cfg, o.auth, { k6: true });
    const { env: _env, ...k6auth } = auth;
    const headers = { ...DEFAULTS.k6.defaultHeaders, ...Object.fromEntries((o.defaultHeaders ?? []).map((h) => [h.name, h.value])) };
    values.entries = [
      `${o.auth ? citeComment(o.auth) : cfg.api?.auth_header ? "  // the run-config's api.auth_header\n" : "  // default (template)\n"}  auth: ${lit(k6auth)},\n`,
      `${o.basePath ? citeComment(o.basePath) : "  // default (template)\n"}  basePath: ${lit(o.basePath?.path ?? "")},\n`,
      `${(o.defaultHeaders ?? []).length ? (o.defaultHeaders ?? []).map((h) => citeComment(h)).join("") : "  // default (template)\n"}  defaultHeaders: ${lit(headers)},\n`,
    ].join("");
  }
  return values;
}

// The versions already in a package.json, by name (the lockfile's world: never bumped by a re-render).
function versionsIn(text) {
  const pkg = (() => {
    try {
      return JSON.parse(text);
    } catch {
      return null;
    }
  })();
  return { ...(pkg?.devDependencies ?? {}), ...(pkg?.dependencies ?? {}) };
}
const sortKeys = (o) => Object.fromEntries(Object.entries(o).sort(([a], [b]) => a.localeCompare(b)));

function renderPackage(text, ctx, overlay) {
  const pkg = JSON.parse(text);
  const existing = existsSync(path.join(ctx.pwProject, "package.json")) ? versionsIn(readFileSync(path.join(ctx.pwProject, "package.json"), "utf8")) : {};
  const dev = { ...(pkg.devDependencies ?? {}) };
  const deps = { ...(pkg.dependencies ?? {}) };
  for (const r of overlay.requests ?? []) if (r.kind === "dependency") (r.dev === false ? deps : dev)[r.name] = "*";
  const pin = (o) => sortKeys(Object.fromEntries(Object.keys(o).map((k) => [k, existing[k] ?? "*"])));
  const out = { ...pkg, ...(Object.keys(deps).length ? { dependencies: pin(deps) } : {}), devDependencies: pin(dev) };
  return JSON.stringify(out, null, 2) + "\n";
}

// package.json with every dependency version blanked and the dependency maps sorted: what the drift check compares.
export function normalizePackage(text) {
  let pkg;
  try {
    pkg = JSON.parse(text);
  } catch {
    return `unparsable:${text}`;
  }
  for (const k of ["dependencies", "devDependencies", "optionalDependencies", "peerDependencies"])
    if (pkg[k] && typeof pkg[k] === "object") pkg[k] = sortKeys(Object.fromEntries(Object.keys(pkg[k]).map((n) => [n, ""])));
  return JSON.stringify(pkg, null, 2);
}
const normalized = (target, text) => (target === "package.json" ? normalizePackage(text) : text);
export const contentHash = (target, text) => sha(normalized(target, text));

// -> {files: Map target -> {template, content}, seeds: Map target -> content, problems}. Writes nothing.
export function renderSide(ctx, side, overlay) {
  const t = templatesOf(side, ctx.templatesRoot);
  const values = valuesFor(ctx, side, overlay ?? {});
  const overlayRel = rel(ctx.root, ctx.fp.overlay(side));
  const files = new Map();
  for (const { template, target } of t.managed) {
    let text = fill(readTemplate(path.join(ctx.templatesRoot, template)), values, template);
    if (side === "ui" && target === "fixtures/ui/auth.setup.ts") {
      const part = text.includes("{{login}}") ? "login" : "noLogin";
      const body = fill(t.parts[part === "login" ? "login" : "no-login"], values, `${TEMPLATE_DIRS.ui}/_parts/${part}`);
      text = text.replace(`{{${part}}}`, () => body);
    }
    if (target === "package.json") text = renderPackage(text, ctx, overlay ?? {});
    files.set(target, { template, content: withHeader(target, template, text, overlayRel, ctx.product, side) });
  }
  if (side === "repo") {
    const json = [...files.keys()].filter((f) => f.endsWith(".json")).sort();
    const sidecar = {
      generatedBy: `${HEADER} Rendered from ${TEMPLATE_DIRS.repo} by: node scripts/foundation.mjs render ${ctx.product} --side repo`,
      why: "JSON can't hold a comment, so this record marks the managed JSON files. node scripts/foundation.mjs check fails when one is hand-edited.",
      files: Object.fromEntries(json.map((f) => [f, { template: files.get(f).template, checked: f === "package.json" ? "everything except the dependency versions (package-lock.json pins them)" : "everything" }])),
      unchecked: ["package-lock.json"],
    };
    files.set(SIDECAR, { template: TEMPLATE_DIRS.repo, content: JSON.stringify(sidecar, null, 2) + "\n" });
  }
  const seeds = new Map([...t.seeds.map((s) => [s.target, readTemplate(path.join(ctx.templatesRoot, s.template))]), ...KEEP[side].map((k) => [k, ""])]);
  return { files, seeds };
}

function configInputs(ctx, side) {
  const cfg = ctx.cfg;
  const pick = {
    repo: { product: ctx.product, authEnv: cfg.api?.auth_header?.env ?? null },
    ui: { product: ctx.product, target: hostOf(cfg.target?.url) },
    api: { product: ctx.product, authHeader: cfg.api?.auth_header ?? null, identities: cfg.authorizations?.identities ?? [] },
    k6: { product: ctx.product, authHeader: cfg.api?.auth_header ?? null },
  }[side];
  return sha(JSON.stringify(pick));
}

// The side's current stamp: the overlay, the templates, the run-config inputs and every managed file (package.json
// without its versions). -> {name: hash}
export function currentStamp(ctx, side) {
  const project = projectOf(ctx, side);
  const stamp = { overlay: sha256(ctx.fp.overlay(side)), templates: templatesHash(side, ctx.templatesRoot), config: configInputs(ctx, side) };
  for (const target of managedTargets(side, ctx.templatesRoot)) {
    const file = path.join(project, target);
    stamp[`file:${target}`] = existsSync(file) ? contentHash(target, readFileSync(file, "utf8")) : null;
  }
  return stamp;
}

// null when the side's verified stamp matches what is on disk, else why not (for the domain flows and the stage).
export function foundationUnverified(ctx, side) {
  const m = readJson(ctx.fp.manifest(side));
  const cmd = `node scripts/foundation.mjs render ${ctx.product} --side ${side}, then check`;
  if (!m) return `the ${side} foundation was never rendered (${cmd})`;
  if (!m.verified) return `the ${side} foundation never passed foundation.mjs check (${cmd})`;
  const now = currentStamp(ctx, side);
  const stale = [...new Set([...Object.keys(now), ...Object.keys(m.verified)])].filter((k) => now[k] !== m.verified[k]);
  return stale.length ? `the ${side} foundation changed after its check: ${stale.slice(0, 6).join(", ")}${stale.length > 6 ? ", ..." : ""}` : null;
}

// Writes the side's managed files (only those that differ), the seeds that are missing, and the manifest.
// -> {written, unchanged, seeded}
export function writeSide(ctx, side, rendered) {
  const project = projectOf(ctx, side);
  const written = [];
  let unchanged = 0;
  for (const [target, { content }] of rendered.files) {
    const file = path.join(project, target);
    if (existsSync(file) && readFileSync(file, "utf8") === content) {
      unchanged++;
      continue;
    }
    writeAtomic(file, content);
    written.push(target);
  }
  // fixtures/<side>/index.ts: generated from the module registrations, kept out of the side's stamp (it follows the
  // modules' builds, not the templates)
  const index = side === "ui" || side === "api" ? writeIndex(project, side, ctx.fp.dir) : { written: false, legacy: null };
  if (index.written) written.push(INDEX_TARGET(side));
  const seeded = [];
  for (const [target, content] of rendered.seeds) {
    const file = path.join(project, target);
    if (existsSync(file)) continue;
    writeAtomic(file, content);
    seeded.push(target);
  }
  const old = readJson(ctx.fp.manifest(side), {});
  const manifest = {
    side,
    project: rel(ctx.root, project),
    overlay: rel(ctx.root, ctx.fp.overlay(side)),
    files: [...rendered.files].map(([target, { template, content }]) => ({ path: target, template, sha256: contentHash(target, content) })),
    extensions: EXTENSIONS[side],
    verified: old?.verified ?? null,
  };
  const text = JSON.stringify(manifest, null, 2) + "\n";
  if (!existsSync(ctx.fp.manifest(side)) || readFileSync(ctx.fp.manifest(side), "utf8") !== text) writeAtomic(ctx.fp.manifest(side), text);
  return { written, unchanged, seeded, legacyIndex: index.legacy };
}

// Managed files whose disk content differs from a fresh render (package.json without its versions; package-lock.json
// never). -> [{file, problem}]
export function driftProblems(ctx, side, rendered) {
  const project = projectOf(ctx, side);
  const out = [];
  for (const [target, { content }] of rendered.files) {
    const file = path.join(project, target);
    if (!existsSync(file)) out.push({ file: target, problem: `${target} is missing: run node scripts/foundation.mjs render ${ctx.product} --side ${side}` });
    else if (contentHash(target, readFileSync(file, "utf8")) !== contentHash(target, content))
      out.push({ file: target, problem: `${target} was hand-edited: it differs from its render of ${rendered.files.get(target).template}. Managed files are never edited: change the ${side} overlay and re-render` });
  }
  return out;
}

