// validate: async (schema, data) -> string[] (lib/contract.mjs validateData).
async function loadValid(ctx, side, validate) {
  const r = readOverlay(ctx, side);
  if (r.error) return { problems: [r.error] };
  const schemaErrors = r.exists ? await validate(`foundation-${side}-overlay`, r.overlay) : [];
  if (schemaErrors.length) return { problems: schemaErrors.map((e) => `${side}-overlay.json: ${e}`) };
  return { overlay: r.overlay, problems: overlayProblems(ctx, side, r.overlay) };
}

export async function render(ctx, side, validate) {
  const { overlay, problems } = await loadValid(ctx, side, validate);
  if (problems.length) return { code: 1, out: { side, rendered: false, problems } };
  const rendered = renderSide(ctx, side, overlay);
  const w = writeSide(ctx, side, rendered);
  return { code: 0, out: { side, rendered: true, project: rel(ctx.root, projectOf(ctx, side)), written: w.written, unchanged: w.unchanged, seeded: w.seeded, ...(w.legacyIndex ? { note: `fixtures/${side}/index.ts is now generated from the module registrations (D-056): the previous hand-written one is kept in ${rel(ctx.root, w.legacyIndex)}; rebuild each module's code (ui-code.mjs or api-code.mjs build) to register its fixtures again` } : {}), manifest: rel(ctx.root, ctx.fp.manifest(side)) } };
}

// Every rule; with compile on, also the compile checks. A full pass stamps the manifest's `verified`.
export async function check(ctx, side, validate, { compile = true, exec } = {}) {
  const { overlay, problems } = await loadValid(ctx, side, validate);
  const out = [...problems];
  if (!existsSync(ctx.fp.manifest(side))) out.push(`the ${side} foundation was never rendered: run node scripts/foundation.mjs render ${ctx.product} --side ${side}`);
  if (overlay) {
    const rendered = renderSide(ctx, side, overlay);
    out.push(...driftProblems(ctx, side, rendered).map((d) => d.problem));
    out.push(...ruleProblems(ctx, side, overlay));
  }
  if (!out.length && compile) out.push(...compileProblems(ctx, side, exec));
  // A full pass stamps the manifest; any failure clears the stamp, so the flows and the stage refuse the side.
  const stamped = !out.length && compile;
  const m = readJson(ctx.fp.manifest(side));
  if (m && (stamped || (out.length && m.verified))) {
    m.verified = stamped ? currentStamp(ctx, side) : null;
    writeAtomic(ctx.fp.manifest(side), JSON.stringify(m, null, 2) + "\n");
  }
  return { valid: !out.length, side, stamped, ...(compile ? {} : { note: "--static: the compile checks did not run, so nothing was stamped" }), problems: out };
}

// npm install (the lockfile pins what it resolves) and the Playwright browser, in the Playwright project.
export function install(ctx, exec = (c, a, d) => runCommand(c, a, d, { timeout: 900_000 })) {
  if (!existsSync(path.join(ctx.pwProject, "package.json"))) return { code: 1, out: { problems: [`render the repo side first: node scripts/foundation.mjs render ${ctx.product} --side repo`] } };
  const problems = [];
  const npm = exec("npm", ["install"], ctx.pwProject);
  if (npm) problems.push(`npm install failed: ${npm}`);
  else {
    const pw = exec("npx", ["playwright", "install", "chromium"], ctx.pwProject);
    if (pw) problems.push(`npx playwright install chromium failed: ${pw}`);
  }
  return { code: problems.length ? 1 : 0, out: { installed: !problems.length, lockfile: existsSync(path.join(ctx.pwProject, "package-lock.json")), problems } };
}

