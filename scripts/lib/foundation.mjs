// Runs a command; null on success, else the first lines of its output.
export function runCommand(cmd, args, cwd, { timeout = 300_000 } = {}) {
  try {
    execFileSync(cmd, args, { cwd, stdio: "pipe", encoding: "utf8", shell: process.platform === "win32", timeout });
    return null;
  } catch (e) {
    const out = `${e.stdout ?? ""}${e.stderr ?? ""}`.trim() || e.message;
    return out.split(/\r?\n/).slice(0, 8).join(" / ");
  }
}

export const K6_CHECK_FILE = ".foundation-check.js";

// The compile checks: tsc and Playwright's --list (pw sides), or k6 inspect of a script-owned temp file that imports
// every lib file (k6). exec(cmd, args, cwd) -> null | error text. -> string[]
export function compileProblems(ctx, side, exec = runCommand) {
  const out = [];
  if (side === "k6") {
    const lib = walk(path.join(ctx.k6Project, "lib")).filter((f) => f.endsWith(".js"));
    const temp = path.join(ctx.k6Project, K6_CHECK_FILE);
    const text = [
      "// Written and deleted by scripts/foundation.mjs check: k6 inspect of every lib file.",
      ...lib.map((f, i) => `import * as lib${i} from './lib/${f}';`),
      `export const options = { vus: 1, iterations: 1 };`,
      `export default function () { return [${lib.map((_, i) => `lib${i}`).join(", ")}].length; }`,
      "",
    ].join("\n");
    writeFileSync(temp, text);
    try {
      const err = exec("k6", ["inspect", K6_CHECK_FILE], ctx.k6Project);
      if (err) out.push(`k6 inspect of the lib failed: ${err}`);
    } finally {
      try {
        unlinkSync(temp);
      } catch {}
    }
    return out;
  }
  const tsc = exec("npx", ["tsc", "--noEmit"], ctx.pwProject);
  if (tsc) out.push(`npx tsc --noEmit failed: ${tsc}`);
  const list = exec("npx", ["playwright", "test", "--list", "--pass-with-no-tests", ...(side === "repo" ? [] : [`--project=${side}`])], ctx.pwProject);
  if (list) out.push(`npx playwright test --list${side === "repo" ? "" : ` --project=${side}`} failed: ${list}`);
  return out;
}

