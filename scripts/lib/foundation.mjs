// The login form the UI overlay names: a state of the module's exploration model (D-052) whose snapshot the entry
// cites and shows the three controls verbatim, on the target's host, with no sign of CAPTCHA or MFA.
// -> {problems, path}
export function loginForm(ctx, login) {
  const where = "ui-overlay.json login";
  const problems = citeProblems(ctx, where, login);
  if (problems.length) return { problems };
  const moduleDir = path.join(ctx.productDir, "modules", login.module);
  const model = readJson(path.join(moduleDir, "explore", "model.json"));
  const state = model?.states?.find((s) => s.id === login.state);
  if (!state) return { problems: [`${where}: ${login.state} is not a state of ${login.module}'s exploration model (explore/model.json): a credential login needs a recorded login form`] };
  const cite = `observation:explore/${state.snapshot}`;
  if (!login.cite.includes(cite)) return { problems: [`${where}: cite the state's own snapshot, ${cite}`] };
  const file = path.join(moduleDir, "explore", state.snapshot);
  if (!existsSync(file)) return { problems: [`${where}: ${state.snapshot} is missing`] };
  const text = readFileSync(file, "utf8");
  const tree = parseSnapshot(text);
  const roles = { username: ["textbox", "combobox"], password: ["textbox"], submit: ["button"] };
  for (const [k, ok] of Object.entries(roles)) {
    const sel = login[k];
    if (!ok.includes(sel.role)) problems.push(`${where}: ${k} must be a ${ok.join(" or ")}, not ${sel.role}`);
    else if (!hasNode(tree, sel)) problems.push(`${where}: ${k} ${sel.role} "${sel.name}" is not in ${state.snapshot}: the selectors are the snapshot's own roles and names`);
  }
  if (login.username.name === login.password.name) problems.push(`${where}: username and password name the same control`);
  if (LOGIN_BLOCKERS.test(text)) problems.push(`${where}: ${state.snapshot} shows CAPTCHA or MFA, so it is not a plain login form: no credential login is generated; a human provides STORAGE_STATE`);
  const target = hostOf(ctx.cfg.target?.url);
  const at = hostOf(state.url);
  if (at && target && at !== target) problems.push(`${where}: the login form is on ${at}, not the target's host ${target} (single sign-on): a human provides STORAGE_STATE`);
  let loginPath = "/";
  try {
    const u = new URL(state.url);
    loginPath = u.pathname || "/";
  } catch {
    if (String(state.url).startsWith("/")) loginPath = String(state.url).split(/[?#]/)[0];
  }
  return { problems, path: loginPath, state };
}

// Text values an overlay renders must not carry a credential or token.
function secretProblems(where, value) {
  const out = [];
  const visit = (v, at) => {
    if (typeof v === "string") {
      if (SECRET_RES.some((re) => re.test(v))) out.push(`${where}${at}: looks like a credential or token: overlays name variables, never values`);
    } else if (Array.isArray(v)) v.forEach((x, i) => visit(x, `${at}[${i}]`));
    else if (v && typeof v === "object") for (const [k, x] of Object.entries(v)) visit(x, `${at}.${k}`);
  };
  visit(value, "");
  return out;
}

function numberProblem(where, entry, min, max) {
  const v = entry?.value;
  return typeof v === "number" && Number.isInteger(v) && v >= min && v <= max ? null : `${where}: value must be an integer from ${min} to ${max}`;
}

function authProblems(ctx, where, auth, { k6 = false } = {}) {
  if (!auth) return [];
  const out = citeProblems(ctx, where, auth);
  if (auth.header !== undefined && auth.header !== null && !HEADER_NAME_RE.test(auth.header)) out.push(`${where}: header must be a header name`);
  if (!k6 && auth.env !== undefined && auth.env !== null && !ENV_NAME_RE.test(auth.env)) out.push(`${where}: env must be a variable NAME (A-Z, 0-9, _), never a value`);
  if (auth.prefix !== undefined && !/^[A-Za-z -]{0,20}$/.test(auth.prefix)) out.push(`${where}: prefix is a scheme word such as "Bearer ", never a credential`);
  if (auth.scheme === "api-key" && !(auth.header ?? ctx.cfg.api?.auth_header?.name)) out.push(`${where}: an api-key scheme needs its header name`);
  // A citation of the endpoint catalogue must match it: some endpoint there uses this scheme.
  if (auth.module && auth.cite?.includes("spec:discovered-endpoints.json")) {
    const cat = readJson(path.join(ctx.productDir, "modules", auth.module, "api", "discovered-endpoints.json"), []);
    if (Array.isArray(cat) && !cat.some((e) => e.auth === auth.scheme)) out.push(`${where}: no endpoint of ${auth.module}'s discovered-endpoints.json uses auth '${auth.scheme}'`);
  }
  return out;
}

function headerProblems(ctx, where, headers) {
  const out = [];
  (headers ?? []).forEach((h, i) => {
    const w = `${where}[${i}]`;
    out.push(...citeProblems(ctx, w, h));
    if (!HEADER_NAME_RE.test(h.name ?? "")) out.push(`${w}: name must be a header name`);
    else if (AUTH_HEADER_RE.test(h.name)) out.push(`${w}: ${h.name} carries credentials: only the auth scheme sets it, from a variable NAME (auth.env), never a default header`);
    if (URL_RE.test(h.value ?? "") || PROTOCOL_RELATIVE.test(`'${h.value ?? ""}`)) out.push(`${w}: a default header never holds a URL`);
    if (looksLikeSecret(String(h.value ?? ""))) out.push(`${w}: the value looks like a key or token: a default header holds no secret; credentials come from a variable NAME through the auth scheme`);
  });
  return out;
}

const pathProblem = (where, p) => (typeof p === "string" && /^\/[^\s?#]*$/.test(p) && !URL_RE.test(p) ? null : `${where}: path must start with / and hold no host, query or spaces`);

// Extension requests (gaps, missing exports): each names the extension files it was resolved in and their exports.
function requestProblems(ctx, side, overlay) {
  const out = [];
  const managed = new Set(managedTargets(side, ctx.templatesRoot));
  (overlay.requests ?? []).forEach((r, i) => {
    const where = `${side}-overlay.json requests[${i}]`;
    out.push(...citeProblems(ctx, where, r));
    for (const f of r.files ?? []) {
      if (managed.has(f) || !EXTENSIONS[side].some((g) => globMatch(g, f))) out.push(`${where}: ${f} is not an extension file of the ${side} side (${EXTENSIONS[side].join(", ")})`);
    }
  });
  return out;
}

function globMatch(glob, file) {
  const re = glob.split(/(\*\*|\*)/).map((p) => (p === "**" ? ".*" : p === "*" ? "[^/]*" : p.replace(/[.+?^${}()|[\]\\]/g, "\\$&"))).join("");
  return new RegExp(`^${re}$`).test(file);
}

// Semantic problems of an overlay that passed its schema. -> string[]
export function overlayProblems(ctx, side, overlay) {
  const out = [];
  const o = overlay ?? {};
  if (side === "repo") {
    (o.requests ?? []).forEach((r, i) => {
      const where = `repo-overlay.json requests[${i}] (${r.kind})`;
      out.push(...citeProblems(ctx, where, r));
      if (r.kind === "dependency" && !NPM_NAME_RE.test(r.name ?? "")) out.push(`${where}: a dependency is a plain npm package name: no version, URL, git or file spec (the lockfile pins versions)`);
      if (r.kind === "env" && !ENV_NAME_RE.test(r.name ?? "")) out.push(`${where}: an env request names a variable (A-Z, 0-9, _); it never carries a value`);
      if (r.kind === "gitignore") {
        const p = String(r.pattern ?? "");
        if (!p.trim() || /[\r\n]/.test(p)) out.push(`${where}: one non-empty pattern`);
        if (p.trim().startsWith("!")) out.push(`${where}: refused: a negated pattern would un-ignore files (.env, .auth/ and secrets stay ignored)`);
      }
      if (r.kind === "config") {
        const spec = CONFIG_KEYS[r.name];
        if (!spec) out.push(`${where}: refused: '${r.name}' is not a configurable value (${Object.keys(CONFIG_KEYS).join(", ")}); grepInvert, the env configuration and secrets never change`);
        else if (spec.type === "boolean" ? typeof r.value !== "boolean" : !(Number.isInteger(r.value) && r.value >= spec.min && r.value <= spec.max))
          out.push(`${where}: ${r.name} must be ${spec.type === "boolean" ? "true or false" : `an integer from ${spec.min} to ${spec.max}`}`);
      }
    });
  }
  if (side === "ui") {
    const s = o.settings ?? {};
    for (const [k, [min, max]] of Object.entries({ actionTimeoutMs: [1000, 120000], navigationTimeoutMs: [1000, 300000] }))
      if (s[k]) out.push(...citeProblems(ctx, `ui-overlay.json settings.${k}`, s[k]), ...[numberProblem(`ui-overlay.json settings.${k}`, s[k], min, max)].filter(Boolean));
    if (s.viewport) out.push(...citeProblems(ctx, "ui-overlay.json settings.viewport", s.viewport));
    for (const k of ["loadingIndicator", "cookieBanner"]) if (s[k]) out.push(...selectorProblems(ctx, `ui-overlay.json settings.${k}`, s[k]));
    if (o.login) out.push(...loginForm(ctx, o.login).problems);
  }
  if (side === "api") {
    (o.basePaths ?? []).forEach((b, i) => {
      const where = `api-overlay.json basePaths[${i}]`;
      out.push(...citeProblems(ctx, where, b));
      const bad = pathProblem(where, b.path);
      if (bad) out.push(bad);
      else if (b.module && b.cite?.includes("spec:discovered-endpoints.json")) {
        const cat = readJson(path.join(ctx.productDir, "modules", b.module, "api", "discovered-endpoints.json"), []);
        const norm = (p) => String(p ?? "").replace(/\/+$/, "");
        if (Array.isArray(cat) && !cat.some((e) => norm(e.basePath) === norm(b.path))) out.push(`${where}: no endpoint of ${b.module}'s discovered-endpoints.json has basePath ${b.path}`);
      }
    });
    const names = (o.basePaths ?? []).map((b) => b.name);
    if (new Set(names).size !== names.length) out.push("api-overlay.json basePaths: names must be unique");
    out.push(...authProblems(ctx, "api-overlay.json auth", o.auth));
    out.push(...headerProblems(ctx, "api-overlay.json defaultHeaders", o.defaultHeaders));
    if (o.timeoutMs) out.push(...citeProblems(ctx, "api-overlay.json timeoutMs", o.timeoutMs), ...[numberProblem("api-overlay.json timeoutMs", o.timeoutMs, 1000, 300000)].filter(Boolean));
  }
  if (side === "k6") {
    out.push(...authProblems(ctx, "k6-overlay.json auth", o.auth, { k6: true }));
    if (o.basePath) {
      out.push(...citeProblems(ctx, "k6-overlay.json basePath", o.basePath));
      const bad = pathProblem("k6-overlay.json basePath", o.basePath.path);
      if (bad) out.push(bad);
    }
    out.push(...headerProblems(ctx, "k6-overlay.json defaultHeaders", o.defaultHeaders));
  }
  (o.notes ?? []).forEach((n, i) => out.push(...citeProblems(ctx, `${side}-overlay.json notes[${i}]`, n)));
  if (side !== "repo") out.push(...requestProblems(ctx, side, o));
  out.push(...secretProblems(`${side}-overlay.json`, o));
  return out;
}

