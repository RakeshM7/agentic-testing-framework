export function readOverlay(ctx, side) {
  const file = ctx.fp.overlay(side);
  if (!existsSync(file)) return { overlay: {}, exists: false };
  try {
    return { overlay: JSON.parse(readFileSync(file, "utf8")), exists: true };
  } catch (e) {
    return { overlay: null, exists: true, error: `${rel(ctx.root, file)}: not valid JSON: ${e.message}` };
  }
}

const ctxCache = new WeakMap();
function citeCtx(ctx, module) {
  if (!ctxCache.has(ctx)) ctxCache.set(ctx, new Map());
  const cache = ctxCache.get(ctx);
  if (!cache.has(module)) {
    const moduleDir = path.join(ctx.productDir, "modules", module ?? "_none");
    const rows = module && existsSync(csvPath(ctx.productDir, module)) ? readRows(csvPath(ctx.productDir, module)) : [];
    const cov = module ? readJson(path.join(moduleDir, "testcases", "coverage.json"), {}) : {};
    cache.set(module, { rows, cases: new Set((cov?.cases ?? []).map((c) => c.id)), productDir: ctx.productDir, moduleDir });
  }
  return cache.get(module);
}

// Every value of an overlay names where it comes from; each citation is checked against the files (lib/citations.mjs).
function citeProblems(ctx, where, entry) {
  const cites = entry?.cite;
  if (!Array.isArray(cites) || !cites.length) return [`${where}: uncited: every overlay value names its source (observation:, spec:, knowledge:, clarification: or testcase:)`];
  const out = [];
  if (entry.module !== undefined && !(ctx.run?.modules ?? []).includes(entry.module)) return [`${where}: module '${entry.module}' is not a module of this run`];
  for (const c of cites) {
    const kind = String(c).split(":")[0];
    if (kind !== "knowledge" && !entry.module) {
      out.push(`${where}: '${c}' cites a module's file: name that module in "module"`);
      continue;
    }
    const why = citationProblem(c, citeCtx(ctx, entry.module));
    if (why) out.push(`${where}: ${why}`);
  }
  return out;
}

// Every node of a parsed accessibility snapshot.
function nodes(n, out = []) {
  for (const c of n.children ?? []) {
    out.push(c);
    nodes(c, out);
  }
  return out;
}
const hasNode = (tree, sel) => nodes(tree.root).some((n) => n.role === sel.role && n.name === sel.name);

// An observed selector (role + accessible name) must appear verbatim in an exploration snapshot the entry cites.
function selectorProblems(ctx, where, entry) {
  const out = citeProblems(ctx, where, entry);
  if (out.length) return out;
  const snaps = entry.cite.filter((c) => /^observation:explore\/.+\.md(#.*)?$/.test(c)).map((c) => c.slice("observation:".length).split("#")[0]);
  if (!snaps.length) return [`${where}: cite the exploration snapshot it was observed in (observation:explore/pages/<slug>/states/<ST>.md or .../dom-snapshot.md)`];
  const moduleDir = path.join(ctx.productDir, "modules", entry.module);
  if (!snaps.some((s) => hasNode(parseSnapshot(readFileSync(path.join(moduleDir, s), "utf8")), entry)))
    return [`${where}: ${entry.role} "${entry.name}" is not in ${snaps.join(", ")}: the role and name must be the snapshot's own`];
  return [];
}

