// What the pre-review gate checks between renders, once a side was rendered by the script (its manifest exists):
// the side's managed files (and, for a Playwright side, the repo's shared files) still equal their render, and the
// extension files keep the guard (fixtures/<side>/index.ts builds on ./base; no setup file but auth.setup.ts).
// -> [{file, problem}] (files relative to the project); [] when the side was never rendered by the script.
export function gateFoundationProblems(ctx, side) {
  const sides = side === "k6" ? ["k6"] : [side, "repo"];
  const out = [];
  for (const s of sides) {
    if (!existsSync(ctx.fp.manifest(s))) continue;
    const r = readOverlay(ctx, s);
    if (r.error || !r.overlay) {
      out.push({ file: rel(projectOf(ctx, s), ctx.fp.overlay(s)), problem: r.error ?? "unreadable overlay" });
      continue;
    }
    let rendered;
    try {
      rendered = renderSide(ctx, s, r.overlay);
    } catch (e) {
      out.push({ file: TEMPLATE_DIRS[s], problem: `the ${s} foundation can't be rendered: ${e.message}` });
      continue;
    }
    out.push(...driftProblems(ctx, s, rendered));
  }
  if (side !== "k6" && existsSync(ctx.fp.manifest(side))) {
    const project = ctx.pwProject;
    const why = indexProblem(project, side);
    if (why) out.push({ file: INDEX_TARGET(side), problem: why });
    for (const f of walk(path.join(project, "fixtures", side)))
      if (f.endsWith(".setup.ts") && f !== "auth.setup.ts") out.push({ file: `fixtures/${side}/${f}`, problem: "only the rendered auth.setup.ts may be a setup file (a setup project runs every *.setup.ts)" });
  }
  return out;
}

