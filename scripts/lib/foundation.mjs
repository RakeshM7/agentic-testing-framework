// The product-wide foundations, rendered from the framework's templates (docs/conventions.md "Script-built agents",
// variant A; decision D-054). Four sides, each owned by one agent that writes only a cited overlay:
//
//   side   project                   templates                  overlay (artifacts/<p>/foundation/)   agent
//   repo   playwright-tests/<p>/     templates/playwright/repo  repo-overlay.json                     pw-repo-owner
//   ui     playwright-tests/<p>/     templates/playwright/ui    ui-overlay.json                       pw-ui-scaffolder
//   api    playwright-tests/<p>/     templates/playwright/api   api-overlay.json                      pw-api-scaffolder
//   k6     k6-tests/<p>/             templates/k6               k6-overlay.json                       k6-lib-writer
