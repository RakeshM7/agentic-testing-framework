// null when a dependency version is a registry specifier: a semver range (`^1.2.3`, `>=1 <2`, `1.x || 2`, `*`, ""), or
// `latest` or another dist-tag; else why not.
export function registrySpecProblem(spec) {
  const s = String(spec ?? "").trim();
  if (typeof spec !== "string") return "a version must be a string";
  if (/[:/\\#@]/.test(s) || /\.(tgz|tar\.gz|tar)$/i.test(s)) return "only registry versions are allowed (a semver range, latest or a dist-tag), never a file:, link:, git, URL, tarball, alias or workspace specifier";
  const range = /^(?:[<>=~^]*\s*v?(?:\d+|[xX*])(?:\.(?:\d+|[xX*])){0,2}(?:-[0-9A-Za-z.-]+)?(?:\+[0-9A-Za-z.-]+)?|\*|)$/;
  const parts = s.split("||").flatMap((alt) => alt.trim().split(/\s+-\s+|\s+/)).filter(Boolean);
  if (!s || s === "*" || parts.every((p) => range.test(p))) return null;
  if (/^[a-z][a-z0-9._-]*$/i.test(s)) return null; // latest, next, beta: a dist-tag
  return "not a semver range or a dist-tag";
}

const isCommentLine =(l) => /^\s*(\/\/|\/?\*|#|<!--)/.test(l);
const codeLines = (text) => text.split(/\r?\n/).map((l, i) => ({ l, n: i + 1 })).filter(({ l }) => !isCommentLine(l));

// Hard-coded URLs, credentials and tokens in code files. -> string[]
export function literalProblems(project, files) {
  const out = [];
  for (const f of files) {
    const abs = path.join(project, f);
    if (!/\.(ts|js|mjs)$/.test(f) || !existsSync(abs)) continue;
    const lines = codeLines(readFileSync(abs, "utf8"));
    let urls = 0;
    for (const { l, n } of lines) {
      if (URL_RE.test(l) || PROTOCOL_RELATIVE.test(l) || SCHEME_PIECE.some((re) => re.test(l))) {
        urls++;
        out.push(`${f}:${n}: hard-coded URL: read it from the environment (BASE_URL / API_BASE_URL)`);
      }
      if (SECRET_RES.some((re) => re.test(l))) out.push(`${f}:${n}: hard-coded credential or token: read it from a variable the .env file holds`);
    }
    // A URL split into string pieces, joined with + (across lines too) or through ${'…'} in a template literal
    const joined = lines.map(({ l }) => l).join("\n").replace(/\$\{\s*(['"])([^'"\n]*)\1\s*\}/g, "$2").replace(/(['"`])\s*\+\s*(['"`])/g, "");
    // ... or an array holding a scheme piece that is joined, inline or through a variable
    const arrayJoin = SCHEME_ARRAY.test(joined) || (SCHEME_ELEMENT.test(joined) && /\.\s*join\s*\(/.test(joined));
    if (!urls && (URL_RE.test(joined) || PROTOCOL_RELATIVE.test(joined) || arrayJoin)) out.push(`${f}: hard-coded URL built from string pieces: read it from the environment (BASE_URL / API_BASE_URL)`);
  }
  return out;
}

const exportsOf = (text) =>
  new Set([
    ...[...text.matchAll(/\bexport\s+(?:async\s+)?(?:function\*?|const|let|var|class|type|interface|enum)\s+([A-Za-z_$][\w$]*)/g)].map((m) => m[1]),
    ...[...text.matchAll(/\bexport\s*\{([^}]*)\}/g)].flatMap((m) => m[1].split(",").map((s) => s.trim().split(/\s+as\s+/).pop()).filter(Boolean)),
  ]);

function listFiles(project, globs) {
  return walk(project).filter((f) => globs.some((g) => globMatch(g, f)));
}
export const extensionFiles = (ctx, side) => {
  const managed = new Set(managedTargets(side, ctx.templatesRoot));
  return listFiles(projectOf(ctx, side), EXTENSIONS[side]).filter((f) => !managed.has(f));
};

const safeMethods = (text) => {
  const m = /SAFE_METHODS\s*=\s*\[([^\]]*)\]/.exec(text ?? "");
  return m ? m[1].split(",").map((s) => s.trim().replace(/^['"`]|['"`]$/g, "").toUpperCase()).filter(Boolean).sort() : null;
};
const SAFE = ["GET", "HEAD", "OPTIONS"];
// An extension fixtures/<side>/index.ts must take `test` from ./base, and never `test` or `expect` from @playwright/test
// itself: not named, aliased, as a namespace or default import, re-exported, through require() or a dynamic import.
// Type-only imports (`import type { Page }`, `{ type Page }`) are fine. -> null, or why it bypasses the guard.
export function bypassesBase(raw) {
  const text = String(raw).replace(/\/\*[\s\S]*?\*\//g, "").replace(/(^|[^:'"`])\/\/.*$/gm, "$1");
  // `@playwright/test` or `playwright`, with any subpath (`@playwright/test/lib/index`, `playwright/test`)
  const PW = String.raw`['"\`](?:@playwright\/test|playwright)(?:\/[^'"\`]*)?['"\`]`;
  if (!new RegExp(String.raw`import\s*\{[^}]*\btest\b[^}]*\}\s*from\s*['"]\.\/base(\.ts)?['"]`).test(text)) return "it does not import { test } from './base'";
  for (const m of text.matchAll(new RegExp(String.raw`\b(import|export)\s+(type\s+)?((?:(?!\bfrom\b|\bimport\b|\bexport\b)[^;])*?)\s*from\s*${PW}`, "g"))) {
    if (m[2]) continue;
    const clause = m[3].trim();
    if (m[1] === "export" && /^\*/.test(clause)) return "it re-exports everything from @playwright/test";
    if (/\*\s*as\s+/.test(clause)) return "it imports @playwright/test as a namespace";
    if (m[1] === "import" && /^[A-Za-z_$]/.test(clause)) return "it takes the default import of @playwright/test";
    const names = (/\{([^}]*)\}/.exec(clause)?.[1] ?? "").split(",").map((s) => s.trim()).filter((s) => s && !/^type\s/.test(s)).map((s) => s.split(/\s+as\s+/)[0].trim());
    const bad = names.filter((n) => n === "test" || n === "expect");
    if (bad.length) return `it takes ${bad.join(" and ")} from @playwright/test`;
  }
  if (new RegExp(String.raw`\brequire\s*\(\s*${PW}\s*\)|\bimport\s*\(\s*${PW}\s*\)`).test(text)) return "it loads @playwright/test through require() or a dynamic import";
  return null;
}
const buildsOnBase = (text) => !bypassesBase(text);

// The rules a check enforces on what is on disk, whatever the drift check says (the guard, grepInvert, the k6 safety
// calls, the login, the extension files). -> string[]
export function ruleProblems(ctx, side, overlay) {
  const project = projectOf(ctx, side);
  const read = (f) => (existsSync(path.join(project, f)) ? readFileSync(path.join(project, f), "utf8") : null);
  const out = [];
  if (side === "repo") {
    // The versions stay out of the drift check, but each must come from the registry: a semver range, `latest` or a
    // dist-tag. Never a file:, link:, git, URL, tarball, alias or workspace specifier.
    const pkgText = read("package.json");
    let pkg = null;
    try {
      pkg = pkgText === null ? null : JSON.parse(pkgText);
    } catch {}
    for (const k of ["dependencies", "devDependencies", "optionalDependencies", "peerDependencies"])
      for (const [name, spec] of Object.entries(pkg?.[k] ?? {})) {
        const why = registrySpecProblem(spec);
        if (why) out.push(`package.json: ${k}.${name} is ${JSON.stringify(spec)}: ${why}`);
      }
    const conf = read("playwright.config.ts");
    if (conf !== null && (!/const fullRun = process\.env\.ATF_MODE === 'full-run';/.test(conf) || !/grepInvert: fullRun \? undefined : \/@mutates\/,/.test(conf) || (conf.match(/\bgrepInvert\b/g) ?? []).length !== 1 || /\bgrep\s*:/.test(conf)))
      out.push("playwright.config.ts: grepInvert is weakened: every @mutates test must be skipped unless ATF_MODE is full-run (grepInvert: fullRun ? undefined : /@mutates/)");
    const ignore = read(".gitignore");
    if (ignore !== null) {
      const lines = ignore.split(/\r?\n/).map((l) => l.trim());
      for (const must of ["node_modules/", ".env", ".auth/"]) if (!lines.includes(must)) out.push(`.gitignore: must ignore ${must}`);
      for (const l of lines) if (l.startsWith("!") && l !== "!.env.example") out.push(`.gitignore: '${l}' un-ignores files`);
    }
    const envEx = read(".env.example");
    if (envEx !== null) {
      const names = new Set();
      for (const { l, n } of codeLines(envEx)) {
        if (!l.trim()) continue;
        const m = /^([A-Z][A-Z0-9_]*)=(.*)$/.exec(l.trim());
        if (!m) out.push(`.env.example:${n}: one NAME= per line`);
        else {
          names.add(m[1]);
          if (m[2].trim()) out.push(`.env.example:${n}: ${m[1]} has a value: .env.example lists names only`);
        }
      }
      for (const n of ENV_NAMES) if (!names.has(n)) out.push(`.env.example: ${n} is missing`);
    }
  }
  if (side === "ui" || side === "api") {
    const base = read(`fixtures/${side}/base.ts`);
    if (base === null) out.push(`fixtures/${side}/base.ts is missing: the ${side === "ui" ? "mutation guard" : "readonly request guard"} fixture must exist`);
    else {
      const methods = safeMethods(base);
      if (!methods || methods.join() !== SAFE.join()) out.push(`fixtures/${side}/base.ts: the guard allows ${methods ? methods.filter((x) => !SAFE.includes(x)).join(", ") || "a changed method set" : "every method"} in readonly: only GET, HEAD and OPTIONS`);
      if (side === "ui") {
        if (!/mutationGuard\s*:\s*\[/.test(base) || !/\{\s*auto:\s*true\s*\}/.test(base)) out.push("fixtures/ui/base.ts: mutationGuard must be an auto fixture ({ auto: true }), so every UI test gets it");
        if (!/process\.env\.ATF_MODE !== 'full-run'/.test(base) || !/route\.abort\(/.test(base)) out.push("fixtures/ui/base.ts: the guard must abort non-safe requests whenever ATF_MODE is not full-run");
      } else {
        if (!/export function guarded\(/.test(base) || !/Mutation blocked: readonly run/.test(base) || !/process\.env\.ATF_MODE === 'full-run'/.test(base)) out.push("fixtures/api/base.ts: guarded() must throw 'Mutation blocked: readonly run' whenever ATF_MODE is not full-run");
        for (const f of ["api", "noAuth", "malformedAuth", "identity"]) {
          const body = new RegExp(`\\n  ${f}: async \\(([\\s\\S]*?)\\n  \\},`).exec(base)?.[1];
          if (!body || !/guarded\(ctx\)/.test(body)) out.push(`fixtures/api/base.ts: the ${f} fixture must hand out a guarded() context`);
        }
      }
    }
    const index = indexProblem(project, side);
    if (index) out.push(index);
    for (const f of walk(path.join(project, "fixtures", side))) if (f.endsWith(".setup.ts") && f !== "auth.setup.ts") out.push(`fixtures/${side}/${f}: only the rendered auth.setup.ts may be a setup file`);
    if (side === "ui") {
      const setup = read("fixtures/ui/auth.setup.ts");
      const cited = overlay?.login && !loginForm(ctx, overlay.login).problems.length;
      if (setup !== null && /LOGIN_PASSWORD|\.fill\(/.test(setup) && !cited) out.push("fixtures/ui/auth.setup.ts logs in with credentials, but the UI overlay cites no recorded plain login form (login.state and its snapshot)");
    }
    if (side === "api" && read("helpers/api/schema.ts") !== null && !exportsOf(read("helpers/api/schema.ts")).has("validateSchema")) out.push("helpers/api/schema.ts must export validateSchema");
  }
  if (side === "k6") {
    const conf = read("lib/config.js");
    if (conf === null) out.push("lib/config.js is missing: the k6 lib must provide assertAllowedHost and requireFullRun");
    else {
      const ex = exportsOf(conf);
      for (const f of ["assertAllowedHost", "requireFullRun"]) if (!ex.has(f)) out.push(`lib/config.js does not export ${f}: every script calls it in setup()`);
      if (/BASE_URL\s*=\s*__ENV\.BASE_URL\s*(\|\||\?\?)/.test(conf)) out.push("lib/config.js gives BASE_URL a default: there is none");
      if (!/K6_ALLOWED_HOSTS/.test(conf)) out.push("lib/config.js must read K6_ALLOWED_HOSTS");
    }
  }
  // Hard-coded URLs and credentials, in the side's managed and extension code.
  const files = [...managedTargets(side, ctx.templatesRoot), ...extensionFiles(ctx, side)];
  out.push(...literalProblems(project, files));
  // Extension requests: every export a request lists is still exported by its files (a gap extends, never breaks).
  (overlay?.requests ?? []).forEach((r, i) => {
    if (side === "repo") return;
    const texts = (r.files ?? []).map((f) => read(f));
    (r.files ?? []).forEach((f, j) => {
      if (texts[j] === null) out.push(`${side}-overlay.json requests[${i}]: ${f} does not exist`);
    });
    const ex = new Set(texts.filter(Boolean).flatMap((t) => [...exportsOf(t)]));
    for (const e of r.exports ?? []) if (!ex.has(e)) out.push(`${side}-overlay.json requests[${i}]: ${e} is not exported by ${(r.files ?? []).join(", ") || "any file"}`);
  });
  return out;
}

