// ---------- fixtures/<side>/index.ts: generated from the module registrations (D-056) ----------

// fixtures/<side>/index.ts is a managed file on both sides: ./base's `test` extended with every module's generated
// registration (fixtures/ui/pages/<m>.ts from ui-code.mjs, fixtures/api/clients/<m>.ts from api-code.mjs), plus ./base's
// `expect` (and waitForReady on the UI side). This one function renders it, for foundation.mjs render and for the two
// code scripts' builds, from the registration files on disk in name order, so whichever writes it writes the same bytes.
export const INDEX_TARGET = (side) => `fixtures/${side}/index.ts`;
export const REGISTRATION_DIR = { ui: "pages", api: "clients" };
const REGISTRATION_BY = { ui: "scripts/ui-code.mjs", api: "scripts/api-code.mjs" };
export function renderIndex(project, side) {
  const dir = path.join(project, "fixtures", side, REGISTRATION_DIR[side]);
  const regs = [];
  for (const f of existsSync(dir) ? readdirSync(dir).filter((x) => x.endsWith(".ts")).sort() : []) {
    const text = readFileSync(path.join(dir, f), "utf8");
    if (!text.startsWith(`// Generated by ${REGISTRATION_BY[side]} — do not edit.`)) continue; // only a generated registration
    const type = /^export type ([A-Za-z_$][\w$]*) = \{/m.exec(text)?.[1];
    const value = /^export const ([A-Za-z_$][\w$]*) = \{/m.exec(text)?.[1];
    if (type && value) regs.push({ module: f.slice(0, -3), type, value });
  }
  const L = [
    `// ${HEADER} The ${side} side's test: ./base extended with every module's generated fixtures`,
    `// (fixtures/${side}/${REGISTRATION_DIR[side]}/*.ts, written by ${REGISTRATION_BY[side]}). Rebuilt by foundation.mjs render --side ${side} and by`,
    `// ${REGISTRATION_BY[side].replace("scripts/", "")} build (D-056); the guard lives in ./base. Never edit it: a fixture is a module's generated registration.`,
    "import { test as base } from './base';",
    ...regs.map((r) => `import { ${r.value}, type ${r.type} } from './${REGISTRATION_DIR[side]}/${r.module}';`),
    "",
    regs.length ? `export const test = base.extend<${regs.map((r) => r.type).join(" & ")}>({ ${regs.map((r) => `...${r.value}`).join(", ")} });` : "export const test = base;",
    "",
    `export { ${side === "ui" ? "expect, waitForReady" : "expect"} } from './base';`,
    "",
  ];
  return L.join("\n");
}
// Writes the index when it differs. A previous index that was not generated (hand-written before D-056) is kept in
// legacyDir/<side>-index.legacy.ts first. -> {written: bool, legacy: path | null}
export function writeIndex(project, side, legacyDir) {
  const file = path.join(project, INDEX_TARGET(side));
  const want = renderIndex(project, side);
  const have = existsSync(file) ? readFileSync(file, "utf8").replace(/\r\n?/g, "\n") : null;
  if (have === want) return { written: false, legacy: null };
  let legacy = null;
  if (have !== null && !have.startsWith(`// ${HEADER}`) && legacyDir) {
    legacy = path.join(legacyDir, `${side}-index.legacy.ts`);
    if (!existsSync(legacy)) writeAtomic(legacy, have);
  }
  writeAtomic(file, want);
  return { written: true, legacy };
}
// Why fixtures/<side>/index.ts is not its render, or null.
export function indexProblem(project, side) {
  const file = path.join(project, INDEX_TARGET(side));
  if (!existsSync(file)) return `${INDEX_TARGET(side)} is missing: it is generated (foundation.mjs render --side ${side}, or the module's build)`;
  return readFileSync(file, "utf8").replace(/\r\n?/g, "\n") === renderIndex(project, side) ? null : `${INDEX_TARGET(side)} differs from its render: it is generated from the module registrations (D-056) and never edited; run foundation.mjs render --side ${side} or the module's build`;
}

