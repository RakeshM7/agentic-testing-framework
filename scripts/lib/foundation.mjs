// Files under dir (relative, forward slashes, sorted), skipping dependency and output folders.
const SKIP_DIRS = new Set(["node_modules", ".auth", "test-results", "playwright-report", "blob-report", ".git"]);
function walk(dir, base = dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .sort()
    .flatMap((f) => {
      const abs = path.join(dir, f);
      if (!statSync(abs).isDirectory()) return [rel(base, abs)];
      return SKIP_DIRS.has(f) ? [] : walk(abs, base);
    });
}
const targetOf = (t) =>
  t
    .replace(/\.(tpl|seed)$/, "")
    .split("/")
    .map((s) => (s === "_gitignore" ? ".gitignore" : s === "_env.example" ? ".env.example" : s))
    .join("/");

// -> {managed: [{template, target}], seeds: [{template, target}], parts: {name: text}}
export function templatesOf(side, root = repoRoot) {
  const dir = path.join(root, TEMPLATE_DIRS[side]);
  const files = walk(dir);
  const at = (t) => ({ template: `${TEMPLATE_DIRS[side]}/${t}`, target: targetOf(t) });
  return {
    managed: files.filter((f) => f.endsWith(".tpl") && !f.startsWith("_parts/")).map(at),
    seeds: files.filter((f) => f.endsWith(".seed")).map(at),
    parts: Object.fromEntries(files.filter((f) => f.startsWith("_parts/")).map((f) => [path.posix.basename(f).replace(/\.part$/, ""), readTemplate(path.join(dir, f))])),
  };
}

