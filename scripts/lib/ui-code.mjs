// The plan and the ledger from the approved cases and the exploration. -> {plan, ledger, warnings, approvals}
export function derivePlan(ctx) {
  const { module } = ctx;
  const tc = readJson(ctx.tp.coverage, null);
  const model = readJson(ctx.xp.model, null);
  const cases = (tc?.cases ?? []).slice().sort((a, b) => byNum(a.id, b.id));
  const itemsById = new Map((tc?.items ?? []).map((i) => [i.id, i]));
  const status = approvalStatus(cases, readApprovals(ctx.tp, module));
  const flows = flowStates(ctx);
  const statesById = new Map((model?.states ?? []).map((s) => [s.id, s]));
  const pagesById = new Map((model?.pages ?? []).map((p) => [p.id, p]));
  const warnings = [];
  if (!model) warnings.push("explore/model.json is missing: no page template can be derived, so no page object is required");

  // which cases are automated: approved, not @api, within testcases.max_cases (ranked by priority, then id)
  const approvedUi = cases.filter((c) => status.get(c.id)?.status === "approved" && !c.api);
  const rank = (c) => [PRIORITIES.indexOf(c.priority ?? "p3"), idNum(c.id)];
  const ranked = approvedUi.slice().sort((a, b) => rank(a)[0] - rank(b)[0] || rank(a)[1] - rank(b)[1]);
  const inBudget = new Set(ranked.slice(0, ctx.maxCases).map((c) => c.id));

  // page objects: one per page template an automated case touches, a component per dialog its touched states show
  const objects = new Map();
  const pageObject = (pg) => {
    const page = pagesById.get(pg);
    const key = pg;
    if (!objects.has(key)) {
      const base = page.slug === module || page.slug.startsWith(`${module}-`) ? page.slug : `${module}-${page.slug}`;
      const states = (page.states ?? []).filter((s) => statesById.has(s)).sort(byNum);
      const entry = states.find((s) => statesById.get(s).reach?.from === s && !(statesById.get(s).reach?.steps ?? []).length) ?? states[0];
      objects.set(key, {
        key, kind: "page", template: pg, templatePath: page.template, dialog: null,
        class: `${pascal(base)}Page`, fixture: `${camel(base)}Page`, file: `pages/${module}/${page.slug}.page.ts`,
        states, snapshots: states.map((s) => `explore/${statesById.get(s).snapshot}`),
        smoke: entry ? smokeRoute(ctx, statesById.get(entry), { viaReach: false, model }) : { skip: `${pg} has no recorded state` },
        cases: [],
      });
    }
    return objects.get(key);
  };
  const dialogObject = (pg, d) => {
    const key = `${pg}#dialog:${d.name}`;
    if (!objects.has(key)) {
      const page = pagesById.get(pg);
      const states = (page.states ?? []).filter((s) => statesById.has(s) && dialogsOf(stateSnapshot(ctx, statesById.get(s))).some((x) => x.name === d.name)).sort(byNum);
      objects.set(key, {
        key, kind: "dialog", template: pg, templatePath: page.template, dialog: d.name, dialogRole: d.role, slug: kebab(d.name), pageSlug: page.slug,
        states, snapshots: states.map((s) => `explore/${statesById.get(s).snapshot}`),
        smoke: states.length ? smokeRoute(ctx, statesById.get(states[0]), { viaReach: true, model }) : { skip: `no state of ${pg} shows the dialog` },
        cases: [],
      });
    }
    return objects.get(key);
  };

  const tests = [];
  const unmapped = [];
  for (const c of cases) {
    if (!inBudget.has(c.id)) continue;
    const states = touchedStates(c, { itemsById, model, flows });
    const pgs = uniq(states.map((s) => statesById.get(s).page)).filter((p) => pagesById.has(p)).sort(byNum);
    const objs = [];
    for (const pg of pgs) objs.push(pageObject(pg));
    for (const s of states) for (const d of dialogsOf(stateSnapshot(ctx, statesById.get(s)))) objs.push(dialogObject(statesById.get(s).page, d));
    for (const o of objs) o.cases.push(c.id);
    if (!pgs.length) unmapped.push(c.id);
    const tags = uniq([c.priority, c.type, ...(c.mutates ? ["mutates"] : []), ...(c.assumption ? ["assumption"] : []), ...(c.visual ? ["visual"] : [])].filter(Boolean)).map((t) => `@${t}`);
    tests.push({
      id: c.id, version: c.version ?? `v${String(c.hash ?? "").slice(0, 12)}`, title: one(c.title), tags,
      literal: [c.id, one(c.title), ...tags].filter(Boolean).join(" "),
      priority: c.priority ?? null, type: c.type ?? null, mutates: !!c.mutates, visual: !!c.visual, assumption: !!c.assumption,
      states, pages: pgs, objects: uniq(objs.map((o) => o.key)),
      steps: (c.steps ?? []).map(one), expected: one(c.expected), preconditions: (c.preconditions ?? []).map(one), data: Object.keys(c.data ?? {}), covers: c.covers ?? [],
    });
  }
  if (unmapped.length) warnings.push(`no page template could be derived for ${unmapped.join(", ")} (their coverage items name no state, transition or flow state): the tests-writer uses the existing page objects`);

  // names: dialogs get <Name>Dialog in pages/<m>/components/<name>.component.ts; a second dialog with the same name on
  // another template gets its page slug in front. Deterministic: the keys are taken in sorted order.
  const used = new Set();
  for (const o of [...objects.values()].filter((x) => x.kind === "dialog").sort((a, b) => (a.key < b.key ? -1 : 1))) {
    const base = used.has(o.slug) ? `${o.pageSlug}-${o.slug}` : o.slug;
    used.add(o.slug);
    Object.assign(o, { class: `${pascal(base)}Dialog`, fixture: `${camel(`${module}-${base}`)}Dialog`, file: `pages/${module}/components/${base}.component.ts` });
    delete o.slug;
    delete o.pageSlug;
  }
  const ordered = [...objects.values()].sort((a, b) => byNum(a.template, b.template) || (a.kind === b.kind ? (a.key < b.key ? -1 : 1) : a.kind === "page" ? -1 : 1));
  const fixtureOf = new Map(ordered.map((o) => [o.key, o.fixture]));
  for (const t of tests) t.fixtures = t.objects.map((k) => fixtureOf.get(k));

  // the ledger: every case and every page template of the module ends in one status
  const ledger = createLedger({ reasons: EXCLUDE_REASONS });
  const spec = SPEC_FILE(module);
  const why = { awaiting: "awaiting a human approval", rejected: "rejected by a human", changes: "a human asked for changes" };
  for (const c of cases) {
    ledger.addItem(c.id, { kind: "case", label: one(c.title) });
    const st = status.get(c.id) ?? { status: "awaiting" };
    if (c.api) ledger.resolve(c.id, { status: "excluded", reason: "api-side", detail: "an @api case: the Playwright API side automates it" });
    else if (st.status !== "approved") ledger.resolve(c.id, { status: "excluded", reason: "not-approved", detail: st.invalidated ? "edited since a human approved it: awaiting a new approval" : why[st.status] ?? st.status });
    else if (!inBudget.has(c.id)) ledger.resolve(c.id, { status: "deferred", reason: "budget", detail: `over testcases.max_cases (${ctx.maxCases})` });
    else ledger.resolve(c.id, { status: "mapped", refs: [spec] });
  }
  for (const p of [...pagesById.values()].sort((a, b) => byNum(a.id, b.id))) {
    ledger.addItem(p.id, { kind: "page", label: p.template });
    const o = objects.get(p.id);
    if (o) ledger.resolve(p.id, { status: "mapped", refs: [o.file] });
    else ledger.resolve(p.id, { status: "excluded", reason: "not-touched", detail: "no automated case touches it" });
  }
  for (const o of ordered.filter((x) => x.kind === "dialog")) {
    ledger.addItem(o.key, { kind: "dialog", label: `${o.dialogRole} "${o.dialog}" on ${o.template}` });
    ledger.resolve(o.key, { status: "mapped", refs: [o.file] });
  }

  const awaiting = cases.filter((c) => !c.api && status.get(c.id)?.status !== "approved").map((c) => ({ id: c.id, status: status.get(c.id)?.invalidated ? "invalidated" : status.get(c.id)?.status ?? "awaiting" }));
  const plan = {
    module, runId: ctx.runId, maxCases: ctx.maxCases,
    files: { spec, smoke: SMOKE_FILE(module), registration: REGISTRATION_FILE(module), data: DATA_FILE(module), index: INDEX_FILE },
    registration: { type: `${pascal(module)}Pages`, value: `${camel(module)}Pages` },
    tests: tests.sort((a, b) => byNum(a.id, b.id)),
    objects: ordered,
    awaiting,
    deferred: ledger.items.filter((i) => i.status === "deferred").map((i) => i.id),
    unmapped,
  };
  return { plan, ledger, warnings, built: !!tc };
}

// No approved case of the module is a UI case (every approved one is @api): the UI side has nothing to automate.
// -> reason | false. A module whose cases are not built, or with none approved, is not this: run.mjs keeps its stage
// awaiting approval.
export function noUiCases(ctx) {
  const tc = readJson(ctx.tp.coverage, null);
  if (!tc) return false;
  const st = approvalStatus(tc.cases ?? [], readApprovals(ctx.tp, ctx.module));
  const approved = (tc.cases ?? []).filter((c) => st.get(c.id)?.status === "approved");
  return approved.length && approved.every((c) => c.api) ? "every approved test case is @api: nothing to automate on the UI side" : false;
}

// ---------- rendering ----------

const BEGIN = /^\s*\/\/ ui-code:begin (\S.*?)\s*$/;
const END = /^\s*\/\/ ui-code:end (\S.*?)\s*$/;
const stepKey = (id, n) => `${id} step ${n}`;
const thenKey = (id) => `${id} then`;
const dataKey = (id) => `${id} data`;

// The regions of a cases spec: -> {regions: Map key -> lines[], titles: Map key -> the test.step title above it, problems}
export function parseRegions(text) {
  const regions = new Map();
  const titles = new Map();
  const problems = [];
  const lines = String(text ?? "").replace(/\r\n?/g, "\n").split("\n");
  let open = null;
  let body = [];
  lines.forEach((l, i) => {
    const b = BEGIN.exec(l);
    const e = END.exec(l);
    if (b) {
      if (open) problems.push(`line ${i + 1}: region '${b[1]}' starts inside region '${open}'`);
      open = b[1];
      body = [];
      const title = /test\.step\((['"])((?:\\.|(?!\1).)*)\1/.exec(lines[i - 1] ?? "");
      if (title) titles.set(open, title[2].replace(/\\(.)/g, "$1"));
    } else if (e) {
      if (!open) problems.push(`line ${i + 1}: 'ui-code:end ${e[1]}' without its begin`);
      else if (e[1] !== open) problems.push(`line ${i + 1}: region '${open}' ends as '${e[1]}'`);
      else if (regions.has(open)) problems.push(`line ${i + 1}: region '${open}' appears twice`);
      else regions.set(open, body);
      open = null;
    } else if (open) body.push(l);
  });
  if (open) problems.push(`region '${open}' never ends`);
  return { regions, titles, problems };
}

const region = (key, body, indent) => [`${indent}// ui-code:begin ${key}`, ...(body ?? []), `${indent}// ui-code:end ${key}`];

// The cases spec: the skeleton around the region bodies. regions: Map key -> lines[].
export function renderSpec(ctx, plan, regions = new Map()) {
  const { product, module } = ctx;
  const L = [
    `// Generated by scripts/ui-code.mjs from the test cases a human approved (artifacts/${product}/modules/${module}/ui-code/plan.json).`,
    '// Only the regions between "// ui-code:begin <key>" and "// ui-code:end <key>" are yours: fill them and keep the',
    `// markers. Everything else is rewritten by \`node scripts/ui-code.mjs build ${product} ${module}\`, which keeps every region's body.`,
    "import { test, expect } from '../../../fixtures/ui';",
    "",
    ...region("setup", regions.get("setup"), ""),
    "",
    `test.describe(${lit(ctx.moduleName)}, () => {`,
  ];
  plan.tests.forEach((t, i) => {
    if (i) L.push("");
    L.push(`  // ${t.id} ${t.version}: ${[t.priority, t.type].filter(Boolean).join(", ")}; covers ${t.covers.join(" ") || "nothing"}; page objects: ${t.fixtures.join(", ") || "none derived"}`);
    if (t.preconditions.length) L.push(`  // Preconditions: ${t.preconditions.join("; ")}`);
    if (t.data.length) L.push(`  // Test data (values in the test case; build them in ${DATA_FILE(module)}): ${t.data.join(", ")}`);
    L.push(`  test(${lit(t.literal)}, async ({ ${["page", ...t.fixtures].join(", ")} }) => {`);
    L.push("    // the test's data: only `const <name> = <builder>(…);` with a builder from the module's data file; every step sees it", ...region(dataKey(t.id), regions.get(dataKey(t.id)), "    "));
    t.steps.forEach((s, n) => {
      L.push(`    await test.step(${lit(`${n + 1}. ${s}`)}, async () => {`, ...region(stepKey(t.id, n + 1), regions.get(stepKey(t.id, n + 1)), "      "), "    });");
    });
    L.push(`    await test.step(${lit(`Then: ${t.expected}`)}, async () => {`, ...region(thenKey(t.id), regions.get(thenKey(t.id)), "      "), "    });");
    L.push("  });");
  });
  L.push("});", "");
  return L.join("\n");
}

const regionKeys = (plan) => ["setup", ...plan.tests.flatMap((t) => [dataKey(t.id), ...t.steps.map((_, n) => stepKey(t.id, n + 1)), thenKey(t.id)])];

export function renderRegistration(ctx, plan) {
  const { module } = ctx;
  const { type, value } = plan.registration;
  const L = [
    `// ${HEADER} Rebuilt from artifacts/${ctx.product}/modules/${module}/ui-code/plan.json by \`node scripts/ui-code.mjs build ${ctx.product} ${module}\`.`,
    `// The module's page-object fixtures. fixtures/ui/index.ts (generated, D-056) spreads them on ./base:`,
    `//   import { ${value}, type ${type} } from './pages/${module}';`,
    `//   export const test = base.extend<${type}>({ ...${value} });   (combine modules with & and more spreads)`,
    "import type { Page } from '@playwright/test';",
    ...plan.objects.map((o) => `import { ${o.class} } from '../../../${o.file.replace(/\.ts$/, "")}';`),
    "",
    `export type ${type} = {`,
    ...plan.objects.map((o) => `  ${o.fixture}: ${o.class};`),
    "};",
    "",
    `export const ${value} = {`,
    ...plan.objects.flatMap((o) => [
      `  ${o.fixture}: async ({ page }: { page: Page }, use: (value: ${o.class}) => Promise<void>) => {`,
      `    await use(new ${o.class}(page));`,
      "  },",
    ]),
    "};",
    "",
  ];
  return L.join("\n");
}

// A page-object or component shell, written once when the file is missing; the pom-writer owns it afterwards.
