function inputDigests(ctx) {
  const flowsDir = ctx.xp.flows;
  const flows = existsSync(flowsDir) ? readdirSync(flowsDir).filter((f) => f.endsWith(".md")).sort().map((f) => `${f}\n${readFileSync(path.join(flowsDir, f), "utf8")}`).join("\n\0") : "";
  return {
    testcases: sha256(ctx.tp.coverage), approvals: sha256(ctx.tp.approvals), model: sha256(ctx.xp.model), flows: sha(flows),
    config: sha(JSON.stringify({ maxCases: ctx.maxCases, name: ctx.moduleName, target: ctx.targetUrl })),
  };
}

// validate: lib/contract.mjs validateData. -> {code, out}
export async function build(ctx, validate) {
  const { up, module } = ctx;
  const { plan, ledger, warnings, built } = derivePlan(ctx);
  if (!built) return { code: 1, out: { problems: [`testcases/coverage.json is missing: the test cases must be built (testcases.mjs) before the UI code`], note: "nothing was built" } };
  const problems = [];
  const written = [];
  const out = { tests: plan.tests.length, objects: plan.objects.length, awaiting: plan.awaiting, deferred: plan.deferred, unmapped: plan.unmapped };
  const foundation = existsSync(pw(ctx, "fixtures/ui/base.ts"));
  if (!foundation) problems.push(`the UI foundation is not rendered (playwright-tests/${ctx.product}/fixtures/ui/base.ts is missing): it comes first (foundation.mjs render --side ui)`);

  // the spec: the skeleton around the agent's region bodies; a body whose key is gone is parked, and comes back with it
  const parked = readJson(up.parked, { module, regions: {} });
  const restored = [];
  const newlyParked = [];
  const changedSteps = [];
  if (foundation) {
    const specFile = pw(ctx, plan.files.spec);
    const old = readText(specFile);
    const parsed = parseRegions(old ?? "");
    if (parsed.problems.length) problems.push(...parsed.problems.map((p) => `${plan.files.spec}: ${p} -- fix the markers by hand; the file was not rewritten`));
    else {
      const keys = new Set(regionKeys(plan));
      const regions = new Map();
      const filled = (lines) => (lines ?? []).some((l) => l.trim());
      for (const key of keys) {
        if (parsed.regions.has(key)) regions.set(key, parsed.regions.get(key));
        else if (parked.regions[key]) {
          regions.set(key, parked.regions[key].lines);
          restored.push(key);
          delete parked.regions[key];
        }
      }
      for (const [key, lines] of parsed.regions)
        if (!keys.has(key) && filled(lines)) {
          parked.regions[key] = { lines, title: parsed.titles.get(key) ?? null, run: ctx.runId };
          newlyParked.push(key);
        }
      // a step whose text changed keeps its body; the writer revisits it
      for (const t of plan.tests)
        t.steps.forEach((s, n) => {
          const key = stepKey(t.id, n + 1);
          const before = parsed.titles.get(key);
          if (before !== undefined && before !== `${n + 1}. ${s}` && filled(regions.get(key))) changedSteps.push(key);
        });
      if (writeIfChanged(specFile, renderSpec(ctx, plan, regions))) written.push(plan.files.spec);
    }
    // page-object shells (once), the registration, the smoke
    for (const o of plan.objects) {
      const f = pw(ctx, o.file);
      if (!existsSync(f)) {
        writeIfChanged(f, renderShell(ctx, o));
        written.push(o.file);
      }
    }
    if (writeIfChanged(pw(ctx, plan.files.registration), renderRegistration(ctx, plan))) written.push(plan.files.registration);
    // fixtures/ui/index.ts spreads every module's registration: generated, the same bytes whoever writes it (D-056)
    const index = writeIndex(ctx.pwProject, "ui", path.join(ctx.productDir, "foundation"));
    if (index.written) written.push(INDEX_FILE);
    if (index.legacy) warnings.push(`fixtures/ui/index.ts is now generated (D-056): the previous hand-written one is kept in ${rel(ctx.root, index.legacy)}`);
    if (writeIfChanged(pw(ctx, plan.files.smoke), renderSmoke(ctx, plan))) written.push(plan.files.smoke);
  }
  const planBad = await validate("ui-code-plan", plan);
  if (planBad.length) problems.push(...planBad.map((e) => `plan.json (internal): ${e}`));
  writeJson(up.plan, plan);
  if (newlyParked.length || restored.length || existsSync(up.parked)) {
    const parkedBad = await validate("ui-code-parked", parked);
    if (parkedBad.length) problems.push(...parkedBad.map((e) => `parked.json (internal): ${e}`));
    writeJson(up.parked, parked);
  }
  const old = readJson(up.coverage, {});
  const coverage = {
    module, runId: ctx.runId, maxCases: ctx.maxCases,
    summary: ledger.summary(), items: ledger.items, problems,
    built: { inputs: inputDigests(ctx) },
    verified: { pages: old.verified?.pages ?? null, tests: old.verified?.tests ?? null },
  };
  const covBad = await validate("ui-code-coverage", coverage);
  if (covBad.length) problems.push(...covBad.map((e) => `coverage.json (internal): ${e}`));
  writeJson(up.coverage, coverage);
  out.parkedCases = recordParked(ctx);
  return {
    code: problems.length ? 1 : 0,
    out: {
      ...out, items: ledger.summary(), written, restored, parked: newlyParked, changedSteps, problems, warnings,
      next: problems.length ? "fix the problems, then build again" : "write the code (page objects, or the step bodies), then run ui-code.mjs check",
    },
  };
}

// ---------- the rules (shared by `check` and the gate, scripts/lib/gate/playwright.mjs) ----------

const readPlan = (ctx) => readJson(ctx.up.plan, null);
const strip = (lines) => lines.join("\n").replace(/\/\*[\s\S]*?\*\//g, "").replace(/\/\/.*$/gm, "").trim();
const declaresTest = (code) => {
  const sig = scanTs(code).filter((t) => t.type !== "comment");
  for (let k = 0; k < sig.length; k++) {
    if (sig[k].value !== "test" || sig[k - 1]?.value === ".") continue;
    let j = k + 1;
    let variant = "";
    if (sig[j]?.value === "." && sig[j + 1]?.type === "ident") [variant, j] = [sig[j + 1].value, j + 2];
    if (sig[j]?.value !== "(") continue;
    if (["describe", "only", "skip", "fixme", "fail", ""].includes(variant)) {
      const { args } = callArgs(sig, j);
      const fn = args[1] ?? [];
      if (variant === "describe" || fn.some((t) => t.value === "=>" || t.value === "function")) return `test${variant ? `.${variant}` : ""}(…)`;
    }
  }
  return null;
};

// The findings for the page objects and the registration: scope "pages"; for the cases spec too: scope "tests".
// -> [{severity, file, line, rule, problem, fix}] (files relative to the Playwright project). [] when never built.
export function uiCodeFindings(ctx, { scope = "tests" } = {}) {
  const plan = readPlan(ctx);
  if (!plan) return [];
  const out = [];
  const { module } = ctx;
  const statesById = new Map((readJson(ctx.xp.model, null)?.states ?? []).map((s) => [s.id, s]));
  const rebuild = `node scripts/ui-code.mjs build ${ctx.product} ${module}`;
  const code = moduleCode(ctx);
  const usage = []; // the builder values that reach a data-driven locator
  // a selector's reason cites a state snapshot (or the page's first-state snapshot) of the object's own template
  const citesOf = (snaps) => new Set([...snaps, ...uniq(snaps.map((x) => /^(explore\/pages\/[^/]+)\//.exec(x)?.[1]).filter(Boolean)).map((d) => `${d}/dom-snapshot.md`)].map((x) => `observation:${x}`));

  // page objects: present, exporting their class, every locator grounded in a snapshot of its template
  for (const o of plan.objects) {
    const text = readText(pw(ctx, o.file));
    if (text === null) {
      out.push(finding("major", o.file, null, "page-object", `${o.file} is missing: ${o.kind === "page" ? `the page object for ${o.template}` : `the component for the ${o.dialogRole} "${o.dialog}"`} (${o.cases.join(", ")} touch it)`, `run ${rebuild} to seed its shell, then write it`));
      continue;
    }
    const parsed = parseLocators(text);
    if (!parsed.classes.includes(o.class)) out.push(finding("major", o.file, null, "page-object", `${o.file} does not export class ${o.class}`, `keep the class name the script gives (export class ${o.class})`));
    const facts = o.states.map((s) => statesById.get(s)).filter(Boolean).map((s) => stateSnapshot(ctx, s)).filter((t) => t !== null).map(snapshotFacts);
    out.push(...locatorFindings(ctx, o.file, parsed, facts, { cites: citesOf(o.snapshots), code, usage }));
  }
  // page objects not in the plan: their locators are checked against every snapshot of the module
  const known = new Set(plan.objects.map((o) => o.file));
  // page objects outside the plan and every helpers/ui file the code imports: checked like page objects, against every
  // snapshot of the module
  const extra = uniq([...walk(ctx.pwProject, `pages/${module}`, /\.ts$/).filter((f) => !known.has(f)), ...code.map((x) => x.file).filter((f) => f.startsWith("helpers/ui/"))]);
  if (extra.length) {
    const states = [...statesById.values()];
    const all = states.map((s) => stateSnapshot(ctx, s)).filter((t) => t !== null).map(snapshotFacts);
    const cites = citesOf(states.map((s) => `explore/${s.snapshot}`));
    for (const f of extra) out.push(...locatorFindings(ctx, f, parseLocators(readText(pw(ctx, f))), all, { cites, code, usage }));
  }

  // the registration file, its use in fixtures/ui/index.ts, the smoke spec: as the plan and the page objects give them
  for (const [file, want, what] of [[plan.files.registration, renderRegistration(ctx, plan), "the fixture registration"], [plan.files.smoke, renderSmoke(ctx, plan), "the locator smoke"]]) {
    const have = readText(pw(ctx, file));
    if (have !== want) out.push(finding("major", file, null, "generated", `${what} ${have === null ? "is missing" : "is out of date or was edited"}`, `run ${rebuild} (it is script-owned; never edit it)`));
  }
  // fixtures/ui/index.ts is generated from the module registrations (D-056): byte-identical to its render
  const indexWhy = indexProblem(ctx.pwProject, "ui");
  if (indexWhy) out.push(finding("major", INDEX_FILE, null, "fixture-registration", indexWhy, `run ${rebuild} (it is generated; never edit it)`));

  if (scope === "pages") return out;

  // the data builders hold data only
  const poMembers = { methods: new Set(), props: new Set() };
  for (const f of walk(ctx.pwProject, `pages/${module}`, /\.ts$/)) {
    const p = parseLocators(readText(pw(ctx, f)) ?? "");
    for (const fn of p.fns) if (fn.name && fn.name !== "constructor") poMembers.methods.add(fn.name);
    for (const x of p.props) poMembers.props.add(x.name);
  }
  const dataText = readText(pw(ctx, plan.files.data));
  if (dataText !== null) out.push(...dataFileFindings(plan.files.data, dataText, new Set([...poMembers.methods, ...poMembers.props])), ...uniqueFindings(plan.files.data, dataText, usage));
  else for (const u of usage) out.push(finding("major", u.file, u.line, "data-unique", `${u.builder}() is not in ${plan.files.data}`, "build the value in the module's data file, with uniqueName"));

  // the cases spec: the skeleton intact around the regions, every step filled, the case's rules in its bodies
  const file = plan.files.spec;
  const text = readText(pw(ctx, file));
  if (text === null) {
    out.push(finding("blocker", file, null, "skeleton", `${file} is missing`, `run ${rebuild}`));
    return out;
  }
  const parsed = parseRegions(text);
  if (parsed.problems.length) {
    for (const p of parsed.problems) out.push(finding("blocker", file, Number(/^line (\d+)/.exec(p)?.[1]) || null, "skeleton", p, "restore the region markers exactly as generated"));
    return out;
  }
  const want = renderSpec(ctx, plan, parsed.regions);
  if (want !== text) {
    let flagged = false;
    for (const t of plan.tests)
      if (!text.includes(`test(${lit(t.literal)},`)) {
        out.push(finding("major", file, null, "skeleton", `${t.id}: its test is missing, or its title or tags were changed (want test(${lit(t.literal)}, …))`, `run ${rebuild}; titles and tags come from the case, never by hand`));
        flagged = true;
      }
    const keys = new Set(regionKeys(plan));
    for (const k of parsed.regions.keys()) if (!keys.has(k)) out.push(finding("major", file, null, "skeleton", `region '${k}' is not in the plan (a test or step not generated for an approved case)`, `run ${rebuild}; it parks the body`));
    if (!flagged) {
      const a = want.split("\n");
      const b = text.split("\n");
      const at = a.findIndex((l, i) => l !== b[i]);
      out.push(finding("major", file, at + 1, "skeleton", `generated code outside the marked regions was changed (line ${at + 1}: ${JSON.stringify((b[at] ?? "").trim().slice(0, 80))}, generated: ${JSON.stringify((a[at] ?? "").trim().slice(0, 80))})`, `run ${rebuild} to restore it; write only inside the regions`));
    }
  }
  const lineOf = (key) => text.split("\n").findIndex((l) => BEGIN.exec(l)?.[1] === key) + 1 || null;
  for (const [key, lines] of parsed.regions) {
    const declared = declaresTest(lines.join("\n"));
    if (declared) out.push(finding("major", file, lineOf(key), "extra-test", `region '${key}' declares ${declared}: tests are generated, one per approved case`, "remove it; a test the cases do not ask for is not added by hand"));
  }
  const regionRules = regionFindings(file, parsed.regions, plan, lineOf, { poMembers });
  out.push(...regionRules.findings);
  for (const [id, reason] of regionRules.parked) out.push(finding("minor", file, lineOf(stepKey(id, 1)) ?? lineOf(thenKey(id)), "parked", `approved case parked: ${id}: ${reason}`, "automate it once the reason is gone; until then it is not covered"));
  const hasStatement = (lines) => scanTs(lines.join("\n")).some((x) => x.type !== "comment" && x.value !== ";");
  for (const t of plan.tests) {
    const keys = [...t.steps.map((_, n) => stepKey(t.id, n + 1)), thenKey(t.id)];
    const bodies = keys.map((k) => parsed.regions.get(k) ?? []);
    const code = strip(bodies.flat());
    if (regionRules.parked.has(t.id)) continue; // parked with a reason (a real test.fixme(true, '…') call): not automatable yet
    keys.forEach((k, n) => {
      if (!hasStatement(bodies[n])) out.push(finding("major", file, lineOf(k), "empty-step", `${t.id}: ${n < t.steps.length ? `step ${n + 1} (${t.steps[n].slice(0, 60)})` : "the expected-result step"} has an empty body`, "implement it through the page objects, or park the test with test.fixme(true, '<reason>') in its first step"));
    });
    if (t.visual && !/\btoHaveScreenshot\s*\(/.test(code)) out.push(finding("major", file, lineOf(thenKey(t.id)), "visual", `${t.id} is @visual but never calls toHaveScreenshot`, `await expect(page).toHaveScreenshot('${t.id}.png', { mask: [...] }) with the dynamic regions masked`));
    if (t.mutates && !/\brecordCreated\s*\(/.test(code)) out.push(finding("major", file, lineOf(keys[0]), "ledger", `${t.id} is @mutates but its steps never call recordCreated`, "record every entity it creates with recordCreated right after creating it"));
    if (/\brecordDeleted\s*\(/.test(code) && !/\bowns\s*\(/.test(code)) out.push(finding("major", file, lineOf(keys[0]), "ledger", `${t.id} calls recordDeleted but never checks owns(type, ref) first`, "delete an entity only when owns(type, ref) says this run created it (D-005), then recordDeleted"));
  }
  // every test lives in the cases spec: another spec file in the module's folder holds tests no case asked for
  for (const f of walk(ctx.pwProject, `tests/ui/${module}`, /\.ts$/))
    if (f !== file && f !== plan.files.smoke) out.push(finding("major", f, null, "extra-file", `${f}: the module's tests live in ${file} (generated) and its data builders in ${plan.files.data}`, "move its code into the regions of the cases spec or the data file, and delete it"));
  return out;
}

// The call sites `.<name>(…)` of a file's tokens, with the named function each one is in. -> [{line, args, inFn}]
function sitesIn(sig, fns, name) {
  const out = [];
  for (let k = 1; k < sig.length - 1; k++) {
    if (sig[k].value !== name || sig[k].type !== "ident" || sig[k - 1].value !== "." || sig[k + 1].value !== "(") continue;
    const { args } = callArgs(sig, k + 1);
    const inFn = fns.filter((f) => f.from <= k && k < f.to && f.name).sort((a, b) => a.to - a.from - (b.to - b.from))[0] ?? null;
    out.push({ line: sig[k].line, args: args.filter((a) => a.length), inFn });
  }
  return out;
}

// The rules on one page object's locators. facts: the snapshots of its template; cites: the observation citations a
// selector's reason may use (a snapshot of the same template); code: the module's code, for a parameter's call sites.
function locatorFindings(ctx, file, parsed, facts, { cites, code, usage = [] }) {
  const out = [];
  const citeCtx = { rows: [], cases: new Set(), productDir: ctx.productDir, moduleDir: path.join(ctx.productDir, "modules", ctx.module) };
  const policyFix = "use getByRole, then getByLabel, then getByText (getByTestId or getByPlaceholder when the snapshot shows it); a selector or page script needs `// locator: css|xpath|evaluate because <reason> [observation:explore/pages/<slug>/states/<ST>.md]` on or above its line, citing a snapshot of this template";
  for (const c of parsed.calls) {
    if (c.selector !== undefined || (c.problem && !c.name)) {
      const what = c.evaluate ? `a page script (${c.method})` : c.method === "locator" ? `a CSS/XPath selector (${c.selector})` : `a ${c.method}() selector (${c.selector})`;
      if (c.problem) out.push(finding("major", file, c.line, "locator-policy", c.problem, policyFix));
      else if (!c.reason) out.push(finding("major", file, c.line, "locator-policy", `${what} without a cited reason`, policyFix));
      else {
        const bad = citationProblem(c.reason.cite, citeCtx) ?? (cites.has(c.reason.cite) ? null : `'${c.reason.cite}', which is not a state snapshot of this page object's template`);
        if (bad) out.push(finding("major", file, c.line, "locator-policy", `the reason for ${what} cites ${bad}`, policyFix));
      }
      continue;
    }
    const why = locatorProblem(c, facts);
    if (why) out.push(finding("major", file, c.line, c.problem ? "locator-policy" : "locator-grounding", why, "copy the role and name verbatim from a state snapshot of the page template (explore/pages/<slug>/states/)"));
  }
  // Runtime data (D-055): a string parameter v may only refine a grounded locator, in a non-async method that only
  // returns it, by getByRole('<grounded role>', { name: v, exact: true }) or .filter({ hasText: v }). At each call
  // site v is a grounded literal, data a builder of helpers/ui/<m>.data.ts returned (in the cases spec), or a string
  // parameter of the calling page-object method, whose own call sites are checked the same way.
  const parsedCode = code.map(({ file: f, text }) => {
    const sig = scanTs(text).filter((t) => t.type !== "comment");
    return { file: f, sig, fns: functionsOf(sig), bindingAt: f === SPEC_FILE(ctx.module) ? specBindings(ctx, text) : () => new Map() };
  });
  for (const fn of parsed.fns) {
    const own = parsed.calls.filter((c) => c.name?.kind === "param" && c.name.fn === fn.name && c.index >= fn.from && c.index < fn.to);
    if (!fn.name || !own.length) continue;
    const shapeFix = "a data-driven locator is a non-async method that only returns a grounded locator refined by getByRole('<role>', { name: v, exact: true }) or .filter({ hasText: v })";
    if (fn.async || !fn.returnsOnly) out.push(finding("major", file, own[0].line, "locator-param", `${fn.name}(…) builds a locator from its parameter but ${fn.async ? "is async" : "does more than return it"}`, shapeFix));
    for (const c of own) {
      const ok = (c.method === "getByRole" && c.role && c.exact) || (c.method === "filter" && c.option === "hasText");
      if (!ok) out.push(finding("major", file, c.line, "locator-param", `${c.option ? `filter({ ${c.option} })` : `${c.method}(…)`} takes the parameter '${c.name.value}'${c.method === "getByRole" && !c.exact ? " without exact: true" : ""}`, shapeFix));
      if (c.method === "getByRole" && c.role && !facts.some((f) => f.nodes.some((x) => x.role === c.role))) out.push(finding("major", file, c.line, "locator-grounding", `getByRole: role '${c.role}' is in none of the template's state snapshots`, "copy the role from a state snapshot of the page template"));
    }
    const seen = new Set();
    const follow = (name, index) => {
      if (seen.has(`${name}#${index}`)) return;
      seen.add(`${name}#${index}`);
      for (const pc of parsedCode)
        for (const site of sitesIn(pc.sig, pc.fns, name)) {
          const arg = site.args[index];
          if (arg?.length === 1 && arg[0].type === "str") {
            for (const c of own.filter((x) => name !== fn.name || x.name.index === index)) {
              const why = locatorProblem({ ...c, name: { kind: "literal", value: arg[0].value } }, facts);
              if (why) out.push(finding("major", pc.file, site.line, "locator-grounding", `${why} (through ${name}(…) in ${file})`, "pass a name copied verbatim from a snapshot of that page object's template, or data from the module's builders"));
            }
            continue;
          }
          const data = boundArg(arg, pc.bindingAt(site.line));
          if (data) {
            usage.push({ ...data, file: pc.file, line: site.line });
            continue;
          }
          const p = arg?.length === 1 && arg[0].type === "ident" && pc.file.startsWith(`pages/${ctx.module}/`) ? site.inFn?.params.findIndex((x) => x.name === arg[0].value && x.string) : -1;
          if (p >= 0 && site.inFn.name !== "constructor") {
            follow(site.inFn.name, p);
            continue;
          }
          out.push(finding("major", pc.file, site.line, "locator-param", `${name}(…) builds a locator from its argument ${index + 1}, but this call passes ${arg ? arg.map((x) => x.value).join(" ").slice(0, 40) : "nothing"}`, `pass a string literal copied verbatim from a snapshot, or a value from the test's data region (const <name> = <builder>(…); with a builder of ${DATA_FILE(ctx.module)}), directly or through a step-local const of one of its members; a builder called in setup, at module level or in a step does not count`));
        }
    };
    for (const i of uniq(own.map((c) => c.name.index))) follow(fn.name, i);
  }
  return out;
}

// Every builder value that reaches a data-driven locator is run-unique: built with uniqueName (or uniqueEmail) from
// utils/shared/data.ts, never a fixed string, so a locator never finds another run's or another test's data.
// usage: [{builder, path, file, line}] from the call sites. -> findings in the data file
function uniqueFindings(file, text, usage) {
  const out = [];
  const sig = scanTs(text).filter((t) => t.type !== "comment");
  const uses = (toks) => toks.some((t, i) => (t.type === "ident" && ["uniqueName", "uniqueEmail"].includes(t.value) && toks[i + 1]?.value === "(") || (t.type === "tpl" && /\bunique(Name|Email)\s*\(/.test(t.value)));
  const seen = new Set();
  for (const u of usage) {
    const key = `${u.builder}|${u.path[0] ?? ""}`;
    if (seen.has(key)) continue;
    seen.add(key);
    const start = sig.findIndex((t, k) => t.value === u.builder && ["const", "function"].includes(sig[k - 1]?.value) && sig[k - 2]?.value === "export");
    if (start < 0) {
      out.push(finding("major", u.file, u.line, "data-unique", `${u.builder}() is not an exported builder of ${file}`, "build the value in the module's data file, with uniqueName"));
      continue;
    }
    let end = sig.findIndex((t, k) => k > start && t.value === "export");
    if (end < 0) end = sig.length;
    const body = sig.slice(start, end);
    let value = body;
    const prop = u.path[0];
    if (prop) {
      const i = body.findIndex((t, k) => t.type === "ident" && t.value === prop && ["{", ","].includes(body[k - 1]?.value) && body[k + 1]?.value === ":");
      if (i >= 0) {
        value = [];
        for (let j = i + 2, d = 0; j < body.length; j++) {
          if (isOpen(body[j])) d++;
          else if (isClose(body[j])) {
            if (!d) break;
            d--;
          } else if (!d && body[j].value === ",") break;
          value.push(body[j]);
        }
      }
    }
    if (!uses(value))
      out.push(finding("major", file, (value[0] ?? body[0]).line, "data-unique", `${u.builder}() returns ${prop ? `'${prop}' ` : ""}without uniqueName (${value.length === 1 && value[0].type === "str" ? `the fixed string '${value[0].value}'` : "a value not unique to the run"}), and ${u.file}:${u.line} finds it with a data-driven locator`, "build every value a locator finds with uniqueName('<prefix>') from utils/shared/data.ts, so it is unique to the run and the test"));
    else {
      // a conditional or defaulted value (cond ? uniqueName(..) : 'Jane', a || 'Jane', a ?? 'Jane'): every alternative that is a bare string or template must be unique too
      const alts = [[]];
      let depth = 0;
      for (const t of value) {
        if (isOpen(t)) depth++;
        else if (isClose(t)) depth--;
        if (!depth && ["?", ":", "|"].includes(t.value)) alts.push([]);
        else alts.at(-1).push(t);
      }
      const bare = alts.length > 1 ? alts.find((x) => x.length === 1 && ["str", "tpl"].includes(x[0].type) && !uses(x)) : null;
      if (bare) out.push(finding("major", file, bare[0].line, "data-unique", `${u.builder}() returns ${prop ? `'${prop}' ` : ""}a fixed string '${String(bare[0].value).slice(0, 40)}' as one alternative of its value, and ${u.file}:${u.line} finds it with a data-driven locator`, "every alternative a locator can find is built with uniqueName('<prefix>'), the fallback too"));
    }
  }
  return out;
}

// The data builders (helpers/ui/<m>.data.ts) hold data only: no Playwright import, no page, locator or page-object
// type or value, no element call. -> findings
function dataFileFindings(file, text, poNames) {
  const out = [];
  const sig = scanTs(text).filter((t) => t.type !== "comment");
  const fix = "keep only data: values and functions returning data (built with uniqueName); element work belongs in the page objects";
  for (const m of text.matchAll(/(?:from|import\s*\(|require\s*\()\s*['"]((?:@playwright\/test|playwright)(?:\/[^'"]*)?|[^'"]*\/pages\/[^'"]*|[^'"]*fixtures\/ui[^'"]*)['"]/g))
    out.push(finding("major", file, text.slice(0, m.index).split("\n").length, "data-file", `the data builders import ${m[1]}`, fix));
  for (let k = 0; k < sig.length; k++) {
    const t = sig[k];
    if (t.type !== "ident") continue;
    if (["Page", "Locator", "Frame", "FrameLocator", "BrowserContext", "ElementHandle", "page"].includes(t.value) && sig[k - 1]?.value !== "." && sig[k + 1]?.value !== ":")
      out.push(finding("major", file, t.line, "data-file", `the data builders use ${t.value}`, fix));
    else if (sig[k - 1]?.value === "." && sig[k + 1]?.value === "(" && (RAW_METHODS.includes(t.value) || PAGE_SELECTOR_METHODS.includes(t.value) || poNames.has(t.value)))
      out.push(finding("major", file, t.line, "data-file", `the data builders call .${t.value}(…)`, fix));
  }
  return out;
}

// Whether the expected-result step really asserts: a top-level `expect(<a page object's locator or data read through
// one>).<matcher>(…)` (or, for a test with no page object, a web-first `expect(page)` matcher). Not counted:
// expect(<literal>), expect.poll, expect.soft, an assertion in a nested block or function, or after a return/throw.
function thenProblems(sig, fixtures) {
  const out = [];
  let depth = 0;
  let ended = false;
  let real = false;
  for (let k = 0; k < sig.length; k++) {
    const t = sig[k];
    if (t.value === "{") depth++;
    else if (t.value === "}") depth--;
    if (depth === 0 && ["return", "throw"].includes(t.value)) {
      const rest = sig.slice(k + 1).findIndex((u) => u.value === ";");
      if (sig.slice(k + 1 + (rest < 0 ? sig.length : rest + 1)).length) out.push("code after a top-level return or throw never runs");
      ended = true;
    }
    if (ended || depth !== 0 || t.value !== "expect" || sig[k - 1]?.value === "." || sig[k + 1]?.value !== "(") continue;
    const close = matchClose(sig, k + 1);
    const subject = sig.slice(k + 2, close).filter((u) => u.value !== "await");
    if (sig[close + 1]?.value !== ".") continue;
    let j = close + 2;
    if (sig[j]?.value === "not" && sig[j + 1]?.value === ".") j += 2;
    if (sig[j]?.type !== "ident" || sig[j + 1]?.value !== "(") continue;
    const onPo = subject[0]?.type === "ident" && fixtures.includes(subject[0].value) && subject[1]?.value === "." && subject[2]?.value !== "page";
    const onPage = !fixtures.length && subject.length === 1 && subject[0].value === "page" && /^to(HaveURL|HaveTitle|HaveScreenshot)$/.test(sig[j].value);
    if (onPo || onPage) real = true;
  }
  if (!real) out.push(fixtures.length ? "it asserts nothing on a page object: expect(<page object>.<locator or read>).<matcher>(…) as a top-level statement" : "it asserts nothing: expect(page).toHaveURL / toHaveTitle / toHaveScreenshot, or a page object");
  return uniq(out);
}

const PAGE_OK = ["goto", "reload", "goBack", "goForward", "waitForURL", "waitForLoadState", "url", "title", "keyboard", "mouse", "setViewportSize", "viewportSize", "bringToFront", "close"];
const HOOKS = ["beforeEach", "afterEach", "beforeAll", "afterAll"];
const staticStr = (n) => (n?.type === "Literal" && typeof n.value === "string" ? n.value : n?.type === "TemplateLiteral" && !n.expressions.length ? (n.quasis[0].value.cooked ?? "") : null);
// The parking statement of a first step: the region's very first statement is `test.fixme(true, '<reason>');`. -> the call | null
function parkingCall(ast, isFirstStep) {
  const st = ast.body[0];
  const c = st?.type === "ExpressionStatement" ? st.expression : null;
  if (!isFirstStep || c?.type !== "CallExpression" || c.arguments.length !== 2) return null;
  const f = c.callee;
  const reason = staticStr(c.arguments[1]);
  return f.type === "MemberExpression" && !f.computed && f.object.type === "Identifier" && f.object.name === "test" && f.property.name === "fixme" && c.arguments[0].type === "Literal" && c.arguments[0].value === true && reason !== null && reason.trim().length >= 3 ? c : null;
}
// Does a member expression's receiver run on a page or a frame: `page.x`, `this.page.x`, `frame.x`, `page.mainFrame().x`, `page.frames()[0].x`?
function onPageNode(m) {
  const r = m.object;
  if (r.type === "Identifier") return /^(page|frame)$/i.test(r.name);
  if (r.type === "MemberExpression" && !r.computed && r.property.type === "Identifier" && /^(page|frame)$/i.test(r.property.name)) return true;
  const gets = (c) => c?.type === "CallExpression" && c.callee.type === "MemberExpression" && !c.callee.computed && FRAME_GETTERS.includes(c.callee.property?.name);
  return gets(r) || (r.type === "MemberExpression" && r.computed && gets(r.object));
}
// The rules on the syntax tree of one step region (see regionFindings): the JavaScript that runs, read as nodes.
function regionAstRules(tree, { key, fixtures, poMembers, parkCall, pomFix, push }) {
  const { tokens } = declaredNames(tree);
  const declaring = new Set(tokens);
  // a function's second parameter after a destructured first one (a hook's) is testInfo
  const infoParams = new Set();
  walkPath(tree.ast, (n) => {
    if (/^(Function|ArrowFunction)/.test(n.type) && n.params.length >= 2 && n.params[0].type !== "Identifier" && n.params[1].type === "Identifier") infoParams.add(n.params[1]);
  });
  const infoNames = new Set([...infoParams].map((x) => x.name));
  const memberOf = (n, p) => (p?.type === "MemberExpression" && p.object === n && !p.computed && p.property.type === "Identifier" ? p.property.name : null);
  const calledAs = (m, g) => g?.type === "CallExpression" && g.callee === m;
  const written = (m, g) => (g?.type === "AssignmentExpression" && g.left === m) || g?.type === "UpdateExpression" || ((g?.type === "ForInStatement" || g?.type === "ForOfStatement") && g.left === m);
  const selectorish = [...PAGE_SELECTOR_METHODS, ...RAW_METHODS, ...FRAME_GETTERS];
  walkPath(tree.ast, (n, up, k) => {
    const p = up.at(-1);
    const g = up.at(-2);
    if (n.type === "CallExpression" && n.callee.type === "MemberExpression" && !n.callee.computed && n.callee.property.type === "Identifier") {
      const name = n.callee.property.name;
      if (RAW_METHODS.includes(name)) push(n.callee.property, "raw-locator", `finds elements itself (.${name}(…)): steps go through the page objects`, "add a locator or method to the page object (pw-ui-pom-writer) and call it; it is grounded in the snapshots there");
      else if ((PAGE_SELECTOR_METHODS.includes(name) || FRAME_GETTERS.includes(name)) && onPageNode(n.callee)) push(n.callee.property, "raw-locator", `calls page.${name}(…), Playwright's selector API: steps go through the page objects`, "add a locator or method to the page object (pw-ui-pom-writer) and call it");
      if (["skip", "fixme", "fail", "slow"].includes(name) && n !== parkCall) push(n.callee.property, "silent-skip", `calls .${name}(…): a skipped or expected-to-fail test passes silently`, "never skip; park a case that can't be automated yet with `test.fixme(true, '<reason>');` as the first statement of its first step");
    }
    if (n.type === "MemberExpression") {
      if (n.computed) {
        const name = staticStr(n.property);
        if (name !== null && (RAW_METHODS.includes(name) || PAGE_SELECTOR_METHODS.includes(name))) push(n.property, "raw-locator", `finds elements itself (['${name}']): steps go through the page objects`, "add a locator or method to the page object (pw-ui-pom-writer) and call it; it is grounded in the snapshots there");
        if (name !== null && poMembers.methods.has(name) && n.object.type === "Identifier" && !fixtures.includes(n.object.name)) push(n.object, "po-access", `calls ['${name}'] by computed access`, pomFix);
      } else if (n.property.type === "Identifier" && selectorish.includes(n.property.name) && !calledAs(n, p) && onPageNode(n)) {
        // the method taken without calling it (`const f = page.locator;`) is the same selector API
        push(n.property, "raw-locator", `takes page.${n.property.name} without calling it: steps go through the page objects`, "add a locator or method to the page object (pw-ui-pom-writer) and call it");
      }
    }
    if (n.type !== "Identifier") return;
    // a name in a pattern's shorthand (`({ page, contactsPage }) =>`) declares a fixture, it does not use one
    if (p?.type === "Property" && p.shorthand && g?.type === "ObjectPattern") return;
    if (infoParams.has(n)) return;
    if (p?.type === "MemberExpression" && k === "property" && !p.computed) return;
    if ((p?.type === "Property" || p?.type === "MethodDefinition" || p?.type === "PropertyDefinition") && k === "key" && !p.computed) return;
    if (["LabeledStatement", "BreakStatement", "ContinueStatement", "MetaProperty"].includes(p?.type) || /^(Import|Export)/.test(p?.type ?? "")) return;
    const m = memberOf(n, p);
    const called = m !== null && calledAs(p, g);
    if (n.name === "page") {
      const inExpect = p?.type === "CallExpression" && p.arguments.length === 1 && p.arguments[0] === n && p.callee.type === "Identifier" && ["expect", "waitForReady"].includes(p.callee.name);
      if (!inExpect && !(m && (PAGE_OK.includes(m) || selectorish.includes(m)))) push(n, "raw-locator", `uses page${m ? `.${m}` : " as a value"}: only navigation, expect(page) and waitForReady(page) belong in a step`, "add a method to the page object (pw-ui-pom-writer)");
    }
    // page objects: po.member and po.method(…) only
    if (fixtures.includes(n.name)) {
      if (m === null) push(n, "po-access", `uses the page object ${n.name} ${p?.type === "MemberExpression" && p.object === n && p.computed ? "with computed access" : "as a value (passed on or aliased)"}`, pomFix);
      else if (g?.type === "MemberExpression" && g.object === p && !g.computed && ["call", "apply", "bind"].includes(g.property?.name)) push(n, "po-access", `calls ${n.name}.${m}.${g.property.name}(…) around its call-site check`, pomFix);
      else if (poMembers.methods.has(m) && !called) push(n, "po-access", `takes ${n.name}.${m} without calling it`, pomFix);
    }
    if (n.name === "test") {
      if (m === "step" && called) return;
      if (key === "setup" && HOOKS.includes(m) && called) return;
      if (parkCall && p === parkCall.callee) return;
      if (m === "info" && called) {
        const use = up.at(-3);
        const useName = memberOf(g, use);
        const callsUse = calledAs(use, up.at(-4));
        if (useName && ((useName === "attach" && callsUse) || (["title", "project"].includes(useName) && !callsUse && !written(use, up.at(-4))))) return;
      }
      push(n, "test-reference", `uses test${m ? `.${m}` : ""} (only test.step, the hooks in setup, test.info().attach(…) and reading .title or .project)`, "tests, describes and annotations are generated; an alias or a call of test hides a test or a skip from the gate");
    }
    if (infoNames.has(n.name)) {
      const okUse = m !== null && ((m === "attach" && called) || (["title", "project"].includes(m) && !called && !written(p, g)));
      if (!okUse) push(n, "test-info", `uses ${n.name}${m ? `.${m}` : ""}: testInfo may only attach, or read .title and .project`, "never change a test's status, annotations or expectations from a region");
    }
  });
}

// The rules on the agent's regions of the cases spec (D-055). Steps go through the page objects: no raw locator,
// selector, page script or selector-taking page/frame method; a page object only as `po.member` or `po.method(…)`
// (no computed access, no .call/.apply/.bind, no method reference, never passed or aliased); `page` only as
// `page.<non-selector method>(…)`, in expect(page) or waitForReady(page). `test` only as test.step, and the hooks in
// setup; testInfo (a hook's second parameter, test.info()) only for .attach(…) and reading .title or .project. No skip,
// fixme or fail, except the parking statement `test.fixme(true, '<reason>');` as the very first statement of a test's
// first step. -> {findings, parked: Map test id -> reason}
function regionFindings(file, regions, plan, lineOf, { poMembers }) {
  const out = [];
  const parked = new Map();
  const firstStep = new Map(plan.tests.map((t) => [t.steps.length ? stepKey(t.id, 1) : thenKey(t.id), t.id]));
  const fixtures = uniq(plan.tests.flatMap((t) => t.fixtures));
  for (const [key, lines] of regions) {
    const sig = scanTs(lines.join("\n")).filter((t) => t.type !== "comment");
    const at = (t) => (lineOf(key) ?? 0) + (t?.line ?? 1);
    const push = (t, rule, problem, fix) => out.push(finding("major", file, at(t), rule, `region '${key}' ${problem}`, fix));
    const pomFix = "call the page object as po.method(…) or use po.locator; a missing one is a request to pw-ui-pom-writer";
    const tree = parseAgentCode(lines.join("\n"), { wrap: key !== "setup" });
    for (const m of lines.join("\n").matchAll(/import\s+(?!type\b)[^;]*?from\s*['"]((?:@playwright\/test|playwright)(?:\/[^'"]*)?)['"]/g)) push(null, "test-reference", `imports ${m[1]}: test and expect come from fixtures/ui`, "import from the fixtures, never from Playwright directly");
    if (!tree) {
      push(null, "syntax", "does not parse (TypeScript that only strips to JavaScript; a step region is the body of a function)", "fix the syntax: every bracket the region opens it closes, and it closes none the skeleton opened");
    } else {
      const parkCall = parkingCall(tree.ast, firstStep.has(key));
      if (parkCall) parked.set(firstStep.get(key), staticStr(parkCall.arguments[1]).trim());
      regionAstRules(tree, { key, fixtures, poMembers, parkCall, pomFix, push: (n, rule, problem, fix) => push(n?.loc ? { line: n.loc.start.line } : n, rule, problem, fix) });
    }
    const testId = key.endsWith(" then") ? key.slice(0, -" then".length) : null;
    if (testId && !parked.has(testId)) {
      const t = plan.tests.find((x) => x.id === testId);
      if (t && sig.length) for (const p of thenProblems(sig, t.fixtures)) out.push(finding("major", file, at(sig[0]), "no-assertion", `${testId}: the expected-result step ${p}`, "assert the case's expected result with a web-first expect on a page-object locator, or on data read through a page object"));
    }
  }
  // each test's data region: only `const <name> = <builder>(…);`; its names are never re-declared, shadowed or
  // reassigned anywhere in the test
  const builders = dataBuilders((regions.get("setup") ?? []).join("\n"), plan.module);
  const dataFix = "write only `const <name> = <builder>(…);` with a builder imported from the module's data file in the test's data region, and never re-declare or reassign its names";
  for (const t of plan.tests) {
    const key = dataKey(t.id);
    const { decls, problems } = dataRegionDecls(regions.get(key), builders);
    for (const p of problems) out.push(finding("major", file, (lineOf(key) ?? 0) + p.line, "data-region", `region '${key}' ${p.problem}`, dataFix));
    const names = new Set(decls.keys());
    for (const n of names) if (["page", "test", "expect", ...t.fixtures].includes(n)) out.push(finding("major", file, lineOf(key), "data-region", `region '${key}' declares ${n}, which names a fixture`, dataFix));
    if (!names.size) continue;
    for (const k2 of [...t.steps.map((_, n) => stepKey(t.id, n + 1)), thenKey(t.id)]) {
      const sig = scanTs((regions.get(k2) ?? []).join("\n")).filter((x) => x.type !== "comment");
      const at = (x) => (lineOf(k2) ?? 0) + (x?.line ?? 1);
      const declared = new Set();
      for (let k = 0; k < sig.length; k++) {
        if (!["const", "let", "var"].includes(sig[k].value)) continue;
        if (sig[k + 1]?.type === "ident") declared.add(sig[k + 1]);
        else if (["{", "["].includes(sig[k + 1]?.value)) for (let j = k + 2; j < matchClose(sig, k + 1); j++) if (sig[j].type === "ident" && [",", "}", "]", "="].includes(sig[j + 1]?.value)) declared.add(sig[j]);
      }
      for (const f of functionsOf(sig)) for (const p of f.params) if (p.name && names.has(p.name)) declared.add({ value: p.name, line: sig[f.from]?.line ?? 1 });
      for (const d of declared) if (names.has(d.value)) out.push(finding("major", file, at(d), "data-shadow", `region '${k2}' re-declares ${d.value}, a name of the test's data region: a step would read another value than the one built for the test`, dataFix));
      for (let k = 0; k < sig.length; k++) {
        const x = sig[k];
        if (x.type !== "ident" || !names.has(x.value) || sig[k - 1]?.value === ".") continue;
        const n1 = sig[k + 1]?.value;
        if (n1 === "=" || (["+", "-", "*", "/", "?", "|", "&", "%"].includes(n1) && sig[k + 2]?.value === "=") || (n1 === sig[k + 2]?.value && ["+", "-"].includes(n1)))
          out.push(finding("major", file, at(x), "data-shadow", `region '${k2}' reassigns ${x.value}, a name of the test's data region`, dataFix));
        // a write to a member of the data (c.name = …, c.a.b += …, c['n']++, delete c.n, Object.assign(c, …)) changes the value the test built
        let j = k + 1;
        while ((sig[j]?.value === "." && sig[j + 1]?.type === "ident") || sig[j]?.value === "[") {
          const next = sig[j].value === "." ? j + 2 : matchClose(sig, j) + 1;
          if (next <= j) break;
          j = next;
        }
        const w = sig[j]?.value;
        const written = j > k + 1 && (w === "=" || (["+", "-", "*", "/", "%", "|", "&", "^"].includes(w) && sig[j + 1]?.value === "=") || (["+", "-"].includes(w) && sig[j + 1]?.value === w) || sig[k - 1]?.value === "delete");
        const assigned = sig[k - 1]?.value === "(" && sig[k - 2]?.value === "assign" && sig[k - 3]?.value === "." && sig[k - 4]?.value === "Object" && [",", ")"].includes(n1);
        if (written || assigned) out.push(finding("major", file, at(x), "data-write", `region '${k2}' writes to ${x.value}, the test's data: a step would use another value than the one built for the test`, "build the value in the data builder (its parameters), not in a step"));
      }
    }
  }
  // a parked test's expected step is exempt; collected after every region was read
  return { findings: out.filter((f) => !(f.rule === "no-assertion" && parked.has(f.problem.split(":")[0]))), parked };
}

// ---------- check: stamps ----------

function stampInputs(ctx, plan, scope) {
  const files = { plan: ctx.up.plan, registration: pw(ctx, plan.files.registration), index: pw(ctx, INDEX_FILE), smoke: pw(ctx, plan.files.smoke) };
  for (const o of plan.objects) files[`po:${o.file}`] = pw(ctx, o.file);
  if (scope === "tests") Object.assign(files, { spec: pw(ctx, plan.files.spec), data: pw(ctx, plan.files.data) });
  return files;
}

// The approved cases parked with `test.fixme(true, '<reason>');` in the cases spec: Map id -> reason.
export function parkedOf(ctx, plan = readPlan(ctx)) {
  const text = plan ? readText(pw(ctx, plan.files.spec)) : null;
  if (text === null) return new Map();
  const parsed = parseRegions(text);
  if (parsed.problems.length) return new Map();
  return regionFindings(plan.files.spec, parsed.regions, plan, () => 0, { poMembers: { methods: new Set(), props: new Set() } }).parked;
}

// Records the parked cases in coverage.json: `parked: [{id, reason}]`, and each one's ledger item excluded with reason
// `parked` (approved, but not covered); a case no longer parked is mapped to its test again. -> the parked list
export function recordParked(ctx) {
  const cov = readJson(ctx.up.coverage, null);
  const plan = readPlan(ctx);
  if (!cov || !plan) return [];
  const parked = parkedOf(ctx, plan);
  cov.parked = [...parked].map(([id, reason]) => ({ id, reason }));
  for (const i of cov.items) {
    if (i.kind !== "case") continue;
    if (parked.has(i.id)) {
      delete i.refs;
      Object.assign(i, { status: "excluded", reason: "parked", detail: `approved, parked in ${plan.files.spec}: ${parked.get(i.id)}` });
    } else if (i.reason === "parked") {
      delete i.reason;
      delete i.detail;
      Object.assign(i, { status: "mapped", refs: [plan.files.spec] });
    }
  }
  cov.summary = { total: cov.items.length, ...Object.fromEntries(["mapped", "excluded", "pending", "deferred"].map((st) => [st, cov.items.filter((i) => i.status === st).length])) };
  writeJson(ctx.up.coverage, cov);
  return cov.parked;
}

// Problems that are not rules on the code: the build missing or stale. -> string[]
export function buildProblems(ctx) {
  const cov = readJson(ctx.up.coverage, null);
  const plan = readPlan(ctx);
  const cmd = `node scripts/ui-code.mjs build ${ctx.product} ${ctx.module}`;
  if (!cov || !plan) return [`ui-code/plan.json is missing: run ${cmd} first`];
  const now = inputDigests(ctx);
  const stale = Object.keys(now).filter((k) => now[k] !== cov.built?.inputs?.[k]);
  const out = stale.length ? [`stale: ${stale.join(", ")} changed after the last build (run ${cmd} again)`] : [];
  return [...out, ...(cov.problems ?? [])];
}

// Writes the scope's verified stamp (and, for tests, the pages stamp too: a full check covers both).
export function stampCheck(ctx, scope) {
  const cov = readJson(ctx.up.coverage, null);
  const plan = readPlan(ctx);
  if (!cov || !plan) return;
  const verified = { ...(cov.verified ?? {}) };
  verified.pages = stampVerified(stampInputs(ctx, plan, "pages"));
  if (scope === "tests") verified.tests = stampVerified(stampInputs(ctx, plan, "tests"));
  writeJson(ctx.up.coverage, { ...cov, verified });
}
export function clearStamp(ctx, scope) {
  const cov = readJson(ctx.up.coverage, null);
  if (!cov?.verified?.[scope]) return;
  writeJson(ctx.up.coverage, { ...cov, verified: { ...cov.verified, [scope]: null, ...(scope === "pages" ? { tests: null } : {}) } });
}

// null when the scope passed `ui-code.mjs check` on exactly what is on disk, else why not (the domain flow's verify).
export function uiCodeUnverified(ctx, scope) {
  const cov = readJson(ctx.up.coverage, null);
  const plan = readPlan(ctx);
  const cmd = `ui-code.mjs check ${ctx.product} ${ctx.module}${scope === "pages" ? " --pages" : ""}`;
  if (!cov || !plan) return `ui-code/coverage.json is missing: the writer must run ui-code.mjs build, then ${cmd}`;
  const stale = buildProblems(ctx).filter((p) => p.startsWith("stale"));
  if (stale.length) return stale[0];
  return unverifiedReason(cov.verified?.[scope] ?? null, stampInputs(ctx, plan, scope), { unstamped: `the ${scope === "pages" ? "page objects" : "tests"} never passed ${cmd}`, changed: `the ${scope === "pages" ? "page objects" : "tests"} changed after ${cmd}` });
}

export function uiCodePathsOut(ctx) {
  const plan = readPlan(ctx);
  const r = (f) => rel(ctx.root, f);
  const p = (f) => r(pw(ctx, f));
  return {
    plan: r(ctx.up.plan), coverage: r(ctx.up.coverage), parked: r(ctx.up.parked),
    spec: p(SPEC_FILE(ctx.module)), smoke: p(SMOKE_FILE(ctx.module)), registration: p(REGISTRATION_FILE(ctx.module)), data: p(DATA_FILE(ctx.module)), index: p(INDEX_FILE),
    objects: (plan?.objects ?? []).map((o) => ({ key: o.key, file: p(o.file), class: o.class, fixture: o.fixture, snapshots: o.snapshots.map((s) => `artifacts/${ctx.product}/modules/${ctx.module}/${s}`) })),
  };
}
