// An identifier used as a locator name: a `string` parameter of the innermost named method that declares it (traced to
// its call sites), else an expression the check can't verify.
function resolveName(fns, k, id) {
  const owners = fns.filter((f) => f.from <= k && k < f.to && f.params.some((p) => p.name === id)).sort((a, b) => a.to - a.from - (b.to - b.from));
  const fn = owners[0];
  if (!fn) return { kind: "expr", value: id };
  const index = fn.params.findIndex((p) => p.name === id);
  if (!fn.params[index].string) return { kind: "expr", value: id, why: `parameter '${id}' is not typed string` };
  if (!fn.name || fn.name === "constructor") return { kind: "expr", value: id, why: `parameter '${id}' belongs to ${fn.name ? "the constructor" : "an anonymous function"}, whose call sites can't be traced` };
  return { kind: "param", value: id, fn: fn.name, index };
}

// A name argument: {kind: literal|none|param|regex|expr, value?}
function nameArg(tokens, fns, k) {
  if (!tokens?.length) return { kind: "none" };
  if (tokens.length === 1 && tokens[0].type === "str") return { kind: "literal", value: tokens[0].value };
  if (tokens.length === 1 && tokens[0].type === "regex") return { kind: "regex", value: tokens[0].value };
  if (tokens.length === 1 && tokens[0].type === "ident") return resolveName(fns, k, tokens[0].value);
  return { kind: "expr", value: tokens.map((t) => t.value).join(" ").slice(0, 60) };
}

// The value tokens of `key:` (or the shorthand `key`) in an object-literal argument; null when absent.
function optionValue(tokens, key) {
  if (tokens?.[0]?.value !== "{") return null;
  let depth = 0;
  for (let k = 0; k < tokens.length; k++) {
    const t = tokens[k];
    if (isOpen(t)) depth++;
    else if (isClose(t)) depth--;
    else if (depth === 1 && t.type === "ident" && t.value === key && ["{", ","].includes(tokens[k - 1]?.value)) {
      if (tokens[k + 1]?.value === ":") {
        const out = [];
        let d = 0;
        for (let j = k + 2; j < tokens.length; j++) {
          const u = tokens[j];
          if (isOpen(u)) d++;
          if (isClose(u)) {
            if (d === 0) break;
            d--;
          }
          if (d === 0 && u.value === ",") break;
          out.push(u);
        }
        return out;
      }
      if ([",", "}"].includes(tokens[k + 1]?.value)) return [t];
    }
  }
  return null;
}
// An options argument the check can read: absent, or an object literal without a spread.
function optionsProblem(tokens, what) {
  if (!tokens?.length) return null;
  if (tokens[0].value !== "{") return `${what}'s options must be an object literal (found ${tokens.map((t) => t.value).join(" ").slice(0, 40)})`;
  let d = 0;
  for (const t of tokens) {
    if (isOpen(t)) d++;
    else if (isClose(t)) d--;
    else if (d === 1 && t.value === "...") return `${what}'s options may not spread another object`;
  }
  return null;
}

// Does the call whose method name is sig[k] (after a ".") run on a page or a frame: `page.x(`, `this.page.x(`,
// `frame.x(`, `page.mainFrame().x(`, `page.frames()[0].x(`?
export function onPage(sig, k) {
  const r = sig[k - 2];
  if (!r) return false;
  if (r.type === "ident") return /^(page|frame)$/i.test(r.value);
  if (r.value === ")") return FRAME_GETTERS.includes(sig[matchOpen(sig, k - 2) - 1]?.value);
  if (r.value === "]") return FRAME_GETTERS.includes(sig[matchOpen(sig, matchOpen(sig, k - 2) - 1) - 1]?.value);
  return false;
}

// Every locator, selector and script call of a TypeScript file, with the class properties and the methods.
// -> {calls: [{method, line, index, role?, name?: {kind, value, fn?, index?}, exact?, option?, selector?, reason?,
//     problem?}], props: [{name, line, from, to, private, locator}], fns, classes: [names exported]}
export function parseLocators(text) {
  const all = scanTs(text);
  const sig = all.filter((t) => t.type !== "comment");
  const comments = all.filter((t) => t.type === "comment");
  const fns = functionsOf(sig);
  const reasonAt = (line) => {
    const m = comments.filter((c) => c.line <= line && c.line >= line - 3).map((c) => REASON_RE.exec(c.value)).find(Boolean);
    return m ? { kind: m[1].toLowerCase(), text: m[2], cite: m[3] } : null;
  };
  // properties first: `this.<name> = <expr>` and `readonly <name>[: T] = <expr>`, each expression up to `;`, the end
  // of its block, or a new statement on a later line; `locator` when the expression builds one with a checked call
  const props = [];
  const stmtEnd = (from) => {
    let depth = 0;
    for (let j = from; j < sig.length; j++) {
      const u = sig[j];
      if (isOpen(u)) depth++;
      else if (isClose(u)) {
        if (depth === 0) return j;
        depth--;
      } else if (depth === 0 && u.value === ";") return j;
      else if (depth === 0 && j > from && u.line > sig[j - 1].line && u.value !== "." && ![".", ",", "(", "=", "=>", "?", ":", "&&", "||", "+", "??"].includes(sig[j - 1].value)) return j;
    }
    return sig.length;
  };
  const isPrivate = (name) => new RegExp(`\\b(private|protected)\\s+(readonly\\s+)?${name.replace(/\$/g, "\\$")}\\b`).test(text);
  const buildsLocator = (from, to) => sig.slice(from, to).some((u, i, xs) => u.type === "ident" && (LOCATOR_METHODS.includes(u.value) || u.value === "locator") && xs[i - 1]?.value === "." && xs[i + 1]?.value === "(");
  for (let k = 0; k < sig.length - 3; k++) {
    let name = null;
    let eq = -1;
    if (sig[k].value === "this" && sig[k + 1].value === "." && sig[k + 2].type === "ident" && sig[k + 3].value === "=") [name, eq] = [sig[k + 2].value, k + 3];
    else if (sig[k].value === "readonly" && sig[k + 1].type === "ident") {
      let j = k + 2;
      if (sig[j]?.value === ":") while (j < sig.length && sig[j].value !== "=" && sig[j].value !== ";" && sig[j].line === sig[k].line) j++;
      if (sig[j]?.value === "=") [name, eq] = [sig[k + 1].value, j];
    }
    if (name === null) continue;
    const to = stmtEnd(eq + 1);
    props.push({ name, line: sig[k].line, from: eq + 1, to, private: isPrivate(name), locator: buildsLocator(eq + 1, to) });
  }
  // `.locator(<a Locator>)` chains locators: this.<a property every assignment of which builds a locator>, or an
  // expression that builds one with getBy*. A field holding a string is a selector, not a chain.
  const locatorProp = (n) => props.some((p) => p.name === n) && props.filter((p) => p.name === n).every((p) => p.locator);
  const isLocatorExpr = (tokens) =>
    (tokens.length === 3 && tokens[0].value === "this" && tokens[1].value === "." && tokens[2].type === "ident" && locatorProp(tokens[2].value)) ||
    (tokens[0]?.type === "ident" && tokens.some((u, i) => u.type === "ident" && LOCATOR_METHODS.includes(u.value) && tokens[i - 1]?.value === "." && tokens[i + 1]?.value === "("));
  const methods = new Set(fns.map((f) => f.name).filter(Boolean));
  const calls = [];
  for (let k = 0; k < sig.length; k++) {
    const t = sig[k];
    // page['getByText'](…), this['row'](…): computed access hides a call from every rule
    if (t.value === "[" && ((sig[k + 1]?.type === "str" && (RAW_METHODS.includes(sig[k + 1].value) || PAGE_SELECTOR_METHODS.includes(sig[k + 1].value) || methods.has(sig[k + 1].value))) || sig[k - 1]?.value === "this")) {
      calls.push({ method: String(sig[k + 1]?.value ?? "[…]"), line: t.line, index: k, problem: `computed access (${sig[k - 1]?.value ?? ""}[${sig[k + 1]?.type === "str" ? `'${sig[k + 1].value}'` : "…"}]) hides a call from the check: call it as .name(…)` });
      continue;
    }
    // this.row.call(…), .apply(…), .bind(…): a page-object method called around its call-site check
    if (t.type === "ident" && ["call", "apply", "bind"].includes(t.value) && sig[k - 1]?.value === "." && methods.has(sig[k - 2]?.value) && sig[k + 1]?.value === "(") {
      calls.push({ method: sig[k - 2].value, line: t.line, index: k, problem: `${sig[k - 2].value}.${t.value}(…) calls a page-object method around its call-site check: call it as .${sig[k - 2].value}(…)` });
      continue;
    }
    if (t.type !== "ident" || sig[k - 1]?.value !== "." || sig[k + 1]?.value !== "(") continue;
    const m = t.value;
    const { args } = callArgs(sig, k + 1);
    const base = { method: m, line: t.line, index: k };
    if (LOCATOR_METHODS.includes(m)) {
      const call = { ...base };
      if (m === "getByRole") {
        const role = nameArg(args[0], fns, k);
        call.role = role.kind === "literal" ? role.value : null;
        call.problem = optionsProblem(args[1], "getByRole") ?? undefined;
        call.name = call.problem ? { kind: "expr", value: "(options)" } : nameArg(optionValue(args[1], "name"), fns, k);
        const exact = optionValue(args[1], "exact");
        call.exact = exact?.length === 1 && exact[0].value === "true";
      } else {
        call.problem = optionsProblem(args[1], m) ?? undefined;
        call.name = nameArg(args[0], fns, k);
      }
      if (!call.problem) delete call.problem;
      calls.push(call);
    } else if (m === "filter" && args[0]?.[0]?.value === "{") {
      const bad = optionsProblem(args[0], "filter");
      if (bad) calls.push({ ...base, problem: bad });
      for (const key of ["hasText", "hasNotText"]) {
        const v = optionValue(args[0], key);
        if (v) calls.push({ ...base, option: key, name: nameArg(v, fns, k) });
      }
    } else if (SELECTOR_METHODS.includes(m) || (PAGE_SELECTOR_METHODS.includes(m) && onPage(sig, k))) {
      const first = args[0] ?? [];
      if (m === "locator" && isLocatorExpr(first)) continue;
      if (first.length === 1 && first[0].type === "str") calls.push({ ...base, selector: first[0].value, reason: reasonAt(t.line) });
      else calls.push({ ...base, selector: first.map((x) => x.value).join(" ").slice(0, 80), problem: `${m}()'s selector must be a string literal (found ${first.map((x) => x.value).join(" ").slice(0, 40) || "nothing"})` });
    } else if (EVAL_METHODS.includes(m)) calls.push({ ...base, selector: "(page script)", evaluate: true, reason: reasonAt(t.line) });
  }
  const classes = [...text.matchAll(/\bexport\s+(?:default\s+)?class\s+([A-Za-z_$][\w$]*)/g)].map((m) => m[1]);
  return { calls, props, fns, classes };
}

// The call sites `.<method>(…)` of a file: [{line, args: [{literal?: string, text, tokens}]}]
export function callSitesIn(text, method) {
  const sig = scanTs(text).filter((t) => t.type !== "comment");
  const out = [];
  for (let k = 1; k < sig.length - 1; k++) {
    if (sig[k].value !== method || sig[k].type !== "ident" || sig[k - 1].value !== "." || sig[k + 1].value !== "(") continue;
    const { args } = callArgs(sig, k + 1);
    out.push({ line: sig[k].line, args: args.filter((a) => a.length).map((a) => ({ ...(a.length === 1 && a[0].type === "str" ? { literal: a[0].value } : {}), text: a.map((x) => x.value).join(" ").slice(0, 40), tokens: a })) });
  }
  return out;
}

// The builders a file imports from the module's data file (helpers/ui/<m>.data.ts): local names.
export function dataBuilders(text, module) {
  const builders = new Set();
  const from = new RegExp(`(^|/)helpers/ui/${module.replace(/[-]/g, "\\-")}\\.data(\\.ts)?$`);
  for (const m of String(text ?? "").matchAll(/import\s*\{([^}]*)\}\s*from\s*['"]([^'"]+)['"]/g))
    if (from.test(m[2])) for (const n of m[1].split(",")) {
      if (/^\s*type\s/.test(n)) continue;
      const parts = n.trim().split(/\s+as\s+/);
      const local = (parts[1] ?? parts[0]).trim();
      if (local) builders.add(local);
    }
  return builders;
}

// A test's data region (D-055): nothing but `const <name> = [await] <builder>(…);` statements, with <builder> imported
// from the module's data file. -> {decls: Map name -> builder, problems: [{line, problem}]}
export function dataRegionDecls(lines, builders) {
  const sig = scanTs((lines ?? []).join("\n")).filter((t) => t.type !== "comment");
  const decls = new Map();
  const problems = [];
  for (let k = 0; k < sig.length; ) {
    if (sig[k].value === ";") {
      k++;
      continue;
    }
    const t = sig[k];
    let j = k + 3;
    if (sig[j]?.value === "await") j++;
    const ok = t.value === "const" && sig[k + 1]?.type === "ident" && sig[k + 2]?.value === "=" && sig[j]?.type === "ident" && builders.has(sig[j].value) && sig[j + 1]?.value === "(";
    if (!ok) {
      problems.push({ line: t.line, problem: `holds ${sig.slice(k, k + 4).map((x) => x.value).join(" ")} …: a data region holds only \`const <name> = <builder>(…);\` with a builder from the module's data file` });
      while (k < sig.length && sig[k].value !== ";" && !(k > 0 && sig[k].line > sig[k - 1].line && sig[k].value === "const")) k++;
      continue;
    }
    const close = matchClose(sig, j + 1);
    if (decls.has(sig[k + 1].value)) problems.push({ line: t.line, problem: `declares ${sig[k + 1].value} twice` });
    decls.set(sig[k + 1].value, sig[j].value);
    k = close + 1;
    if (sig[k] && sig[k].value !== ";" && sig[k].line === sig[close].line) problems.push({ line: sig[k].line, problem: `has more after ${sig[k - 1].value}: one builder call per const` });
  }
  return { decls, problems };
}

// The data-bound names inside one step region: the test's data names (each with its builder and an empty path), plus
// the region's own `const x = <bound>[.<member>…]` derivations. A name the region re-declares otherwise is dropped
// (and is a finding of its own). -> Map name -> {builder, path}
function deriveBound(sig, initial) {
  const bound = new Map(initial);
  const decls = [];
  for (let k = 0; k < sig.length; k++) {
    if (!["const", "let", "var"].includes(sig[k].value)) continue;
    let names = [];
    let eq = k + 2;
    if (sig[k + 1]?.type === "ident") names = [sig[k + 1].value];
    else if (sig[k + 1]?.value === "{" || sig[k + 1]?.value === "[") {
      const close = matchClose(sig, k + 1);
      for (let j = k + 2; j < close; j++) if (sig[j].type === "ident" && [",", "}", "]", "="].includes(sig[j + 1]?.value)) names.push(sig[j].value);
      eq = close + 1;
    }
    if (sig[eq]?.value === ":") while (eq < sig.length && sig[eq].value !== "=") eq++;
    let end = eq + 1;
    for (let d = 0; end < sig.length; end++) {
      if (isOpen(sig[end])) d++;
      else if (isClose(sig[end])) {
        if (!d) break;
        d--;
      } else if (!d && [";", ","].includes(sig[end].value)) break;
    }
    decls.push({ kind: sig[k].value, destructured: sig[k + 1]?.value !== names[0], names, init: sig[eq]?.value === "=" ? sig.slice(eq + 1, end) : [] });
  }
  for (const d of decls) for (const n of d.names) bound.delete(n); // every re-declaration shadows
  for (let changed = true; changed; ) {
    changed = false;
    for (const d of decls) {
      if (d.kind !== "const" || d.destructured || d.names.length !== 1 || bound.has(d.names[0])) continue;
      const init = d.init;
      const root = init[0]?.type === "ident" ? (initial.get(init[0].value) && !decls.some((x) => x.names.includes(init[0].value)) ? initial.get(init[0].value) : bound.get(init[0].value)) : null;
      if (root && init.every((u, i) => (i % 2 ? u.value === "." : u.type === "ident"))) {
        bound.set(d.names[0], { builder: root.builder, path: [...root.path, ...init.filter((u, i) => i > 0 && i % 2 === 0).map((u) => u.value)] });
        changed = true;
      }
    }
  }
  return bound;
}

// The data bindings at each line of the cases spec: per test, its data region's names in every region of the test,
// plus each region's own derivations. -> (line) -> Map name -> {builder, path}
export function specBindings(ctx, text) {
  const plan = readPlan(ctx);
  const parsed = parseRegions(text);
  if (!plan || parsed.problems.length) return () => new Map();
  const builders = dataBuilders((parsed.regions.get("setup") ?? []).join("\n"), ctx.module);
  const lines = String(text).split("\n");
  const ranges = [];
  for (const t of plan.tests) {
    const { decls } = dataRegionDecls(parsed.regions.get(dataKey(t.id)), builders);
    const initial = new Map([...decls].map(([name, builder]) => [name, { builder, path: [] }]));
    for (const key of [...t.steps.map((_, n) => stepKey(t.id, n + 1)), thenKey(t.id)]) {
      const body = parsed.regions.get(key) ?? [];
      const at = lines.findIndex((l) => BEGIN.exec(l)?.[1] === key) + 1;
      ranges.push({ from: at + 1, to: at + body.length, bound: deriveBound(scanTs(body.join("\n")).filter((x) => x.type !== "comment"), initial) });
    }
  }
  return (line) => ranges.find((r) => line >= r.from && line <= r.to)?.bound ?? new Map();
}
// An argument that is data from the module's builders: a bound identifier, or a member of one. -> {builder, path} | null
const boundArg = (tokens, bound) =>
  tokens?.[0]?.type === "ident" && bound.has(tokens[0].value) && tokens.every((u, i) => (i % 2 ? u.value === "." : u.type === "ident"))
    ? { builder: bound.get(tokens[0].value).builder, path: [...bound.get(tokens[0].value).path, ...tokens.filter((u, i) => i > 0 && i % 2 === 0).map((u) => u.value)] }
    : null;

// ---------- snapshots: what a locator may name ----------

const norm = (s) => String(s ?? "").replace(/\s+/g, " ").trim();
// -> {nodes: [{role, name}], texts: [every node's name and text, whitespace collapsed], testIds, placeholders, raw}
export function snapshotFacts(text) {
  const { root } = parseSnapshot(text);
  const nodes = [];
  const texts = new Set();
  const testIds = new Set();
  const placeholders = new Set();
  const visit = (node) => {
    for (const c of node.children) {
      nodes.push({ role: c.role, name: c.name });
      for (const s of [c.name, c.value]) if (typeof s === "string" && norm(s)) texts.add(norm(s));
      for (const [k, v] of Object.entries(c.attrs ?? {})) if (/^(data-)?test-?id$/i.test(k) && typeof v === "string") testIds.add(v.replace(/^["']|["']$/g, ""));
      if (typeof c.props?.placeholder === "string") placeholders.add(c.props.placeholder);
      visit(c);
    }
  };
  visit(root);
  return { nodes, texts, testIds, placeholders, raw: text };
}

// Does one snapshot show what a locator call names, verbatim: a node of that role with exactly that name, a label,
// placeholder or test id equal to it, or a node whose whole name or text equals it (never a substring)?
export function shows(facts, call) {
  const v = call.name?.value;
  if (call.method === "getByRole") return facts.nodes.some((x) => x.role === call.role && (call.name.kind === "none" || x.name === v));
  if (call.method === "getByLabel") return facts.nodes.some((x) => x.name === v);
  if (call.method === "getByTestId") return facts.testIds.has(v);
  if (call.method === "getByPlaceholder") return facts.placeholders.has(v);
  return facts.texts.has(norm(v));
}

// Why a locator call can't be verified, or null. facts: the snapshots of the object's page template. A selector or a
// parameter is judged elsewhere (its reason, its call sites).
export function locatorProblem(call, facts) {
  if (call.problem) return call.problem;
  if (call.selector !== undefined) return null;
  const what0 = call.option ? `filter({ ${call.option} })` : call.method;
  if (call.method === "getByRole" && !call.role) return "getByRole needs a literal role";
  const { kind } = call.name;
  if (kind === "param") return null;
  if (kind === "regex") return `${what0} with a regular expression (${call.name.value}) can't be checked against the snapshots: use the name verbatim`;
  if (kind === "expr") return `${what0}'s name must be a string literal copied from a snapshot, or a string parameter of its method (found ${call.name.value}${call.name.why ? `: ${call.name.why}` : ""})`;
  if (kind === "none" && call.method !== "getByRole") return `${what0} needs a literal`;
  if (facts.some((f) => shows(f, call))) return null;
  const what = call.method === "getByRole" ? `role '${call.role}'${kind === "none" ? "" : ` named '${call.name.value}'`}` : `'${call.name.value}'`;
  return `${what0}: ${what} is in none of the template's state snapshots (names are copied verbatim, whole)`;
}

