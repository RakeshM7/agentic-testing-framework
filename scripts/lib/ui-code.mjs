function flowStates(ctx) {
  const dir = ctx.xp.flows;
  const out = new Map();
  if (!existsSync(dir)) return out;
  for (const f of readdirSync(dir).filter((x) => x.endsWith(".md")).sort()) out.set(f, uniq(readFileSync(path.join(dir, f), "utf8").match(ST_RE) ?? []));
  return out;
}

// The states a case touches, through its coverage items (field states, transition ends, the states its flow names)
// and its observation evidence (a state snapshot it cites). -> [ST ids known to the model]
export function touchedStates(c, { itemsById, model, flows }) {
  const known = new Map((model?.states ?? []).map((s) => [s.id, s]));
  const pageBySlug = new Map((model?.pages ?? []).map((p) => [p.slug, p]));
  const out = new Set();
  for (const id of c.covers ?? []) {
    const it = itemsById.get(id);
    if (!it) continue;
    for (const st of it.field?.states ?? []) out.add(st);
    if (it.field?.page && pageBySlug.has(it.field.page) && !(it.field.states ?? []).length) out.add(pageBySlug.get(it.field.page).states[0]);
    if (it.transition) [it.transition.from, it.transition.to].forEach((s) => out.add(s));
    if (it.technique === "flow") for (const st of flows.get(String(it.subject).replace(/^flows\//, "")) ?? []) out.add(st);
  }
  for (const e of c.evidence ?? []) {
    if (!e.startsWith("observation:")) continue;
    for (const st of e.match(ST_RE) ?? []) out.add(st);
    const slug = /explore\/pages\/([^/]+)\//.exec(e)?.[1];
    if (slug && pageBySlug.has(slug) && !(e.match(ST_RE) ?? []).length) out.add(pageBySlug.get(slug).states[0]);
  }
  return [...out].filter((s) => s && known.has(s)).sort(byNum);
}

// A recorded URL as a path under BASE_URL, or null off the target's host. Query parameters that can carry a credential
// (token, auth, session, key, signature, code, password, secret) and the fragment are dropped: the smoke is committed code.
const SECRET_PARAM = /token|auth|session|key|sig|code|pass|secret|jwt/i;
const pathOf = (url, target) => {
  try {
    const u = new URL(url);
    if (target && new URL(target).origin !== u.origin) return null;
    for (const k of [...u.searchParams.keys()]) if (SECRET_PARAM.test(k)) u.searchParams.delete(k);
    return `${u.pathname}${u.search}` || "/";
  } catch {
    return null;
  }
};

// Why the smoke may not replay a click on a recorded control, or null: only a navigation-like role, outside any form
// or dialog, whose name neither signs out nor commits (lib/explore.mjs mutatesControl with the control's context,
// plus the smoke's own commit words, for every role including links).
export function smokeClickProblem(c) {
  if (!CLICK_ROLES.includes(c.role)) return `needs ${c.role} input, which is not readonly-safe`;
  if (c.inForm || c.inDialog) return "is inside a form or dialog";
  const name = String(c.name ?? "");
  if (LOGOUT.test(name)) return "signs out";
  if (mutatesControl({ role: c.role, name, inForm: !!c.inForm, inDialog: !!c.inDialog, pointer: c.pointer })) return "may change data";
  if (name.toLowerCase().split(/[^a-z]+/).some((w) => SMOKE_COMMIT.has(w) && !(w === "open" && c.role === "link" && c.url))) return "may change data";
  return null;
}

// How the smoke reaches a state: goto a recorded URL, then replay recorded clicks that are readonly-safe: each control
// found exactly once in the snapshot of the state it was clicked in, followed by a recorded transition into a state for
// which the exploration's network inventory holds no request other than GET. -> {url, clicks, state} | {state, skip}
function smokeRoute(ctx, state, { viaReach, model }) {
  if (!viaReach) {
    const url = pathOf(state.url, ctx.targetUrl);
    return url ? { state: state.id, url, clicks: [] } : { state: state.id, skip: `${state.id}'s URL is not on the target's host` };
  }
  const skip = (why) => ({ state: state.id, skip: why });
  const reach = state.reach;
  if (!reach) return skip(`no recorded path reaches ${state.id}`);
  const url = pathOf(reach.url, ctx.targetUrl);
  if (!url) return skip(`the recorded path to ${state.id} starts off the target's host`);
  const statesById = new Map((model?.states ?? []).map((s) => [s.id, s]));
  const inventory = readJson(ctx.xp.inventory, []);
  const writes = (Array.isArray(inventory) ? inventory : []).filter((e) => String(e.method ?? "").toUpperCase() !== "GET");
  const steps = reach.steps ?? [];
  const clicks = [];
  let cur = reach.from;
  for (let i = 0; i < steps.length; i++) {
    const a = parseAction(steps[i]);
    if (!a) return skip(`the recorded path to ${state.id} has a step the smoke can't replay (${steps[i]})`);
    const st = statesById.get(cur);
    const text = st ? stateSnapshot(ctx, st) : null;
    if (!text) return skip(`the snapshot of ${cur} is missing`);
    const c = extractControls(parseSnapshot(text).root).find((x) => x.role === a.role && (x.name === a.name || x.names.includes(a.name)));
    if (!c) return skip(`${steps[i]} is not in ${cur}'s snapshot`);
    if (c.occurrences > 1) return skip(`${steps[i]} appears ${c.occurrences} times in ${cur}'s snapshot, so a click can't target the recorded element`);
    const why = smokeClickProblem(c);
    if (why) return skip(`the recorded path to ${state.id} clicks ${steps[i]}, which ${why}`);
    clicks.push({ role: a.role, name: a.name });
    const t = (model?.transitions ?? []).find((x) => x.from === cur && x.actions.length === 1 && x.actions[0] === steps[i]);
    if (t) cur = t.to;
    else if (i === steps.length - 1) cur = state.id;
    else return skip(`no recorded transition follows ${steps[i]} from ${cur}`);
    const sent = writes.filter((w) => (w.states ?? []).includes(cur));
    if (sent.length) return skip(`the recorded transition into ${cur} sent ${sent[0].method} ${sent[0].pathTemplate ?? ""}`.trim());
  }
  return { state: state.id, url, clicks };
}

