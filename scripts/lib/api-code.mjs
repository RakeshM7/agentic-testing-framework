const BEGIN = /^\s*\/\/ api-code:begin (\S.*?)\s*$/;
const END = /^\s*\/\/ api-code:end (\S.*?)\s*$/;

// -> {regions: Map key -> lines[], problems}
export function parseSlots(text) {
  const regions = new Map();
  const problems = [];
  let open = null;
  let body = [];
  String(text ?? "").replace(/\r\n?/g, "\n").split("\n").forEach((l, i) => {
    const b = BEGIN.exec(l);
    const e = END.exec(l);
    if (b) {
      if (open) problems.push(`line ${i + 1}: slot '${b[1]}' starts inside slot '${open}'`);
      open = b[1];
      body = [];
    } else if (e) {
      if (!open) problems.push(`line ${i + 1}: 'api-code:end ${e[1]}' without its begin`);
      else if (e[1] !== open) problems.push(`line ${i + 1}: slot '${open}' ends as '${e[1]}'`);
      else if (regions.has(open)) problems.push(`line ${i + 1}: slot '${open}' appears twice`);
      else regions.set(open, body);
      open = null;
    } else if (open) body.push(l);
  });
  if (open) problems.push(`slot '${open}' never ends`);
  return { regions, problems };
}
const slot = (key, body, indent) => [`${indent}// api-code:begin ${key}`, ...(body ?? []), `${indent}// api-code:end ${key}`];
