// Member names that reach around a check: the function constructor, a call with another receiver, a raw request.
const DANGEROUS_MEMBERS = new Set(["constructor", "prototype", "__proto__", "call", "apply", "bind", "fetch", "newContext", "request", "__defineGetter__", "__lookupGetter__", "__defineSetter__", "__lookupSetter__"]);
const RAW = new Set(["request", "APIRequestContext", "newContext", "playwright", "playwrightRequest", "fetch", "axios", "http", "https", "http2", "net", "tls", "XMLHttpRequest", "WebSocket", "EventSource", "child_process"]);
// The built-ins a test's assertions and runtime checks rely on: agent code never changes one (B3).
export const BUILTINS = new Set(["Object", "Array", "JSON", "Math", "String", "Number", "Boolean", "Symbol", "Promise", "Date", "RegExp", "Map", "Set", "WeakMap", "WeakSet", "Error", "TypeError", "RangeError", "Function", "Intl", "BigInt", "Atomics", "console", "Buffer", "URL", "URLSearchParams", "Uint8Array", "ArrayBuffer", "DataView", "globalThis", "global", "window", "self", "Reflect", "Proxy", "structuredClone", "encodeURIComponent", "decodeURIComponent", "parseInt", "parseFloat", "isNaN", "process", "expect", "test"]);
const PATCH_CALLS = new Set(["defineProperty", "defineProperties", "setPrototypeOf", "getPrototypeOf", "getOwnPropertyDescriptor", "getOwnPropertyDescriptors", "__defineGetter__", "__defineSetter__"]);
const isKey = (sig, k) => ["{", ","].includes(sig[k - 1]?.value) && sig[k + 1]?.value === ":";
const memberAccess = (prev) => prev && (prev.type === "ident" || prev.type === "str" || [")", "]", "}"].includes(prev.value)) && !["return", "typeof", "in", "of", "case", "await", "yield", "new", "delete", "void", "throw", "const", "let", "var", "else", "do", "export", "default", "instanceof"].includes(prev.value);

// The names a piece of code declares itself (const, let, var, function, class, parameters, destructuring).
function localNames(sig) {
  const out = new Set();
  for (let k = 0; k < sig.length; k++) {
    if (["const", "let", "var", "function", "class"].includes(sig[k].value)) {
      if (sig[k + 1]?.type === "ident") out.add(sig[k + 1].value);
      else if (["{", "["].includes(sig[k + 1]?.value)) for (let j = k + 2; j < matchClose(sig, k + 1); j++) if (sig[j].type === "ident" && [",", "}", "]", "="].includes(sig[j + 1]?.value)) out.add(sig[j].value);
    }
  }
  for (const f of functionsOf(sig)) for (const p of f.params) if (p.name) out.add(p.name);
  return out;
}

// B3: no change to a built-in, a prototype, globalThis, or (strict) any object the code did not create itself (a literal
// or a construction in the same code, agent-scope.mjs createdNames; never a parameter or an alias): no
// assignment to a member of one, no delete of one, no Object.assign onto one, no defineProperty, setPrototypeOf,
// getPrototypeOf or the like. strict: off for page objects, whose constructors assign their own `this` fields.
export function builtinPatchFindings(file, code, at, { strict = true, wrap = false } = {}) {
  const out = [];
  const tree = parseAgentCode(code, { wrap });
  if (!tree) return out; // the parse finding is the property rules' and the free-identifier rule's
  const push = (n, problem) => out.push(finding("major", file, at({ line: n.loc.start.line }), "builtin-patch", problem, "never change a built-in or an object you did not create here: the generated assertions and the runtime checks rely on them"));
  const locals = strict ? createdNames(tree) : new Set();
  // the root and the members of the member chain that ends at a target: names, root first; root: the node it starts at
  const chain = (target) => {
    const names = [];
    let n = target;
    let called = false;
    for (;;) {
      if (n.type === "MemberExpression") {
        const p = n.property;
        names.push(`${!n.computed && p.type === "Identifier" ? p.name : n.computed && p.type === "Literal" ? String(p.value) : "[]"}${called ? "()" : ""}`);
        called = false;
        n = n.object;
      } else if (n.type === "CallExpression" || n.type === "NewExpression") {
        called = true;
        n = n.callee;
      } else if (n.type === "ChainExpression" || n.type === "TSNonNullExpression") n = n.expression;
      else if (n.type === "ParenthesizedExpression") n = n.expression;
      else break;
    }
    if (n.type === "Identifier") names.push(`${n.name}${called ? "()" : ""}`);
    else if (n.type === "ThisExpression") names.push("this");
    else if (["ObjectExpression", "ArrayExpression"].includes(n.type) && !called) return { names: [], root: null }; // a fresh object: its own
    else names.push("(expression)");
    return { names: names.reverse(), root: n };
  };
  const rootName = (names) => names[0].replace(/\(\)$/, "");
  const target = (t, at2) => {
    if (t.type !== "MemberExpression") return;
    const { names } = chain(t);
    if (names.length < 2) return;
    const root = rootName(names);
    if (BUILTINS.has(root) || names.some((x) => ["prototype", "__proto__", "getPrototypeOf()", "constructor"].includes(x))) push(at2, `assigns to ${names.join(".")}: a built-in or a prototype`);
    else if (strict && !locals.has(root)) push(at2, `assigns to ${names.join(".")}, a member of an object this code did not create (${root})`);
  };
  // `a.b = v`, `a[b] = v`, `a.b += v`, `a.b ??= v`, `a.b++`, a destructuring or for-of target: a member written
  for (const w of writesOf(tree)) target(w.target, w.node);
  astWalk(tree.ast, (n) => {
    // delete (round 4): strict, only `delete <name>.<member>` of an object this code created, nothing deeper, computed or
    // parenthesised; not strict (page objects), never a member of a built-in
    if (n.type === "UnaryExpression" && n.operator === "delete") {
      const a = n.argument;
      const root = a.type === "MemberExpression" ? rootName(chain(a).names.length ? chain(a).names : ["(expression)"]) : a.type === "Identifier" ? a.name : "(expression)";
      const plain = a.type === "MemberExpression" && !a.computed && a.object.type === "Identifier" && a.property.type === "Identifier";
      if (BUILTINS.has(root) || (strict && !(plain && locals.has(root)))) push(n, `deletes ${plain ? `a member of ${root}` : "something other than a member of an object this code created"}`);
    }
    if (n.type !== "CallExpression" || n.callee.type !== "MemberExpression") return;
    const m = n.callee;
    const name = !m.computed && m.property.type === "Identifier" ? m.property.name : m.computed && m.property.type === "Literal" ? String(m.property.value) : null;
    if (name !== null && PATCH_CALLS.has(name)) push(m.property, `calls ${name}: it reaches or changes an object's prototype or property definitions`);
    if (name === "assign" && m.object.type === "Identifier" && m.object.name === "Object" && n.arguments[0]?.type !== "ObjectExpression") push(m.property, `Object.assign onto ${n.arguments[0] ? tree.src.slice(n.arguments[0].start, n.arguments[0].end).slice(0, 40) : "nothing"}: only onto a new object literal`);
  });
  return out;
}
// B1: an agent file (a helper, a page object, a composite helper) never takes the test runner: no value import of
// `test` or `expect`, from the fixtures, @playwright/test or anywhere, so it can't add hooks, skip, override fixtures
// or replace an assertion for the specs that import it. Type-only imports are fine.
export function runnerImportFindings(file, text) {
  const out = [];
  const src = String(text ?? "");
  for (const m of src.matchAll(/\bimport\s+(type\s+)?([^;]*?)\s*from\s*['"]([^'"]+)['"]/g)) {
    if (m[1]) continue;
    const names = (/\{([^}]*)\}/.exec(m[2])?.[1] ?? "").split(",").map((s) => s.trim()).filter((s) => s && !/^type\s/.test(s)).map((s) => s.split(/\s+as\s+/)[0].trim());
    const bad = names.filter((n) => n === "test" || n === "expect");
    const whole = /\*\s*as\s+\w+/.test(m[2]) && /(^|\/)(fixtures\/(ui|api)(\/index)?|@playwright\/test|playwright(\/test)?)$/.test(m[3].replace(/\.ts$/, ""));
    if (bad.length || whole) out.push(finding("major", file, src.slice(0, m.index).split("\n").length, "test-runner-import", `${file} imports ${bad.length ? bad.join(" and ") : "the test runner as a namespace"} from ${m[3]}`, "only a spec uses test and expect; a helper, page object or composite helper never adds hooks, skips or assertions"));
  }
  if (/\brequire\s*\(\s*['"](@playwright\/test|playwright)/.test(src) || /\bimport\s*\(\s*['"](@playwright\/test|playwright)/.test(src)) out.push(finding("major", file, null, "test-runner-import", `${file} loads the test runner at run time`, "only a spec uses test and expect"));
  return out;
}

// The literal rules on agent code: no URL, no host of the target, no credential or token, however the string is written
// (escapes are cooked by the scanner; pieces joined with + or ${} are read by foundation.mjs literalProblems).
function literalFindings(ctx, file, text, sig, at) {
  const out = [];
  const hostRe = ctx.hosts.length ? new RegExp(`(^|[^A-Za-z0-9.-])(${ctx.hosts.map((h) => h.replace(/[.]/g, "\\.")).join("|")})($|[^A-Za-z0-9.-])`, "i") : null;
  for (const t of sig) {
    if (t.type !== "str" && t.type !== "tpl") continue;
    const v = String(t.value);
    if (URL_RE.test(v) || /(^|[^:])\/\/[a-z0-9-]+(\.[a-z0-9-]+)+/i.test(v)) out.push(finding("major", file, at(t), "hardcoded", `a hard-coded URL (${v.slice(0, 60)})`, "never a URL in test code: the clients send paths, and the base URL comes from API_BASE_URL"));
    else if (hostRe?.test(v)) out.push(finding("major", file, at(t), "hardcoded", `a hard-coded host of the target (${v.slice(0, 60)})`, "never name the product's host: the base URL comes from the environment"));
    if (SECRET_RES.some((re) => re.test(v)) || SECRET_RES.some((re) => re.test(`token: '${v}'`) && /^(eyJ|AKIA|gh[pousr]_|xox|AIza|sk_|pk_|rk_)/.test(v))) out.push(finding("major", file, at(t), "hardcoded", "a hard-coded credential or token", "never a secret in code: build secret-shaped test values at run time"));
  }
  // a credential assembled from pieces at run time: the strings of one statement (an array that is joined, a + chain)
  let pieces = [];
  const flush = (t) => {
    const v = pieces.map((x) => x.value).join("");
    if (pieces.length > 1 && (/\b(password|passwd|pwd|secret|token|api[_-]?key|client[_-]?secret)\b\s*[:=]\s*\S{4,}/i.test(v) || SECRET_RES.some((re) => re.test(v) || re.test(`token: '${v}'`)) && /(^|[^A-Za-z])(eyJ|AKIA|gh[pousr]_|xox|AIza|sk_|pk_|rk_)/.test(v)))
      out.push(finding("major", file, at(pieces[0] ?? t), "hardcoded", "a hard-coded credential or token, assembled from string pieces", "never a secret in code, whole or in pieces"));
    pieces = [];
  };
  for (const t of sig) {
    if (t.type === "str") pieces.push(t);
    else if (t.value === ";" || (t.type === "punct" && t.value === "}")) flush(t);
  }
  flush(sig.at(-1));
  for (const p of literalProblems(ctx.pwProject, [file])) if (!out.length) out.push(finding("major", file, Number(/^[^:]+:(\d+):/.exec(p)?.[1]) || null, "hardcoded", p.replace(/^[^:]+:(\d+:)?\s*/, ""), "read URLs and credentials from the environment"));
  return out;
}

// The rules every piece of agent code shares: no forbidden name (the network, the runtime, the test runner, the
// fixtures, `arguments`, `this`), no computed member access but a number (or, in data, a harmless string), no
// .call/.apply/.bind or constructor walk, nothing hidden in a template literal, no change to a built-in or a shared
// object. kind: payload | glue | composite | helper. allow: names the kind may use. code (and wrap, for a slot body):
// the source, for the property rules on the JavaScript that runs (agent-scope.mjs propertyFindings, X1): no
// constructor, prototype, __proto__, caller, callee or arguments anywhere, no computed access but a number or a loop
// counter.
function agentCodeFindings(file, sig, at, kind, { allow = new Set(), code, wrap = false } = {}) {
  const out = [];
  const push = (t, rule, problem, fix) => out.push(finding("major", file, at(t), rule, problem, fix));
  const tree = code === undefined ? null : parseAgentCode(code, { wrap });
  const lineAt = (n) => ({ line: n.loc.start.line });
  if (tree) {
    // the names and members of the syntax tree of the JavaScript that runs (types stripped): a name that is only a type
    // is not code, a member is a member whatever surrounds it, and a template's ${} is walked like any expression
    astWalk(tree.ast, (n, parent, key) => {
      let name = null;
      if (n.type === "Identifier") {
        const member = parent?.type === "MemberExpression" && key === "property" && !parent.computed;
        const prop = (parent?.type === "Property" || parent?.type === "MethodDefinition" || parent?.type === "PropertyDefinition") && key === "key" && !parent.computed && !parent.shorthand;
        if (member) {
          if (DANGEROUS_MEMBERS.has(n.name)) push(lineAt(n), ["call", "apply", "bind"].includes(n.name) ? "call-apply-bind" : RAW.has(n.name) ? "raw-request" : "computed-access", `${kind} code uses .${n.name}`, "call functions and methods directly, by name");
          return;
        }
        if (!prop) name = n.name;
      } else if (n.type === "ThisExpression") name = "this";
      else if (n.type === "ImportExpression" || (wrap && n.type === "ImportDeclaration")) name = "import"; // a static import of a file is agentImportFindings' to judge
      // a dynamic import is never allowed, whatever the kind may import statically
      if (name === null || !FORBIDDEN.includes(name) || (allow.has(name) && n.type !== "ImportExpression")) return;
      const rule = ["test", "testInfo"].includes(name) ? "test-reference" : name === "expect" ? (kind === "composite" ? "client-assertion" : "assertion") : RAW.has(name) || name === "import" || name === "require" ? "raw-request" : "forbidden";
      push(lineAt(n), rule, `${kind} code uses ${name}`, {
        "test-reference": "tests are generated: no test, annotation or testInfo in agent code",
        assertion: "assertions are generated from the plan's sourced expectations: none in agent code",
        "client-assertion": "no assertion in a client or a composite helper: the generated test asserts",
        "raw-request": "requests go only through the generated clients (and their guarded fixtures)",
        forbidden: "plain data and the generated clients only: no runtime, environment, fixture, global, arguments or this",
      }[rule]);
    });
  }
  if (code !== undefined) out.push(...propertyFindings(file, code, { wrap, at, kind }));
  // on the JavaScript that runs when there is source (types stripped, positions kept): a type is never a target
  if (code !== undefined) out.push(...builtinPatchFindings(file, code, at, { wrap }));
  return out;
}

// The data-only rules of the payload slots (and helpers): synchronous, no throw, no type escape.
function payloadFindings(file, sig, at, raw, wrap) {
  const out = agentCodeFindings(file, sig, at, "payload", { code: raw, wrap });
  // synchronous data, read from the syntax tree of the JavaScript that runs
  const tree = parseAgentCode(raw, { wrap });
  if (tree) {
    const dataOnly = (n, problem, fix) => out.push(finding("major", file, at({ line: n.loc.start.line }), "data-only", problem, fix));
    astWalk(tree.ast, (n) => {
      const isFn = n.type === "FunctionDeclaration" || n.type === "FunctionExpression" || n.type === "ArrowFunctionExpression";
      if (isFn && n.async) dataOnly(n, "a payload builder uses async: builders are synchronous data", "return plain values");
      if (n.type === "AwaitExpression") dataOnly(n, "a payload builder uses await: builders are synchronous data", "return plain values");
      if (n.type === "YieldExpression" || (isFn && n.generator)) dataOnly(n, "a payload builder uses yield: builders are synchronous data", "return plain values");
      if (n.type === "ThrowStatement") dataOnly(n, "a payload builder throws: it builds nothing", "return a valid value, or park the scenario in tests-overlay.json with a reason");
      if (n.type === "NewExpression" && !(n.callee.type === "Identifier" && ["Date", "Map", "Set", "Array", "URLSearchParams"].includes(n.callee.name))) dataOnly(n, `a payload builder constructs ${n.callee.type === "Identifier" ? n.callee.name : "something"}`, "plain values only (Date, Map, Set, Array, URLSearchParams at most)");
    });
  }
  // a type is erased before the tree: `as any` and the @ts- comments are read from the TypeScript tokens
  for (let k = 0; k < sig.length - 1; k++) if (sig[k].value === "as" && ["any", "never", "unknown"].includes(sig[k + 1].value)) out.push(finding("major", file, at(sig[k]), "type-escape", `'as ${sig[k + 1].value}' escapes the generated request type`, "return a value of the builder's type"));
  for (const m of String(raw).matchAll(/@ts-(ignore|expect-error|nocheck)/g)) out.push(finding("major", file, null, "type-escape", `@ts-${m[1]} silences the type check`, "fix the value instead"));
  return out;
}

// The scaffolder's gap files a slot file or the composite helpers may import (M4): helpers/api/<topic>.ts that exist,
// not one of a module's own files, not a managed file.
const gapFile = (ctx, f) => /^helpers\/api\/[A-Za-z0-9_-]+\.ts$/.test(f) && !/^helpers\/api\/[^/]*\.(payloads|glue|composite)\.ts$/.test(f) && f !== "helpers/api/schema.ts" && existsSync(pw(ctx, f));

// N4: what agent code (the composite helpers, the gap files) may import as a value: the scaffolder's gap files, any
// module's pure support.ts, types.ts and facade.ts, a module's payload builders and the shared data helpers. Never the
// sender (the test session and the raw send), a client class (which holds it), the fixtures, a spec or a package; types
// from anywhere (import type); no re-export, so no agent file hands anything on. The checks follow every import of an
// agent file to the next agent file (apiCodeFindings), so the sender is out of reach directly and transitively.
const SESSION_FILE = /^clients\/[^/]+\/(sender\.ts|[^/]+\.client\.ts)$|^fixtures\//;
const agentImportable = (ctx, f) => gapFile(ctx, f) || /^clients\/[^/]+\/(support|types|facade)\.ts$/.test(f) || /^helpers\/api\/[^/]+\.payloads\.ts$/.test(f) || f === "utils/shared/data.ts";
const resolveImport = (file, from) => path.posix.normalize(path.posix.join(path.posix.dirname(file), from)).replace(/\.(ts|mts|js|mjs)$/, "") + (/\.json$/.test(from) ? "" : ".ts");
// The value names a file exports (functions, constants, classes, export lists, a default).
function exportedValues(text) {
  const src = String(text ?? "");
  const out = new Set([...src.matchAll(/\bexport\s+(?:declare\s+)?(?:async\s+)?(?:function\*?|const|let|var|class|enum)\s+([A-Za-z_$][\w$]*)/g)].map((m) => m[1]));
  for (const m of src.matchAll(/\bexport\s*\{([^}]*)\}/g)) for (const x of m[1].split(",")) if (x.trim() && !/^type\s/.test(x.trim())) out.add(x.trim().split(/\s+as\s+/).at(-1).trim());
  if (/\bexport\s+default\b/.test(src)) out.add("default");
  return out;
}
export function agentImportFindings(ctx, file, text) {
  const out = [];
  const src = String(text ?? "").replace(/\/\*[\s\S]*?\*\//g, (c) => c.replace(/[^\n]/g, " ")).replace(/\/\/[^\n]*/g, (c) => " ".repeat(c.length));
  const lineAt = (i) => src.slice(0, i).split("\n").length;
  for (const m of src.matchAll(/\b(import|export)\s+(type\s+)?([^;'"]*?)\s*from\s*['"]([^'"]+)['"]/g)) {
    const line = lineAt(m.index);
    const from = m[4];
    if (m[1] === "export") {
      out.push(finding("major", file, line, "re-export", `${file} re-exports from ${from}`, "agent code never re-exports: import what you use, by name, where you use it"));
      continue;
    }
    if (m[2] || /^\{\s*(type\s+[\w$]+(\s+as\s+[\w$]+)?\s*,?\s*)*\}$/.test(m[3].trim())) continue; // types only: erased
    if (!from.startsWith(".")) {
      out.push(finding("major", file, line, "raw-request", `${file} imports ${from} at run time`, "import types only from a package; values only from the module's facade, support, types and payload builders and the scaffolder's helpers/api/<topic>.ts"));
      continue;
    }
    const target = resolveImport(file, from);
    if (SESSION_FILE.test(target)) out.push(finding("major", file, line, "session-reach", `${file} imports ${target}: the sender, the test session, the client classes and the fixtures are for generated code only`, "take facade clients as parameters (types from clients/<module>/facade.ts with import type)"));
    else if (!agentImportable(ctx, target)) out.push(finding("major", file, line, "raw-request", `${file} imports ${target}`, "import values only from the module's facade, support, types and payload builders and the scaffolder's helpers/api/<topic>.ts"));
    else {
      // each value it imports is one the target exports (support.ts exports no session or sender function)
      const have = exportedValues(readText(pw(ctx, target)));
      const names = (/\{([^}]*)\}/.exec(m[3])?.[1] ?? "").split(",").map((x) => x.trim()).filter((x) => x && !/^type\s/.test(x)).map((x) => x.split(/\s+as\s+/)[0].trim());
      const def = /^([A-Za-z_$][\w$]*)\s*(,|$)/.exec(m[3].trim())?.[1];
      for (const n of [...names, ...(def ? ["default"] : [])]) if (!have.has(n)) out.push(finding("major", file, line, "session-reach", `${file} imports ${n} from ${target}, which does not export it`, "import only what the file exports"));
    }
  }
  for (const m of src.matchAll(/\bimport\s*['"]([^'"]+)['"]/g)) out.push(finding("major", file, lineAt(m.index), "raw-request", `${file} imports ${m[1]} for its side effects`, "no side-effect imports in agent code"));
  if (/\b(require|import)\s*\(/.test(src)) out.push(finding("major", file, null, "raw-request", `${file} loads a module at run time`, "static imports only"));
  return out;
}

// The imports slot: only `import { a, b } from './<topic>';` (or `import type`) of a gap file.
function importSlotFindings(ctx, file, lines, at0) {
  const out = [];
  const text = (lines ?? []).map((l) => l.replace(/\/\/.*$/, "")).join("\n").replace(/\/\*[\s\S]*?\*\//g, "");
  for (const st0 of text.split(";")) {
    const st = st0.replace(/\s+/g, " ").trim();
    if (!st) continue;
    const m = /^import\s+(type\s+)?\{\s*([A-Za-z_$][\w$]*(\s+as\s+[A-Za-z_$][\w$]*)?(\s*,\s*[A-Za-z_$][\w$]*(\s+as\s+[A-Za-z_$][\w$]*)?)*)\s*,?\s*\}\s*from\s*'(\.\/[A-Za-z0-9_-]+)'$/.exec(st);
    const target = m ? path.posix.normalize(path.posix.join(path.posix.dirname(file), m[6])) + ".ts" : null;
    if (!m || !gapFile(ctx, target)) out.push(finding("major", file, at0, "imports", `the imports slot holds ${st.slice(0, 60)}`, "only `import { a } from './<topic>';` of the scaffolder's helpers/api/<topic>.ts files"));
    else if (/\b(test|expect)\b/.test(m[2])) out.push(finding("major", file, at0, "test-runner-import", `the imports slot imports ${m[2]}`, "only a spec uses test and expect"));
  }
  return out;
}

// The glue slot rules (second layer: the sender refuses at run time any change to an entity this test did not create,
// and the glue only holds the facade). `c` only as c.clients.<client>.<facade method>(…), as a client argument of
// composite.<helper>(…), or c.track(…); `given` only read; payloads.<builder>(…) and composite.<helper>(…) only by
// name; no re-declaration or reassignment of c, given, payloads or composite; a slot returns what it arranged.
function glueFindings(file, sig, at, model, compositeNames, code, wrap) {
  const out = agentCodeFindings(file, sig, at, "glue", { allow: new Set(), code, wrap });
  const push = (t, rule, problem, fix) => out.push(finding("major", file, at(t), rule, problem, fix));
  const clients = new Map(model.clients.map((c) => [c.fixture, c]));
  const payloadNames = new Set(model.payloads.map((p) => p.name));
  for (let k = 0; k < sig.length; k++) {
    const t = sig[k];
    if (t.type !== "ident" || sig[k - 1]?.value === ".") continue;
    if (["c", "given", "payloads", "composite"].includes(t.value)) {
      const decl = ["const", "let", "var", "function", "class"].includes(sig[k - 1]?.value) || (["{", ","].includes(sig[k - 1]?.value) && [",", "}", "="].includes(sig[k + 1]?.value) && sig.slice(0, k).some((x) => ["const", "let", "var"].includes(x.value)));
      const assigned = sig[k + 1]?.value === "=" || (["+", "-", "*", "/", "?", "|", "&"].includes(sig[k + 1]?.value) && sig[k + 2]?.value === "=");
      if (decl || assigned) {
        push(t, "shadow", `glue re-declares or reassigns ${t.value}`, "keep c, given, payloads and composite as the generated code binds them");
        continue;
      }
    }
    if (t.value === "c") {
      if (sig[k + 1]?.value === "." && sig[k + 2]?.value === "track" && sig[k + 3]?.value === "(") continue;
      if (sig[k + 1]?.value === "." && sig[k + 2]?.value === "clients" && sig[k + 3]?.value === "." && clients.has(sig[k + 4]?.value)) {
        const client = clients.get(sig[k + 4].value);
        const next = sig[k + 5]?.value;
        if (next === "." && sig[k + 7]?.value === "(") {
          const m = client.methods.find((x) => x.name === sig[k + 6].value);
          if (!m) push(sig[k + 6], "glue", `glue calls ${client.fixture}.${sig[k + 6].value}(…), which is not a generated method`, "call a method of the facade");
          else if (!m.facade) push(sig[k + 6], "glue", `glue calls ${client.fixture}.${m.name}(…) (${m.method} ${m.path}), which the facade does not offer: no delete, update, action or other change`, "cleanup is generated and deletes only what this run created; glue reads and creates");
          continue;
        }
        if ([",", ")"].includes(next)) {
          // a client passed whole: only as an argument of composite.<helper>(…)
          let d = 0;
          let j = k - 1;
          for (; j >= 0; j--) {
            if (isClose(sig[j])) d++;
            else if (isOpen(sig[j])) {
              if (d === 0) break;
              d--;
            }
          }
          if (sig[j]?.value === "(" && sig[j - 2]?.value === "." && sig[j - 3]?.value === "composite" && compositeNames.has(sig[j - 1]?.value)) continue;
        }
      }
      push(t, "glue", "glue uses c other than as c.clients.<client>.<method>(…), a client argument of composite.<helper>(…), or c.track(…)", "no alias, no computed access, no passing a client anywhere else");
      continue;
    }
    if (t.value === "given" && !(sig[k + 1]?.value === "." && sig[k + 2]?.value === "path" && sig[k + 3]?.value === "." && sig[k + 4]?.type === "ident" && sig[k + 5]?.value !== "=")) push(t, "glue", "glue uses given other than reading given.path.<parameter>", "read the setup's values; return what the request should use");
    if (t.value === "payloads" && !(sig[k + 1]?.value === "." && payloadNames.has(sig[k + 2]?.value) && sig[k + 3]?.value === "(")) push(t, "glue", "glue uses payloads other than payloads.<builder>(…)", "call a generated payload builder by name");
    if (t.value === "composite" && !(sig[k + 1]?.value === "." && compositeNames.has(sig[k + 2]?.value) && sig[k + 3]?.value === "(")) push(t, "glue", "glue uses composite other than composite.<helper>(…)", "call an exported composite helper by name");
    if (t.value === "new" && /Client$/.test(sig[k + 1]?.value ?? "")) push(t, "raw-request", `glue constructs ${sig[k + 1].value}`, "use the facade in c.clients");
  }
  return out;
}

// The composite helpers (helpers/api/<m>.composite.ts): imports only from the module's facade, clients (types), types,
// the pure helpers of support.ts (never the sender or the session), its payload builders and the scaffolder's gap
// files; calls only facade methods; no send(), delete, update, assertion, raw request or test runner.
function compositeFindings(ctx, model, file, text) {
  const all = scanTs(text);
  const sig = all.filter((t) => t.type !== "comment");
  const at = (t) => t?.line ?? null;
  const out = [];
  out.push(...agentImportFindings(ctx, file, text), ...runnerImportFindings(file, text), ...freeIdentifierFindings(file, text));
  const body = sig.filter((t) => !(t.type === "ident" && t.value === "import"));
  out.push(...agentCodeFindings(file, body, at, "composite", { allow: new Set(["import"]), code: text }));
  const outside = new Set(model.clients.flatMap((c) => c.methods.filter((m) => !m.facade).map((m) => m.name)));
  const inside = new Set(model.clients.flatMap((c) => c.methods.filter((m) => m.facade).map((m) => m.name)));
  for (let k = 1; k < sig.length - 1; k++) {
    const t = sig[k];
    if (t.type !== "ident" || sig[k - 1].value !== ".") continue;
    if (t.value === "send") out.push(finding("major", file, t.line, "raw-request", "a composite helper uses send(): the raw escape hatch is for the generated tests' method faults only", "call a facade method"));
    else if (outside.has(t.value) && !inside.has(t.value)) out.push(finding("major", file, t.line, "composite", `a composite helper uses ${t.value}, which the facade does not offer (a delete, an update or another change): cleanup is generated and deletes only what this run created (D-005)`, "call the facade's reads and plain creates only"));
  }
  for (let k = 0; k < sig.length - 1; k++) if (sig[k].value === "new" && /Client$/.test(sig[k + 1].value ?? "")) out.push(finding("major", file, sig[k].line, "raw-request", `a composite helper constructs ${sig[k + 1].value}: it takes the facade client as a parameter`, "take the facade client as a parameter"));
  out.push(...literalFindings(ctx, file, text, sig, at));
  return out;
}

// The test declarations of a spec: [{title, kind, line, from, to}] (from..to: the body's tokens), plus every
// annotation call inside a body.
export function specTests(text) {
  const sig = scanTs(text).filter((t) => t.type !== "comment");
  const tests = [];
  for (let k = 0; k < sig.length; k++) {
    if (sig[k].value !== "test" || sig[k].type !== "ident" || sig[k - 1]?.value === ".") continue;
    let j = k + 1;
    let variant = "";
    if (sig[j]?.value === "." && sig[j + 1]?.type === "ident") [variant, j] = [sig[j + 1].value, j + 2];
    if (sig[j]?.value !== "(" || !["", "only", "skip", "fixme", "fail"].includes(variant)) continue;
    const { args, close } = callArgs(sig, j);
    const fn = args[1] ?? [];
    if (!fn.some((t) => t.value === "=>" || t.value === "function")) continue;
    const title = args[0]?.length === 1 && args[0][0].type === "str" ? args[0][0].value : null;
    const arrow = fn.findIndex((t) => t.value === "=>" || t.value === "function");
    const open = sig.indexOf(fn.slice(arrow).find((t) => t.value === "{"), j);
    tests.push({ title, kind: variant || "test", line: sig[k].line, from: open + 1, to: open >= 0 ? matchClose(sig, open) : close, titleSource: (args[0] ?? []).map((t) => t.value).join(" ") });
  }
  return { sig, tests };
}

// The spec rules of one generated spec file, against the plan's tests for it.
function specFindings(ctx, model, file, text) {
  const out = [];
  const { sig, tests } = specTests(text);
  const want = model.tests.filter((t) => t.file === file);
  const idRe = new RegExp(`^API-${ctx.module}-\\d+\\b`);
  const rebuild = `node scripts/api-code.mjs build ${ctx.product} ${ctx.module}`;
  const counts = new Map();
  for (const d of tests) counts.set(d.title, (counts.get(d.title) ?? 0) + 1);
  for (const t of want) {
    const n = counts.get(t.literal) ?? 0;
    if (n > 1) out.push(finding("major", file, null, "duplicate-test", `${t.id} is declared ${n} times: one test per plan scenario`, `run ${rebuild}`));
  }
  for (const d of tests) {
    const id = idRe.exec(d.title ?? "")?.[0];
    const planned = want.find((t) => t.id === id);
    if (d.title === null) out.push(finding("major", file, d.line, "extra-test", `a test whose title is not a literal (${d.titleSource.slice(0, 60)})`, `tests are generated: run ${rebuild}`));
    else if (!id || !model.tests.some((t) => t.id === id)) out.push(finding("major", file, d.line, "extra-test", `"${d.title.slice(0, 80)}" is not a scenario of the plan`, "tests are generated, one per plan scenario; remove it"));
    else if (!planned) out.push(finding("major", file, d.line, "extra-test", `${id} belongs in ${model.tests.find((t) => t.id === id).file}`, `run ${rebuild}`));
    else if (d.title !== planned.literal) out.push(finding("major", file, d.line, "title-drift", `${id}: the title or tags differ from the plan (want '${planned.literal}')`, `titles and tags come from the plan: run ${rebuild}`));
  }
  for (const t of want) {
    const decls = tests.filter((d) => d.title === t.literal || (d.title ?? "").startsWith(`${t.id} `));
    if (!decls.length) {
      out.push(finding("major", file, null, "missing-test", `${t.id} has no test (${t.kind === "test" ? "a runnable scenario" : `${t.kind}: it is a test.fixme with its reason`})`, `run ${rebuild}`));
      continue;
    }
    for (const d of decls) {
      const body = sig.slice(d.from, d.to);
      const has = (name) => body.some((x, i) => x.value === name && body[i + 1]?.value === "(" && body[i - 1]?.value !== ".");
      const annotations = body.filter((x, i) => ["fixme", "skip", "fail", "slow", "only"].includes(x.value) && body[i - 1]?.value === "." && body[i - 2]?.value === "test");
      if (t.kind !== "test") {
        const ok = d.kind === "test" && body[0]?.value === "test" && body[2]?.value === "fixme" && body[3]?.value === "(" && body[4]?.value === "true" && body[6]?.type === "str" && body[6].value === `${t.kind}: ${t.reason}` && t.reason.trim().length > 0;
        if (!ok) out.push(finding("major", file, d.line, "fixme", `${t.id} is ${t.kind} (${t.reason}) but its test is not test.fixme(true, '${t.kind}: <reason>') as its first statement`, `run ${rebuild}`));
        continue;
      }
      if (d.kind !== "test" || annotations.length) out.push(finding("major", file, d.line, "silent-skip", `${t.id} is runnable but its test is ${d.kind !== "test" ? `test.${d.kind}` : `annotated .${annotations[0].value}`}`, `a runnable scenario runs: run ${rebuild}`));
      if (!has("expect")) out.push(finding("major", file, d.line, "no-assertion", `${t.id} asserts nothing`, `the plan's assertions are generated: run ${rebuild}`));
      // the ledger: every test opens a session with the three ledger calls and ends it (its cleanup) in finally
      const begin = body.findIndex((x, i) => x.value === "beginTest" && body[i + 1]?.value === "(");
      const args = begin >= 0 ? callArgs(body, begin + 1).args.flat().map((x) => x.value) : [];
      const missing = ["recordCreated", "recordDeleted", "owns"].filter((n) => !args.includes(n));
      if (begin < 0 || missing.length) out.push(finding("major", file, d.line, "ledger", `${t.id} ${begin < 0 ? "opens no test session (beginTest)" : `opens its session without ${missing.join(", ")}`}: its creates would not be recorded or cleaned up`, `run ${rebuild}`));
      if (!body.some((x, i) => x.value === "end" && body[i - 1]?.value === "." && body[i - 2]?.value === "session" && body[i + 1]?.value === "(")) out.push(finding("major", file, d.line, "ledger", `${t.id} never ends its session: nothing it created would be cleaned up`, `run ${rebuild}`));
    }
  }
  // assertions: never on a literal alone, never soft or polled (the plan's expectations are hard facts)
  for (let k = 0; k < sig.length; k++) {
    if (sig[k].value !== "expect" || sig[k - 1]?.value === ".") continue;
    if (sig[k + 1]?.value === "." && ["soft", "poll"].includes(sig[k + 2]?.value)) out.push(finding("major", file, sig[k].line, "assertion", `expect.${sig[k + 2].value}: the plan's expectations are hard assertions`, `run ${rebuild}`));
    if (sig[k + 1]?.value === "(") {
      const { args } = callArgs(sig, k + 1);
      const subject = args[0] ?? [];
      const literalOnly = subject.length && subject.every((x) => ["str", "num"].includes(x.type) || ["true", "false", "null", "undefined", "[", "]", ",", "{", "}", ":"].includes(x.value));
      if (literalOnly) out.push(finding("major", file, sig[k].line, "assertion", "an assertion on a literal is always true or always false", `run ${rebuild}`));
    }
  }
  out.push(...rawRequestFindings(file, sig));
  return out;
}

// No raw request API anywhere in API test code: no Playwright request fixture or newContext, no fetch, axios or node http.
function rawRequestFindings(file, sig) {
  const out = [];
  for (let k = 0; k < sig.length; k++) {
    const t = sig[k];
    if (t.type !== "ident" || !RAW.has(t.value) || isKey(sig, k)) continue;
    if (sig[k - 1]?.value === "." && !["fetch", "newContext", "request"].includes(t.value)) continue;
    out.push(finding("major", file, t.line, "raw-request", `uses ${t.value}: requests go only through the generated clients and the guarded fixtures`, "call a generated client method"));
  }
  return out;
}

// The module's agent and helper files reachable through imports from the generated specs and the slot files.
const importsOf = (file, text) =>
  [...String(text ?? "").matchAll(/(?:from|import\s*\(|require\s*\()\s*['"](\.{1,2}\/[^'"]+)['"]/g)].map((m) => {
    let t = path.posix.normalize(path.posix.join(path.posix.dirname(file), m[1]));
    if (!/\.(ts|json)$/.test(t)) t += ".ts";
    return t;
  });

// -> [{severity, file, line, rule, problem, fix}] (files relative to the Playwright project). [] when never built.
export function apiCodeFindings(ctx, { scope = "tests" } = {}) {
  const model = readPlan(ctx);
  if (!model) return [];
  const out = [];
  const { module } = ctx;
  const rebuild = `node scripts/api-code.mjs build ${ctx.product} ${ctx.module}`;
  const catalogue = tryReadJson(ctx.pp.catalogue, []);
  const scenarios = tryReadJson(ctx.pp.plan, []);
  let files;
  try {
    files = generatedFiles(ctx, model, catalogue, scenarios);
  } catch (e) {
    return [finding("blocker", "api-code/plan.json", null, "generated", `the code can't be generated from the current inputs (${e.message})`, `run ${rebuild}`)];
  }
  const isSpec = (f) => f.startsWith(`${SPECS_DIR(module)}/`);
  // generated files: present and byte-identical to their render (the clients scope leaves the specs to the tests scope)
  for (const [f, text] of files) {
    if (scope === "clients" && isSpec(f)) continue;
    const have = readText(pw(ctx, f));
    if (have !== text) out.push(finding("major", f, have === null ? null : firstDiff(text, have), "generated", `${f} ${have === null ? "is missing" : "was edited or is out of date"}: it is generated from the catalogue and the plan`, `run ${rebuild} (never edit it; a naming fix or edge case goes in client-overlay.json)`));
  }
  for (const dir of generatedDirs(module)) {
    if (scope === "clients" && dir === SPECS_DIR(module)) continue;
    for (const f of walk(ctx.pwProject, dir)) if (!files.has(f)) out.push(finding("major", f, null, "extra-file", `${f} is not generated: ${dir}/ holds only generated files`, `run ${rebuild} --adopt: it moves the file to artifacts/${ctx.product}/modules/${module}/api-code/legacy/ (${dir === SPECS_DIR(module) ? "tests are generated, one per plan scenario" : "client code is generated; composite helpers go in " + model.files.composite})`));
  }
  for (const f of walk(ctx.pwProject, "helpers/api", /\.ts$/)) if (f.startsWith(`helpers/api/${module}.`) && ![model.files.payloads, model.files.glue, model.files.composite].includes(f)) out.push(finding("major", f, null, "extra-file", `${f}: the module's helper files are ${model.files.payloads} and ${model.files.glue} (the tests-writer's slots) and ${model.files.composite}`, "move the code into a slot or a composite helper"));
  // no assertion and no raw request in the clients (sender.ts is the one sender, through the guarded context)
  for (const f of walk(ctx.pwProject, CLIENTS_DIR(module), /\.ts$/)) {
    const sig = scanTs(readText(pw(ctx, f)) ?? "").filter((t) => t.type !== "comment");
    for (const t of sig) if (t.type === "ident" && t.value === "expect") out.push(finding("major", f, t.line, "client-assertion", "an assertion inside a client", "clients return the raw response; the generated test asserts"));
    // APIRequestContext is the type of the guarded context a client is constructed with; nothing else of the kind
    if (f !== model.files.sender) out.push(...rawRequestFindings(f, sig.filter((t) => t.value !== "APIRequestContext")));
  }
  // fixtures/api/index.ts: generated from the module registrations (D-056), byte-identical to its render
  const indexWhy = indexProblem(ctx.pwProject, "api");
  if (indexWhy) out.push(finding("major", INDEX_FILE, null, "fixture-registration", indexWhy, `run ${rebuild} (it is generated; never edit it)`));
  // the composite helpers
  const composite = readText(pw(ctx, model.files.composite));
  const compositeNames = new Set([...String(composite ?? "").matchAll(/\bexport\s+(?:async\s+)?function\s+([A-Za-z_$][\w$]*)/g)].map((m) => m[1]));
  if (composite !== null) out.push(...compositeFindings(ctx, model, model.files.composite, composite));
  if (scope === "clients") return out;

  // the slot files: the skeleton intact around the slots, every needed slot filled, the slot rules
  for (const [f, render, kind] of [[model.files.payloads, (r) => renderPayloads(ctx, model, r), "payload"], [model.files.glue, (r) => renderGlue(ctx, model, r, new Map((tryReadJson(ctx.ap.testsOverlay, {})?.glue ?? []).map((g) => [g.scenario, one(g.reason)]))), "glue"]]) {
    const text = readText(pw(ctx, f));
    if (kind === "glue" && !model.glue.length && text === null) continue;
    if (text === null) {
      out.push(finding("blocker", f, null, "skeleton", `${f} is missing`, `run ${rebuild}`));
      continue;
    }
    const parsed = parseSlots(text);
    if (parsed.problems.length) {
      for (const p of parsed.problems) out.push(finding("blocker", f, Number(/^line (\d+)/.exec(p)?.[1]) || null, "skeleton", p, "restore the slot markers exactly as generated"));
      continue;
    }
    const want = render(parsed.regions);
    if (want !== text) out.push(finding("major", f, firstDiff(want, text), "skeleton", `generated code outside the slots of ${f} was changed`, `run ${rebuild} to restore it; write only inside the slots`));
    const lines = text.split("\n");
    const lineOf = (key) => lines.findIndex((l) => BEGIN.exec(l)?.[1] === key) + 1;
    const fileScope = scopeOf(text);
    for (const [key, body] of parsed.regions) {
      if (key === "imports") {
        out.push(...importSlotFindings(ctx, f, body, lineOf(key)));
        continue;
      }
      const sig = scanTs(body.join("\n")).filter((t) => t.type !== "comment");
      const at = (t) => lineOf(key) + (t?.line ?? 1);
      // B3: every identifier declared, imported or an allowed pure global, used as one (agent-scope.mjs)
      out.push(...freeIdentifierFindings(f, body.join("\n"), { declared: fileScope, wrap: key !== "helpers", at: (line) => lineOf(key) + line }));
      if (kind === "payload") out.push(...payloadFindings(f, sig, at, body.join("\n"), key !== "helpers"));
      else out.push(...glueFindings(f, sig, at, model, compositeNames, body.join("\n"), key !== "helpers"));
      out.push(...literalFindings(ctx, f, body.join("\n"), sig, at).filter((x) => x.problem.startsWith("a hard-coded")));
      if ((key.startsWith("payload ") || key.startsWith("glue ")) && filled(body) && !sig.some((t) => t.value === "return")) out.push(finding("major", f, lineOf(key), `${kind}-slot`, `${key.replace(/^\w+ /, "")}() returns nothing`, kind === "payload" ? "return the builder's value" : "return what the request should use ({} when nothing)"));
    }
    for (const p of kind === "payload" ? model.payloads : model.glue) {
      const key = kind === "payload" ? payloadKey(p.name) : glueKey(p.name);
      if (!filled(parsed.regions.get(key))) out.push(finding("major", f, lineOf(key) || null, `${kind}-slot`, `${p.name}() is empty, and ${kind === "payload" ? p.scenarios.join(", ") : p.scenario} need${kind === "payload" && p.scenarios.length > 1 ? "" : "s"} it`, kind === "payload" ? "write the builder (data only), or park the scenarios in tests-overlay.json with a reason" : "write the glue the cited business rule needs"));
    }
    out.push(...literalFindings(ctx, f, text, [], () => null).filter((x) => !x.problem.startsWith("a hard-coded")));
  }
  // the generated specs: one literal test per scenario, titles and tags as planned, fixme for blocked, the ledger
  for (const f of model.files.specs) {
    const text = readText(pw(ctx, f));
    if (text !== null) out.push(...specFindings(ctx, model, f, text));
  }
  // any other helpers/api file the specs or the module's files import is checked as agent code too
  const known = new Set([model.files.payloads, model.files.glue, model.files.composite, "helpers/api/schema.ts"]);
  const seen = new Set();
  const queue = [...model.files.specs, model.files.payloads, model.files.glue, model.files.composite];
  while (queue.length) {
    const f = queue.shift();
    if (seen.has(f)) continue;
    seen.add(f);
    for (const imp of importsOf(f, readText(pw(ctx, f)))) {
      if (!imp.startsWith("helpers/api/") || known.has(imp) || seen.has(imp)) continue;
      const text = readText(pw(ctx, imp));
      if (text === null) continue;
      const sig = scanTs(text).filter((t) => t.type !== "comment");
      const helper = [...agentCodeFindings(imp, sig.filter((t) => !(t.type === "ident" && t.value === "import" && ["{", "type", "*"].includes(sig[sig.indexOf(t) + 1]?.value))), (t) => t?.line ?? null, "helper", { code: text }), ...runnerImportFindings(imp, text)];
      // only a gap file is agent code another file may import; its own imports are checked here and followed below (N4)
      if (gapFile(ctx, imp)) helper.push(...agentImportFindings(ctx, imp, text), ...freeIdentifierFindings(imp, text));
      out.push(...helper.map((x) => ({ ...x, problem: `${x.problem} (imported by ${f})` })), ...literalFindings(ctx, imp, text, sig, (t) => t?.line ?? null));
      queue.push(imp);
    }
  }
  return out;
}
const firstDiff = (a, b) => {
  const x = String(a).split("\n");
  const y = String(b).split("\n");
  const i = x.findIndex((l, n) => l !== y[n]);
  return (i < 0 ? x.length : i) + 1;
};

// ---------- check: stamps ----------

function stampInputs(ctx, model, scope) {
  const files = {
    plan: ctx.ap.plan, clientOverlay: ctx.ap.clientOverlay, index: pw(ctx, INDEX_FILE), composite: pw(ctx, model.files.composite),
    registration: pw(ctx, model.files.registration), types: pw(ctx, model.files.types), support: pw(ctx, model.files.support), sender: pw(ctx, model.files.sender), facade: pw(ctx, model.files.facade),
  };
  for (const c of model.clients) Object.assign(files, { [`client:${c.file}`]: pw(ctx, c.file), [`schema:${c.schemaFile}`]: pw(ctx, c.schemaFile) });
  if (scope === "tests") {
    Object.assign(files, { testsOverlay: ctx.ap.testsOverlay, payloads: pw(ctx, model.files.payloads), glue: pw(ctx, model.files.glue) });
    for (const f of model.files.specs) files[`spec:${f}`] = pw(ctx, f);
  }
  return files;
}

// Problems that are not rules on the code: the build missing or stale, the plan not verified. -> string[]
export function buildProblems(ctx) {
  const cov = tryReadJson(ctx.ap.coverage, null);
  const model = readPlan(ctx);
  const cmd = `node scripts/api-code.mjs build ${ctx.product} ${ctx.module}`;
  if (!cov || !model) return [`api-code/plan.json is missing: run ${cmd} first`];
  const now = inputDigests(ctx);
  const stale = Object.keys(now).filter((k) => now[k] !== cov.built?.inputs?.[k]);
  const planWhy = planUnverified(ctx.pp);
  return [
    ...(stale.length ? [`stale: ${stale.join(", ")} changed after the last build (run ${cmd} again)`] : []),
    ...(planWhy ? [`the API plan is not verified: ${planWhy}`] : []),
    ...(cov.problems ?? []),
  ];
}

export function stampCheck(ctx, scope) {
  const cov = tryReadJson(ctx.ap.coverage, null);
  const model = readPlan(ctx);
  if (!cov || !model) return;
  const verified = { ...(cov.verified ?? {}) };
  verified.clients = stampVerified(stampInputs(ctx, model, "clients"));
  if (scope === "tests") verified.tests = stampVerified(stampInputs(ctx, model, "tests"));
  writeJsonIfChanged(ctx.ap.coverage, { ...cov, verified });
}
export function clearStamp(ctx, scope) {
  const cov = tryReadJson(ctx.ap.coverage, null);
  if (!cov?.verified?.[scope]) return;
  writeJsonIfChanged(ctx.ap.coverage, { ...cov, verified: { ...cov.verified, [scope]: null, ...(scope === "clients" ? { tests: null } : {}) } });
}

// null when the scope passed `api-code.mjs check` on exactly what is on disk, else why not (the domain flow's verify).
export function apiCodeUnverified(ctx, scope) {
  const cov = tryReadJson(ctx.ap.coverage, null);
  const model = readPlan(ctx);
  const cmd = `api-code.mjs check ${ctx.product} ${ctx.module}${scope === "clients" ? " --clients" : ""}`;
  if (!cov || !model) return `api-code/coverage.json is missing: the writer must run api-code.mjs build, then ${cmd}`;
  const stale = buildProblems(ctx).filter((p) => p.startsWith("stale"));
  if (stale.length) return stale[0];
  return unverifiedReason(cov.verified?.[scope] ?? null, stampInputs(ctx, model, scope), { unstamped: `the ${scope} never passed ${cmd}`, changed: `the ${scope} changed after ${cmd}` });
}

