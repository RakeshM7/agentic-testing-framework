// A TypeScript literal of any JSON value. A string holding "//" is written with "\/" escapes, so a value from the plan
// (a cited realistic URL) never reads as a hard-coded URL in generated code; it is the same string at run time.
export function tsLit(v) {
  if (v === undefined) return "undefined";
  if (typeof v === "string") return strLit(v);
  if (v === null || typeof v !== "object") return JSON.stringify(v);
  if (Array.isArray(v)) return `[${v.map(tsLit).join(", ")}]`;
  const entries = Object.entries(v);
  return entries.length ? `{ ${entries.map(([k, x]) => `${prop(k)}: ${tsLit(x)}`).join(", ")} }` : "{}";
}
// A title as a single-quoted literal (the gate's title reader stops at the first matching quote, so no escaped quote).
export const titleLit = (s) => {
  const t = one(s).replace(/\\/g, "/");
  return t.includes("'") && !t.includes('"') ? `"${t}"` : `'${t.replace(/'/g, "’")}'`;
};
function strLit(s) {
  let t = String(s).replaceAll("\\", "\\\\").replaceAll("'", "\\'").replaceAll("\n", "\\n").replaceAll("\r", "\\r");
  if (t.includes("//")) t = t.replaceAll("/", "\\/");
  return `'${t}'`;
}
const prop = (k) => (IDENT.test(k) ? k : strLit(k));

