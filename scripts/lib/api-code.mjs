function pathValue(method: string, template: string, name: string, value: PathValue, ref: PathRef | undefined, changes: boolean): string {
  if (value !== null && typeof value === 'object') {
    if (INVALID.has(value)) return String((value as InvalidPath).invalid);
    throw new Error('refused: ' + method + ' ' + template + ': path parameter ' + name + ' is not a string or a number');
  }
  const v = String(value);
  const kind = ref?.kind ?? 'string';
  const ok = kind === 'integer' ? matches(INTEGER, v) : kind === 'number' ? matches(NUMBER, v) : ref?.format === 'uuid' ? matches(UUID, v) : matches(SEGMENT, v);
  if (!ok) throw new Error('refused: ' + method + ' ' + template + ': ' + name + '=' + $stringify(v) + ' is not a valid ' + (ref?.format ?? kind));
  if (changes && !owned(ref ? ref.type : null, v)) throw new Error('refused (D-005): ' + method + ' ' + template + ' names ' + name + '=' + v + ', which this test did not create' + (ref?.type ? ' as a ' + ref.type : ' (no entity type is known for it)'));
  return v;
}

// An integer (a number or digits) or a uuid: a value that can name an entity whatever field holds it.
const idShaped = (node: unknown): boolean => matches(INTEGER, String(node)) || (typeof node === 'string' && matches(UUID, node));
// The entity type a field's value references (null: an unknown type, so nothing this test owns), or undefined: not a
// reference. An id-like name (id, ids, <x>Id, <x>Ids, <x>_id) or a field the client's meta lists (an id format), any
// value; a field named after a resource or path parameter of the catalogue, an id-shaped value (X3).
function refType(field: string | null, node: unknown, meta: Meta): string | null | undefined {
  if (field === null) return undefined;
  if (meta.refs && hasOwn(meta.refs, field)) return meta.refs[field];
  if (matches(ID_KEY, field)) return field === 'id' || field === 'ids' ? (meta.self ?? null) : null;
  const n = nameKey(field);
  return idShaped(node) && hasOwn(NAMED, n) ? NAMED[n] : undefined;
}

// Every entity reference in a body, a query or GraphQL variables of a request that changes data names an entity of the
// referenced type this test created, unless the plan put it there (planned()). On a destructive or action endpoint
// (meta.bulk) every integer or uuid in an array, and every uuid anywhere, is a reference too, of the endpoint's own type.
function refs(method: string, template: string, where: string, root: unknown, meta: Meta): void {
  const plannedSet = root !== null && typeof root === 'object' ? PLANNED.get(root as object) : undefined;
  const walk = (node: unknown, pointer: string, field: string | null, inArray: boolean): void => {
    if (plannedSet && plannedSet.has(pointer)) return;
    if ($isArray(node)) {
      for (let i = 0; i < node.length; i++) walk(node[i], pointer + '/' + i, field, true);
      return;
    }
    if (node !== null && typeof node === 'object') {
      const names = $keys(node as Record<string, unknown>);
      for (let i = 0; i < names.length; i++) walk((node as Record<string, unknown>)[names[i]], pointer + '/' + names[i], names[i], false);
      return;
    }
    if (node === null || node === undefined || typeof node === 'boolean') return;
    let type = refType(field, node, meta);
    if (type === undefined) {
      if (!(meta.bulk && ((inArray && idShaped(node)) || (typeof node === 'string' && matches(UUID, node))))) return;
      type = meta.self ?? null;
    }
    if (!owned(type, String(node))) throw new Error('refused (D-005): ' + method + ' ' + template + ' sends ' + where + ' ' + (field ?? 'an item') + '=' + String(node) + ', which this test did not create');
  };
  walk(root, '', null, false);
}

async function afterResponse(res: APIResponse, ref: string | null, meta: Meta): Promise<void> {
  const s = current;
  if (meta.creates && res.ok()) {
    if (!s) throw new Error('a create outside a test session: it could never be cleaned up');
    const body = await bodyOf(res);
    const id = getPointer(body, meta.creates.pointer);
    if (id === undefined || id === null || typeof id === 'object') throw new Error('created ' + meta.creates.type + ' without an id at ' + meta.creates.pointer + ': it can not be cleaned up');
    const e: Entity = { type: meta.creates.type, ref: String(id), module: s.ledger.module, label: s.ledger.label, ...(meta.creates.cleanup ? { cleanup: meta.creates.cleanup } : {}) };
    s.ledger.recordCreated(e);
    s.created.push(e);
    s.marked.set(res, e);
  }
  if (meta.deletes && s && ref !== null && (res.ok() || res.status() === 404 || res.status() === 410)) {
    const k = key(meta.deletes.type, ref);
    if (owned(meta.deletes.type, ref) && !s.deleted.has(k)) {
      s.deleted.add(k);
      s.ledger.recordDeleted({ type: meta.deletes.type, ref, module: s.ledger.module, label: s.ledger.label });
    }
  }
}

