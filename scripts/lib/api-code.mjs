const MAX_TYPE_DEPTH = 6;
// mode: "request" (readOnly properties optional) | "response" (writeOnly properties optional).
export function tsType(schema, mode = "response", depth = 0, indent = "") {
  if (!schema || typeof schema !== "object" || depth > MAX_TYPE_DEPTH) return "unknown";
  if (schema["x-circular"] || schema["x-unresolved"]) return "unknown";
  const nullable = schema.nullable === true || (Array.isArray(schema.type) && schema.type.includes("null"));
  const wrap = (t) => (nullable && t !== "unknown" && t !== "null" ? `${t} | null` : t);
  if ("const" in schema) return wrap(tsLit(schema.const));
  if (Array.isArray(schema.enum) && schema.enum.length) return wrap(uniq(schema.enum.map((v) => (v === null ? "null" : tsLit(v)))).join(" | "));
  if (Array.isArray(schema.oneOf) || Array.isArray(schema.anyOf)) return wrap(uniq((schema.oneOf ?? schema.anyOf).map((s) => paren(tsType(s, mode, depth + 1, indent)))).join(" | ") || "unknown");
  if (Array.isArray(schema.allOf) && schema.allOf.length) {
    const parts = [schema, ...schema.allOf];
    const merged = { ...schema, allOf: undefined, type: "object", properties: Object.assign({}, ...parts.map((p) => p?.properties ?? {})), required: uniq(parts.flatMap((p) => p?.required ?? [])) };
    if (!Object.keys(merged.properties).length) return wrap(uniq(schema.allOf.map((s) => paren(tsType(s, mode, depth + 1, indent)))).join(" & ") || "unknown");
    return tsType(merged, mode, depth, indent);
  }
  const types = (Array.isArray(schema.type) ? schema.type : [schema.type ?? (schema.properties ? "object" : schema.items ? "array" : undefined)]).filter((t) => t && t !== "null");
  if (types.length > 1) return wrap(types.map((t) => paren(tsType({ ...schema, type: t, nullable: false }, mode, depth, indent))).join(" | "));
  const t = types[0];
  if (t === "string") return wrap("string");
  if (t === "integer" || t === "number") return wrap("number");
  if (t === "boolean") return wrap("boolean");
  if (t === "array") return wrap(`Array<${tsType(schema.items, mode, depth + 1, indent)}>`);
  if (t === "object") {
    const props = Object.entries(schema.properties ?? {}).sort(([a], [b]) => a.localeCompare(b));
    const req = new Set(schema.required ?? []);
    const inner = `${indent}  `;
    const lines = props.map(([k, s]) => {
      const optional = !req.has(k) || (mode === "request" && s?.readOnly) || (mode === "response" && s?.writeOnly);
      return `${inner}${prop(k)}${optional ? "?" : ""}: ${tsType(s, mode, depth + 1, inner)};`;
    });
    const ap = schema.additionalProperties;
    if (ap && typeof ap === "object") lines.push(`${inner}[key: string]: ${props.length ? "unknown" : tsType(ap, mode, depth + 1, inner)};`);
    else if (ap !== false && !props.length) lines.push(`${inner}[key: string]: unknown;`);
    return wrap(lines.length ? `{\n${lines.join("\n")}\n${indent}}` : "Record<string, never>");
  }
  return "unknown";
}
const paren = (t) => (/[|&]/.test(t) && !/^[{(]/.test(t) ? `(${t})` : t);
// Loose types from the key names traffic showed (no schema): marked unverified.
const keysType = (keys) => (keys?.length ? `{\n${keys.slice().sort().map((k) => `  ${prop(k)}?: unknown;`).join("\n")}\n  [key: string]: unknown;\n}` : "Record<string, unknown>");
const paramTs = (p) => (p.enum?.length ? p.enum.map(tsLit).join(" | ") : ["integer", "number"].includes(p.type) ? "number" : p.type === "boolean" ? "boolean" : "string");

// OpenAPI 3.0 `nullable` as JSON Schema (`type: [t, "null"]`), so Ajv validates what the spec means.
export function jsonSchemaOf(schema) {
  if (Array.isArray(schema)) return schema.map(jsonSchemaOf);
  if (!schema || typeof schema !== "object") return schema;
  const out = {};
  for (const [k, v] of Object.entries(schema)) if (k !== "nullable") out[k] = jsonSchemaOf(v);
  if (schema.nullable === true && typeof schema.type === "string") out.type = [schema.type, "null"];
  return out;
}

