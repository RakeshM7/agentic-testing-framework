const gqlDocument = (m) => {
  const g = m.graphql;
  const defs = g.args.length ? `(${g.args.map((a) => `$${a.name}: ${a.type}`).join(", ")})` : "";
  const args = g.args.length ? `(${g.args.map((a) => `${a.name}: $${a.name}`).join(", ")})` : "";
  const scalar = SCALARS.has(String(g.returnType).replace(/[[\]!]/g, ""));
  const sel = scalar ? "${req.select ? ` { ${req.select} }` : ''}" : "{ __typename${req.select ? ` ${req.select}` : ''} }";
  return `\`${g.operationType} ${pascal(g.field)}${defs} { ${g.field}${args} ${sel} }\``;
};

// Per REST path of a client, what its methods tell the sender (path types, id-field types, the entity type), for send().
function sendMeta(c) {
  const out = {};
  for (const m of c.methods) {
    if (m.kind === "graphql") continue;
    const o = (out[m.path] ??= {});
    if (m.meta.path && !o.path) o.path = m.meta.path;
    if (m.meta.self && !o.self) o.self = m.meta.self;
    if (m.meta.refs) o.refs = { ...m.meta.refs, ...(o.refs ?? {}) };
    if (m.meta.bulk) o.bulk = true;
  }
  return out;
}

