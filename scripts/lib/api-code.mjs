// The delete operation (and the pointer and parameter it takes) that removes what create endpoint `c` makes: the
// catalogue's link from `c` into a delete; null when there is none (the entity is left, recorded: leavesData).
function deleteFor(catalogue, c) {
  for (const d of catalogue.filter((x) => x.crud === "delete" && x.kind === "rest").sort((a, b) => byNum(a.id, b.id))) {
    const l = (d.links ?? []).find((x) => x.from === c.id);
    if (l) return { endpoint: d.id, param: l.param, pointer: l.pointer };
  }
  return null;
}
// Where the id of what `c` creates is: the pointer of any link from `c` (the delete's first), else /id.
function idPointer(catalogue, c) {
  const d = deleteFor(catalogue, c);
  if (d) return d.pointer;
  for (const x of catalogue) for (const l of x.links ?? []) if (l.from === c.id) return l.pointer;
  return "/id";
}

function methodNames(ctx, eps, overlay) {
  const base = (e) => {
    if (e.kind === "graphql") return camel(e.graphql?.field ?? e.operationId ?? `${e.method} ${e.path}`);
    if (["list", "read", "create", "update", "delete"].includes(e.crud)) return e.crud;
    if (e.operationId) return camel(e.operationId);
    const seg = e.path.split("/").filter((s) => s && !s.startsWith("{")).at(-1) ?? "call";
    return camel(`${e.method.toLowerCase()} ${seg}`);
  };
  const names = new Map(eps.map((e) => [e.id, base(e)]));
  // a clash is resolved for every endpoint in it at once: the HTTP method, then the last path segment, then the number
  const clashing = () => {
    const seen = new Map();
    for (const n of names.values()) seen.set(n, (seen.get(n) ?? 0) + 1);
    return eps.filter((e) => seen.get(names.get(e.id)) > 1);
  };
  for (const e of clashing()) names.set(e.id, camel(`${names.get(e.id)} ${e.method.toLowerCase()}`));
  for (const e of clashing()) names.set(e.id, camel(`${names.get(e.id)} ${e.path.split("/").filter((s) => s && !s.startsWith("{")).at(-1) ?? ""}`));
  for (const e of clashing()) names.set(e.id, `${names.get(e.id)}${idNum(e.id)}`);
  for (const e of eps) if (RESERVED.has(names.get(e.id))) names.set(e.id, `${names.get(e.id)}Op`);
  for (const e of eps) if (overlay?.methods?.[e.id]?.name) names.set(e.id, overlay.methods[e.id].name);
  return names;
}

const gqlIdArgs = (e) => (e.graphql?.args ?? []).filter((a) => String(a.type).replace(/[[\]!]/g, "") === "ID" || /^id$|Id$/.test(a.name)).map((a) => a.name);
const gqlDeletes = (e) => e.kind === "graphql" && e.graphql?.operationType === "mutation" && /^(delete|remove|destroy|purge)/i.test(e.graphql.field);
const erasePath = (p) => String(p).replace(/\{[^}]+\}/g, "{}");
// A field name that references an entity (the sender checks the same names at run time).
const ID_KEY = /^(id|ids)$|[a-z0-9](Id|Ids|ID|IDs)$|_(id|ids)$/;
const singular = (s) => String(s).toLowerCase().replace(/[^a-z0-9]/g, "").replace(/ies$/, "y").replace(/s$/, "");
// The ledger type an id field or path parameter names: the resource of the create whose path it extends or that links to
// it, or the resource its name spells (contactId -> contacts). null: no type is known (any owned entity then).
function refTypeOf(ctx, e, catalogue, name) {
  const creates = catalogue.filter((x) => isCreate(x) && x.kind === "rest");
  const link = (e.links ?? []).find((l) => l.param === name && creates.some((c) => c.id === l.from));
  if (link) return resourceSlug(ctx, creates.find((c) => c.id === link.from));
  const at = e.path?.indexOf(`{${name}}`) ?? -1;
  if (at > 0) {
    const prefix = erasePath(e.path.slice(0, at)).replace(/\/$/, "");
    const c = creates.find((x) => erasePath(x.path) === prefix && x.server === e.server);
    if (c) return resourceSlug(ctx, c);
  }
  const base = singular(String(name).replace(/(Ids?|IDs?|_ids?)$/, ""));
  if (!base || base === "id") return null;
  const c = creates.find((x) => singular(resourceSlug(ctx, x)) === base || singular(x.resource ?? "") === base);
  return c ? resourceSlug(ctx, c) : null;
}
// Every id-like field name of a request schema, at any depth.
function idFields(schema, out = new Set(), depth = 0) {
  if (!schema || typeof schema !== "object" || depth > 6) return out;
  for (const [k, v] of Object.entries(schema.properties ?? {})) {
    if (ID_KEY.test(k)) out.add(k);
    idFields(v, out, depth + 1);
  }
  for (const k of ["items", "additionalProperties"]) if (schema[k] && typeof schema[k] === "object") idFields(schema[k], out, depth + 1);
  for (const k of ["allOf", "oneOf", "anyOf"]) for (const s of schema[k] ?? []) idFields(s, out, depth + 1);
  return out;
}
// X3 (round 3): the formats that make a field a reference whatever its name: uuid, and every string format a path
// parameter of the catalogue has (an id format such as ulid or objectid), never a plain data format.
const DATA_FORMATS = new Set(["date", "date-time", "time", "duration", "email", "idn-email", "hostname", "idn-hostname", "ipv4", "ipv6", "uri", "url", "uri-reference", "iri", "iri-reference", "uri-template", "json-pointer", "relative-json-pointer", "regex", "byte", "binary", "password", "int32", "int64", "float", "double", "decimal", "phone", "currency", "country", "language"]);
function idFormats(catalogue) {
  const out = new Set(["uuid"]);
  for (const e of catalogue) for (const p of e.params ?? []) if (p.in === "path" && (p.type ?? "string") === "string" && p.format && !DATA_FORMATS.has(String(p.format).toLowerCase())) out.add(String(p.format).toLowerCase());
  return out;
}
// Every field name of a request schema, at any depth, whose schema (or array items) has an id format.
function formatFields(schema, formats, out = new Set(), depth = 0) {
  if (!schema || typeof schema !== "object" || depth > 6) return out;
  const isId = (s) => !!s && typeof s === "object" && (formats.has(String(s.format ?? "").toLowerCase()) || (s.items && typeof s.items === "object" && formats.has(String(s.items.format ?? "").toLowerCase())));
  for (const [k, v] of Object.entries(schema.properties ?? {})) {
    if (isId(v)) out.add(k);
    formatFields(v, formats, out, depth + 1);
  }
  for (const k of ["items", "additionalProperties"]) if (schema[k] && typeof schema[k] === "object") formatFields(schema[k], formats, out, depth + 1);
  for (const k of ["allOf", "oneOf", "anyOf"]) for (const s of schema[k] ?? []) formatFields(s, formats, out, depth + 1);
  return out;
}
// X3: the names a field references an entity by, whatever its value's shape: every resource of the catalogue and every
// path parameter (without its Id suffix), singular, lowercase, letters and digits only (contact and contacts alike),
// except generic words. The sender checks these at run time, so a field the request type does not declare is checked
// too. -> {name: the ledger type, or null when no create of the catalogue makes it}
const GENERIC_NAMES = new Set(["name", "key", "slug", "code", "type", "kind", "status", "state", "version", "lang", "language", "locale", "format", "date", "year", "month", "day", "page", "size", "field", "path", "file", "filename", "title", "label", "value", "mode", "scope", "search", "query", "filter", "sort", "order", "limit", "offset", "count", "me", "self", "current", "all", "id", "uuid"]);
export function referenceNames(ctx, catalogue) {
  const out = new Map();
  const add = (raw) => {
    const n = singular(String(raw ?? "").replace(/(Ids?|IDs?|_ids?)$/, ""));
    if (!n || GENERIC_NAMES.has(n) || out.has(n)) return;
    out.set(n, refTypeOf(ctx, {}, catalogue, n));
  };
  for (const e of catalogue) {
    if (e.kind === "rest" && e.resource) add(e.resource);
    for (const p of e.params ?? []) if (p.in === "path") add(p.name);
  }
  return Object.fromEntries([...out].sort(([a], [b]) => a.localeCompare(b)));
}
// What a client method tells the sender: what it creates (the ledger type, the id's pointer), what it deletes (the
// type and the path parameter or GraphQL argument naming the id), each path parameter's entity type and format, the
// entity type each id field of its body, query or variables names, and whether it is a GraphQL mutation. -> the meta
// object rendered into the client
function methodMeta(ctx, e, catalogue) {
  const meta = {};
  if (isCreate(e)) meta.creates = { type: resourceSlug(ctx, e), pointer: e.kind === "graphql" ? `/data/${e.graphql.field}/id` : idPointer(catalogue, e) };
  // the delete that removes what it creates, recorded with the entity so a human's ledger.mjs sweep can (D-075)
  const cleanup = isCreate(e) && e.kind === "rest" ? deleteFor(catalogue, e) : null;
  if (cleanup) meta.creates.cleanup = { endpoint: cleanup.endpoint, param: cleanup.param };
  if (e.kind === "rest" && e.crud === "delete") {
    const c = catalogue.find((x) => isCreate(x) && x.kind === "rest" && deleteFor(catalogue, x)?.endpoint === e.id);
    const params = (e.params ?? []).filter((p) => p.in === "path");
    if (c) meta.deletes = { type: resourceSlug(ctx, c), param: deleteFor(catalogue, c).param };
    else if (params.length) meta.deletes = { type: refTypeOf(ctx, e, catalogue, params.at(-1).name) ?? resourceSlug(ctx, e), param: params.at(-1).name };
  }
  if (gqlDeletes(e) && gqlIdArgs(e).length) meta.deletes = { type: resourceSlug(ctx, e), param: gqlIdArgs(e)[0] };
  const path = Object.fromEntries((e.params ?? []).filter((p) => p.in === "path").map((p) => [p.name, { type: refTypeOf(ctx, e, catalogue, p.name), kind: p.type ?? "string", format: p.format ?? null }]));
  if (Object.keys(path).length) meta.path = path;
  meta.self = meta.deletes?.type ?? (isCreate(e) ? resourceSlug(ctx, e) : refTypeOf(ctx, e, catalogue, (e.params ?? []).filter((p) => p.in === "path").at(-1)?.name ?? "") ?? resourceSlug(ctx, e));
  // X3: a field with an id format (uuid, or a catalogue path parameter's format) is a reference whatever its name
  const formats = idFormats(catalogue);
  const formatted = [...formatFields(e.requestSchema, formats), ...(e.params ?? []).filter((p) => p.in === "query" && formats.has(String(p.format ?? "").toLowerCase())).map((p) => p.name), ...gqlIdArgs(e)];
  const names = new Set([...idFields(e.requestSchema), ...(e.requestKeys ?? []).filter((k) => ID_KEY.test(k)), ...(e.params ?? []).filter((p) => p.in === "query" && ID_KEY.test(p.name)).map((p) => p.name), ...(e.graphql?.args ?? []).map((a) => a.name).filter((n) => ID_KEY.test(n)), ...formatted]);
  const refs = Object.fromEntries([...names].sort().filter((n) => !["id", "ids"].includes(n)).map((n) => [n, refTypeOf(ctx, e, catalogue, n)]));
  if (Object.keys(refs).length) meta.refs = refs;
  if (e.kind === "graphql" && e.graphql?.operationType === "mutation") meta.mutation = true;
  // X3: on a destructive or action endpoint (or a create that sounds like one), every integer or uuid in an array of the
  // body, and every uuid anywhere in it, is a reference too
  if ((e.kind === "rest" && (["action", "delete"].includes(e.crud) || (isCreate(e) && !plainCreate(e)))) || (e.kind === "graphql" && e.graphql?.operationType === "mutation" && !isCreate(e))) meta.bulk = true;
  // a collection action (POST /contacts/bulk-delete) acts on the entities of its parent collection's create
  if (meta.bulk && e.kind === "rest" && !isCreate(e) && !(e.params ?? []).some((p) => p.in === "path")) {
    const parent = erasePath(e.path).replace(/\/[^/]+\/?$/, "");
    const c = catalogue.find((x) => isCreate(x) && x.kind === "rest" && erasePath(x.path) === parent && x.server === e.server);
    if (c) meta.self = resourceSlug(ctx, c);
  }
  return meta;
}
// A create whose path, operationId and summary all read as a plain create. The catalogue classifies by the path only
// (endpoints.mjs crudOf), so a POST called "Create a batch" or createBlock stays a recorded create, its entity in the
// ledger and cleaned up; it is only kept out of the facade (round 3).
const plainCreate = (e) => e.crud === "create" && crudOf("POST", e.path) === "create" && !actionLike(...segmentsOf(e.path), e.operationId, e.summary);
const segmentsOf = (p) => String(p ?? "").split("/").filter((x) => x && !x.startsWith("{"));
// The facade glue and composite helpers get (D-056, N3): reads, and plain creates only: a POST to a collection path
// (no path parameter) that is neither destructive nor action-like by its path, operationId or summary. Never a
// delete, an update, an action or another GraphQL mutation.
function inFacade(e) {
  if (e.safeMethod) return true;
  if (e.kind === "graphql") return isCreate(e);
  return e.method === "POST" && !(e.params ?? []).some((p) => p.in === "path") && plainCreate(e);
}
// The unknown id of a request that changes data (D-005): an entity this test creates and then deletes. -> {create,
// delete, deleteParam, param} or {why}
function goneFor(e, catalogue) {
  const params = (e.params ?? []).filter((p) => p.in === "path");
  if (params.length !== 1) return { why: `an unknown id for ${e.method} ${e.path} is an entity this run created and deleted (D-005), and ${params.length ? "a nested path names more than one" : "the path names none"}` };
  for (const c of catalogue.filter((x) => isCreate(x) && x.kind === "rest").sort((a, b) => byNum(a.id, b.id))) {
    const d = deleteFor(catalogue, c);
    const del = d && catalogue.find((x) => x.id === d.endpoint);
    if (del && erasePath(del.path) === erasePath(e.path) && del.server === e.server) return { create: c.id, delete: del.id, deleteParam: d.param, param: params[0].name };
  }
  return { why: `an unknown id for ${e.method} ${e.path} is an entity this run created and deleted (D-005), and the catalogue has no create with a delete operation on that path` };
}

// Why a scenario's request can't be built: a path parameter no mutation, unknown id, setup or bound step gives a value.
function missingPathValue(s, e, byId) {
  const calls = s.steps?.length ? s.steps.map((st, i) => [byId.get(st.endpoint), i === 0 ? s.request : st.request, i === 0 ? null : st.bind]) : [[e, s.request, null]];
  for (const [x, req, bind] of calls)
    for (const p of (x.params ?? []).filter((q) => q.in === "path")) {
      const ok = (req?.mutation?.in === "path" && req.mutation.name === p.name) || req?.target === "unknown-id" || (s.request?.setup ?? []).some((su) => su.param === p.name) || bind?.param === p.name;
      if (!ok) return `path parameter ${p.name} of ${x.id} has no value in the plan (no setup, link or unknown id)`;
    }
  return null;
}

