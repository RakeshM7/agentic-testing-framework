// The malformed credential's scheme for fixtures/api/base.ts malformedAuth(scheme): the plan names a security scheme of
// the spec (or the catalogue's auth); undefined = the configured scheme.
function authSchemeOf(e, name) {
  const valid = ["none", "session", "bearer", "basic", "api-key", "oauth2"];
  if (valid.includes(name)) return name;
  const s = (e.security?.alternatives ?? []).flat().find((x) => x.scheme === name);
  if (s?.type === "apiKey") return s.in === "cookie" ? "session" : "api-key";
  if (s?.type === "http") return /basic/i.test(`${s.scheme} ${s.name ?? ""}`) ? "basic" : "bearer";
  if (s?.type === "oauth2" || s?.type === "openIdConnect") return "oauth2";
  return valid.includes(e.auth) && e.auth !== "none" ? e.auth : undefined;
}
