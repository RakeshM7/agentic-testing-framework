// The text a citation stands for, to look a value up in verbatim: a spec source's JSON node (its #pointer), a
// clarification's answer, or the cited file.
function citedText(ctx, c) {
  const [kind, ...rest] = String(c).split(":");
  const ref = rest.join(":");
  const [file, frag] = ref.split("#");
  if (kind === "clarification") return readRows(csvPath(ctx.productDir, ctx.module)).find((r) => r.id.trim() === ref)?.answer ?? null;
  const base = { spec: ctx.pp.dir, knowledge: path.join(ctx.productDir, "knowledge"), observation: path.join(ctx.productDir, "modules", ctx.module) }[kind];
  if (!base) return null;
  const text = readText(path.join(base, file));
  if (text === null) return null;
  if (!frag || !frag.startsWith("/")) return text;
  const node = getPointer(tryReadJson(path.join(base, file), null), frag);
  return node === undefined ? null : JSON.stringify(node);
}
function getPointer(doc, pointer) {
  let cur = doc;
  for (const raw of String(pointer).split("/").slice(1)) {
    const k = raw.replaceAll("~1", "/").replaceAll("~0", "~");
    if (cur === null || typeof cur !== "object" || !(k in cur)) return undefined;
    cur = cur[k];
  }
  return cur;
}
// A name is verbatim in a text when a run of whole words of the text spells it, letters and digits only, any case
// (`addTag` in "operationId": "addTag", `ContactTags` in "Contact Tags"); never a substring of a word.
export function nameIn(text, name) {
  const want = String(name).replace(/[^A-Za-z0-9]/g, "").toLowerCase();
  if (!want) return false;
  const ws = String(text ?? "").match(/[A-Za-z0-9]+/g) ?? [];
  for (let i = 0; i < ws.length; i++) {
    let acc = "";
    for (let j = i; j < ws.length && j < i + 8 && acc.length < want.length; j++) {
      acc += ws[j].toLowerCase();
      if (acc === want) return true;
    }
  }
  return false;
}
// A value is verbatim in a text when it appears exactly, as a whole token (bounded by start, end, whitespace, a quote,
// a comma, a colon or a bracket), never inside a longer token.
export function valueIn(text, value) {
  const v = String(value ?? "");
  if (!v) return false;
  const t = String(text ?? "");
  const edge = (c) => c === undefined || /[\s"'`,:;()[\]{}<>=]/.test(c);
  // a sentence's full stop after the value still ends the token: "… XMLHttpRequest."
  const after = (j) => edge(t[j]) || (/[.!?]/.test(t[j]) && edge(t[j + 1]));
  for (let i = t.indexOf(v); i >= 0; i = t.indexOf(v, i + 1)) if (edge(t[i - 1]) && after(i + v.length)) return true;
  return false;
}

// -> problems[] for one overlay entry's citations: each holds (lib/citations.mjs), a spec: citation names one of the
// entry's own endpoints' spec sources (the specific source, not any file under api/), and `values` are verbatim in at
// least one cited text (names by nameIn, values by valueIn).
function citeProblems(ctx, where, cite, endpoints, { names = [], values = [] } = {}) {
  const out = [];
  const list = Array.isArray(cite) ? cite : [];
  if (!list.length) return [`${where}: needs a citation (cite: [spec:sources/<file>#<pointer> | knowledge:<path> | clarification:<id> | observation:<path>])`];
  const cctx = { rows: readRows(csvPath(ctx.productDir, ctx.module)), cases: new Set(), productDir: ctx.productDir, moduleDir: path.join(ctx.productDir, "modules", ctx.module), apiDir: ctx.pp.dir };
  const texts = [];
  for (const c of list) {
    if (String(c).startsWith("testcase:")) {
      out.push(`${where}: '${c}': a test case is not a source for client code; cite the spec, the knowledge notes, a clarification or an observation`);
      continue;
    }
    const bad = citationProblem(c, cctx);
    if (bad) {
      out.push(`${where}: ${bad}`);
      continue;
    }
    if (String(c).startsWith("spec:")) {
      // the endpoint's own node: its source file and #pointer, or a node inside it (never the whole file or a parent
      // node that holds other operations too)
      const ref = String(c).slice(5);
      const own = endpoints.flatMap((e) => (e.sources ?? []).filter((s) => ["openapi", "graphql", "docs"].includes(s.source)).map((s) => String(s.ref)));
      const inside = (src) => {
        const [f, p = ""] = src.split("#");
        const [cf, cp] = ref.split("#");
        return cf === f && cp !== undefined && (cp === p || cp.startsWith(`${p}/`));
      };
      if (!own.some(inside)) {
        out.push(`${where}: '${c}' is not a spec source of ${endpoints.map((e) => e.id).join(", ")} (its sources: ${uniq(own).join(", ") || "none"})`);
        continue;
      }
    }
    const text = citedText(ctx, c);
    if (text === null) out.push(`${where}: '${c}': its text could not be read (a #pointer must name a node of the JSON file)`);
    else texts.push(text);
  }
  if (out.length) return out;
  for (const n of names) if (!texts.some((t) => nameIn(t, n))) out.push(`${where}: '${n}' is not spelled by whole words of any cited source (copied verbatim, never a substring)`);
  for (const v of values) if (!texts.some((t) => valueIn(t, v))) out.push(`${where}: '${v}' does not appear verbatim, as a whole token, in any cited source`);
  return out;
}

export function clientOverlayProblems(ctx, overlay, catalogue) {
  const out = [];
  if (!overlay) return out;
  const byId = new Map(catalogue.map((e) => [e.id, e]));
  const slugs = new Map();
  for (const e of catalogue) slugs.set(resourceSlug(ctx, e), [...(slugs.get(resourceSlug(ctx, e)) ?? []), e]);
  const classNames = new Map();
  for (const [slug, c] of Object.entries(overlay.classes ?? {})) {
    const where = `client-overlay.json classes['${slug}']`;
    if (!slugs.has(slug)) {
      out.push(`${where}: no resource '${slug}' in the catalogue (resources: ${[...slugs.keys()].join(", ")})`);
      continue;
    }
    if (!/^[A-Z][A-Za-z0-9]*Client$/.test(c.name ?? "")) out.push(`${where}: name must be PascalCase and end with Client`);
    else {
      if (classNames.has(c.name)) out.push(`${where}: ${c.name} is also the name of '${classNames.get(c.name)}'`);
      classNames.set(c.name, slug);
      out.push(...citeProblems(ctx, where, c.cite, slugs.get(slug), { names: [c.name.replace(/Client$/, "")] }));
    }
  }
  for (const [id, m] of Object.entries(overlay.methods ?? {})) {
    const where = `client-overlay.json methods['${id}']`;
    const e = byId.get(id);
    if (!e) {
      out.push(`${where}: no endpoint ${id} in the catalogue`);
      continue;
    }
    if (!/^[a-z][A-Za-z0-9]*$/.test(m.name ?? "") || RESERVED.has(m.name)) out.push(`${where}: name must be camelCase and not one of ${[...RESERVED].join(", ")}`);
    else out.push(...citeProblems(ctx, where, m.cite, [e], { names: [m.name] }));
  }
  (overlay.edgeCases ?? []).forEach((x, i) => {
    const where = `client-overlay.json edgeCases[${i}]`;
    const e = byId.get(x.endpoint);
    if (!e) return out.push(`${where}: no endpoint ${x.endpoint} in the catalogue`);
    if (x.kind === "content-type") {
      if (!CONTENT_KINDS[x.value]) out.push(`${where}: content type must be one of ${Object.keys(CONTENT_KINDS).join(", ")}`);
      else out.push(...citeProblems(ctx, where, x.cite, [e], { values: [x.value] }));
    } else if (x.kind === "header") {
      if (!HEADER_NAME_RE.test(x.name ?? "")) out.push(`${where}: name must be a header name`);
      else if (AUTH_HEADER_RE.test(x.name)) out.push(`${where}: ${x.name} carries credentials: only the auth scheme sets it (fixtures/api/base.ts), never a client`);
      else if (URL_RE.test(x.value ?? "") || looksLikeSecret(String(x.value ?? ""))) out.push(`${where}: the value looks like a URL, a key or a token: a client holds none`);
      else out.push(...citeProblems(ctx, where, x.cite, [e], { values: [x.name, x.value] }));
    } else if (x.kind === "note") out.push(...citeProblems(ctx, where, x.cite, [e]));
    else out.push(`${where}: kind must be content-type, header or note`);
  });
  return out;
}

