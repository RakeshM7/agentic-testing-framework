  const moduleCleanup = [...new Map(catalogue.filter(isCreate).sort((a, b) => byNum(a.id, b.id)).map((c) => [resourceSlug(ctx, c), c])).values()]
    .map((c) => ({ creator: c.id, type: resourceSlug(ctx, c), pointer: idPointer(catalogue, c), delete: deleteFor(catalogue, c) }))
    .sort((a, b) => a.type.localeCompare(b.type));
