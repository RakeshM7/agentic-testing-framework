test("a gap or missing-export request extends the extension files without breaking existing exports; seeds are never overwritten", async () => {
  const { root } = startRun();
  put(root, "artifacts/acme/knowledge/overview.md", "# Acme\nDates show as 18 Oct 2026.\n");
  await renderFoundation(root, ["repo", "ui", "k6"]);
  // a page object fixture registered in the seeded index.ts survives a re-render
  const index = "import { test as base } from './base';\nimport { ListPage } from '../../pages/contacts/list.page';\nexport const test = base.extend<{ listPage: ListPage }>({ listPage: async ({ page }, use) => use(new ListPage(page)) });\nexport { expect } from './base';\n";
  put(root, "playwright-tests/acme/fixtures/ui/index.ts", index);
  put(root, "playwright-tests/acme/helpers/ui/dates.ts", "export function formatDate(d: Date): string { return d.toISOString().slice(0, 10); }\n");
  const gap = { kind: "gap", text: "pw-ui-pom-writer: no date formatter for the list's dates", requestedBy: "pw-ui-pom-writer", files: ["helpers/ui/dates.ts"], exports: ["formatDate"], cite: ["knowledge:overview.md"] };
  overlay(root, "ui", { requests: [gap] });
  assert.equal((await run(root, "render", "acme", "--side", "ui")).code, 0);
  assert.equal(read(pw(root, "fixtures/ui/index.ts")), index, "the extension file is the writers'");
  assert.match(read(pw(root, "config/ui/README.md")), /gap from pw-ui-pom-writer: .*-> helpers\/ui\/dates\.ts \(exports formatDate\)/);
  assert.equal((await check(root, "ui")).valid, true);
  // a second gap extends; the first one's exports must stay
  put(root, "playwright-tests/acme/helpers/ui/dates.ts", "export function parseDate(s: string): Date { return new Date(s); }\n");
  overlay(root, "ui", { requests: [gap, { ...gap, text: "a date parser", exports: ["parseDate"] }] });
  await run(root, "render", "acme", "--side", "ui");
  assert.match((await check(root, "ui")).problems.join("\n"), /requests\[0\]: formatDate is not exported by helpers\/ui\/dates\.ts/);
  put(root, "playwright-tests/acme/helpers/ui/dates.ts", "export function formatDate(d: Date): string { return d.toISOString().slice(0, 10); }\nexport function parseDate(s: string): Date { return new Date(s); }\n");
  assert.equal((await check(root, "ui")).valid, true);
  // a request can't be resolved in a managed file
  overlay(root, "ui", { requests: [{ ...gap, files: ["fixtures/ui/base.ts"] }] });
  assert.match((await run(root, "render", "acme", "--side", "ui")).out.problems.join("\n"), /fixtures\/ui\/base\.ts is not an extension file of the ui side/);
  // k6: missing exports go to lib/ext/, never into the rendered lib
  put(root, "k6-tests/acme/lib/ext/paging.js", "export function nextPage(res) { return res.json('next'); }\n");
  overlay(root, "k6", { requests: [{ kind: "missing-export", text: "k6-script-writer: nextPage", files: ["lib/ext/paging.js"], exports: ["nextPage"], cite: ["knowledge:overview.md"] }] });
  assert.equal((await run(root, "render", "acme", "--side", "k6")).code, 0);
  assert.equal((await check(root, "k6")).valid, true);
});

