test("templates checked out with CRLF (core.autocrlf) render the same LF bytes and the same stamp", async () => {
  const { root } = startRun();
  const { cpSync, mkdtempSync, readdirSync, statSync } = await import("node:fs");
  const { tmpdir } = await import("node:os");
  const crlfRoot = mkdtempSync(path.join(tmpdir(), "atf-crlf-"));
  cpSync(path.join(repoRoot, "templates"), path.join(crlfRoot, "templates"), { recursive: true });
  const toCrlf = (dir) => {
    for (const f of readdirSync(dir)) {
      const abs = path.join(dir, f);
      if (statSync(abs).isDirectory()) toCrlf(abs);
      else writeFileSync(abs, read(abs).replace(/\r?\n/g, "\r\n"));
    }
  };
  toCrlf(path.join(crlfRoot, "templates"));
  assert.match(read(path.join(crlfRoot, "templates/k6/lib/config.js.tpl")), /\r\n/);
  const lf = ctxOf(root);
  const crlf = { ...ctxOf(root), templatesRoot: crlfRoot };
  for (const side of SIDES) {
    const a = renderSide(lf, side, {});
    const b = renderSide(crlf, side, {});
    for (const [f, { content }] of a.files) {
      assert.equal(b.files.get(f).content, content, `${side}: ${f}`);
      assert.doesNotMatch(content, /\r/, `${side}: ${f} is LF only`);
    }
    for (const [f, content] of b.seeds) assert.doesNotMatch(content, /\r/, `${side}: seed ${f}`);
    assert.equal(currentStamp(crlf, side).templates, currentStamp(lf, side).templates, `${side}: the templates hash ignores line endings`);
  }
  assert.match(read(path.join(repoRoot, ".gitattributes")), /^templates\/\*\* text eol=lf$/m);
});

test("drift: a hand-edited managed file fails check; package.json's dependency versions and package-lock.json are ignored, its scripts and dependency names are not", async () => {
  const { root } = startRun();
  await renderFoundation(root);
  const ctx = ctxOf(root);
  assert.equal(foundationUnverified(ctx, "repo"), null);
  // npm install: versions resolved, the lockfile written -- no drift, the stamp still holds
  const pkg = JSON.parse(read(pw(root, "package.json")));
  pkg.devDependencies["@playwright/test"] = "^1.99.0";
  writeFileSync(pw(root, "package.json"), JSON.stringify(pkg, null, 2) + "\n");
  writeFileSync(pw(root, "package-lock.json"), "{}\n");
  assert.equal((await check(root, "repo")).valid, true);
  assert.equal(foundationUnverified(ctx, "repo"), null, "versions and the lockfile are outside the stamp");
  // a re-render never bumps a version
  await run(root, "render", "acme", "--side", "repo");
  assert.equal(JSON.parse(read(pw(root, "package.json"))).devDependencies["@playwright/test"], "^1.99.0");
  // a new dependency name, or a changed script, is drift
  pkg.devDependencies.lodash = "^4.0.0";
  writeFileSync(pw(root, "package.json"), JSON.stringify(pkg, null, 2) + "\n");
  assert.match((await check(root, "repo")).problems.join("\n"), /package\.json was hand-edited/);
  delete pkg.devDependencies.lodash;
  pkg.scripts.typecheck = "echo skip";
  writeFileSync(pw(root, "package.json"), JSON.stringify(pkg, null, 2) + "\n");
  assert.match((await check(root, "repo")).problems.join("\n"), /package\.json was hand-edited/);
  // any other managed file: the stamp goes stale at once, and a failing check clears it
  await run(root, "render", "acme", "--side", "repo");
  assert.equal((await check(root, "repo")).valid, true);
  writeFileSync(pw(root, "utils/shared/data.ts"), read(pw(root, "utils/shared/data.ts")) + "export const x = 1;\n");
  assert.match(foundationUnverified(ctx, "repo"), /changed after its check: .*file:utils\/shared\/data\.ts/);
  const r = await check(root, "repo");
  assert.equal(r.valid, false);
  assert.equal(r.stamped, false);
  assert.match(r.problems.join("\n"), /utils\/shared\/data\.ts was hand-edited/);
  assert.match(foundationUnverified(ctx, "repo"), /never passed foundation\.mjs check/);
  // render repairs it, keeping the versions
  await run(root, "render", "acme", "--side", "repo");
  assert.equal((await check(root, "repo")).valid, true);
});

