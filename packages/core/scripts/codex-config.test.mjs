// The Codex project config (.codex/config.toml): the atf block, merged with the workspace's own settings
// (lib/codex-config.mjs).
import test from "node:test";
import assert from "node:assert/strict";
import { CODEX_CONFIG, atfBlock, renderCodexConfig, tomlString } from "./lib/codex-config.mjs";

const FW = "node_modules/@atf/core";
const MCP = {
  browser_server: "playwright",
  servers: {
    playwright: {
      command: "npx",
      args: ["-y", "@playwright/mcp@0.0.83", "--browser", "chromium", "--isolated", "--init-page", "{fw}/scripts/browser/init-page.cjs"],
    },
  },
};
const START = "# >>> atf: generated by build-agents (D-115) -- do not edit inside this block; run npm run build-agents >>>";
const END = "# <<< atf <<<";
const thrown = (fn) => {
  try {
    fn();
  } catch (e) {
    return e;
  }
  assert.fail("expected an error");
};
const render = (text, mcp = MCP, fw = FW) => renderCodexConfig(text, mcp, fw);

test("a fresh render is exactly the atf block, ending in a newline", () => {
  for (const text of [undefined, "", "  \n\n"]) {
    const out = render(text);
    assert.equal(out, atfBlock(MCP, FW));
    assert.ok(out.startsWith(START + "\n"));
    assert.ok(out.endsWith(END + "\n"));
  }
});

test("the block: web search off, agents.max_depth 3, one table per server with {fw} expanded", () => {
  const block = atfBlock(MCP, FW);
  assert.match(block, /^web_search = "disabled" +# UNVERIFIED key \(Codex spike pending, docs\/codex-spike\/\)/m);
  assert.match(block, /^\[agents\]\nmax_depth = 3 /m);
  assert.match(block, /^\[mcp_servers\.playwright\]/m);
  assert.match(block, /^command = "npx"$/m);
  assert.ok(
    block.includes(
      `args = ["-y", "@playwright/mcp@0.0.83", "--browser", "chromium", "--isolated", "--init-page", "${FW}/scripts/browser/init-page.cjs"]`,
    ),
  );
  assert.ok(!block.includes("{fw}/scripts/browser"));
  // the framework's own repository: no prefix
  assert.ok(atfBlock(MCP, "").includes('"scripts/browser/init-page.cjs"]'));
});

test("several servers, quoted names, env as an inline table, one-line arrays", () => {
  const mcp = {
    servers: {
      one: { command: "node", args: ["{fw}/a.js"], env: { TOKEN: "x\"y", "odd key": "v", PATH_FW: "{fw}/bin" } },
      "two.three": { command: "c" },
    },
  };
  const block = atfBlock(mcp, FW);
  assert.ok(block.includes('[mcp_servers.one]'));
  assert.ok(block.includes('[mcp_servers."two.three"]'));
  assert.ok(block.includes(`args = ["${FW}/a.js"]`));
  assert.ok(block.includes(`env = { TOKEN = "x\\"y", "odd key" = "v", PATH_FW = "${FW}/bin" }`));
  assert.ok(block.indexOf("[mcp_servers.one]") < block.indexOf('[mcp_servers."two.three"]'));
});

test("TOML basic-string escaping", () => {
  assert.equal(tomlString('a"b\\c'), '"a\\"b\\\\c"');
  assert.equal(tomlString("l1\nl2\tx\r\b\f"), '"l1\\nl2\\tx\\r\\b\\f"');
  assert.equal(tomlString("\u0001\u007f"), '"\\u0001\\u007F"');
  assert.equal(tomlString("naïve ✓"), '"naïve ✓"');
});

test("an unsupported server shape throws", () => {
  const bad = [
    [{ servers: { a: { command: "x", url: "http://h" } } }, /'url' can't be rendered/],
    [{ servers: { a: { command: 3 } } }, /command must be a string/],
    [{ servers: { a: { args: "x" } } }, /args must be a list/],
    [{ servers: { a: { args: [1] } } }, /args\[0\] must be a string/],
    [{ servers: { a: { env: ["x"] } } }, /env must be a mapping/],
    [{ servers: { a: { env: { K: 1 } } } }, /env\.K must be a string/],
    [{ servers: { a: "x" } }, /must be a mapping/],
    [{}, /needs a 'servers' mapping/],
  ];
  for (const [mcp, message] of bad) {
    const e = thrown(() => render(undefined, mcp));
    assert.match(e.message, message);
    assert.equal(e.file, CODEX_CONFIG);
  }
});

test("the client's prelude and tail are kept, block between; re-render is idempotent and byte for byte", () => {
  const client = [
    "# my settings",
    'model = "gpt-5"   # trailing',
    "",
    'notes = """',
    "[not a header]",
    "# not a comment",
    '"""',
    "",
    "[profiles.fast]",
    'model = "mini"',
    "",
    "[mcp_servers.mine]",
    'command = "x"',
    "",
  ].join("\n");
  const once = render(client);
  const start = once.indexOf(START);
  const end = once.indexOf(END) + END.length + 1;
  const prelude = once.slice(0, start);
  const tail = once.slice(end);
  assert.ok(prelude.startsWith('# my settings\nmodel = "gpt-5"'));
  assert.ok(prelude.includes('"""\n\n'));
  assert.ok(prelude.endsWith("\n\n"));
  assert.ok(tail.endsWith("[profiles.fast]\n" + 'model = "mini"\n\n[mcp_servers.mine]\ncommand = "x"\n'));
  assert.ok(!prelude.includes("[profiles.fast]"));
  assert.equal(render(once), once);
  // a replaced block keeps whatever surrounds it, even odd spacing
  const odd = prelude + "\n\n" + once.slice(start, end) + "\n\n\n" + tail.trimStart();
  const rerendered = render(odd.replace('"disabled"', '"live"'));
  assert.equal(rerendered, odd);
  const stale = odd.replace('max_depth = 3', 'max_depth = 9');
  assert.equal(render(stale), odd);
});

test("a stale block with an old path is replaced, never duplicated", () => {
  const old = render('x = 1\n\n[t]\na = 1\n', MCP, "old/fw");
  const fresh = render(old, MCP, FW);
  assert.equal(fresh.split(START).length, 2);
  assert.equal(fresh.split("[agents]").length, 2);
  assert.ok(!fresh.includes("old/fw"));
  assert.ok(fresh.includes(FW));
  assert.ok(fresh.startsWith("x = 1\n\n"));
  assert.ok(fresh.endsWith("[t]\na = 1\n"));
});

test("only a tail: first render puts a blank line between block and tail; prelude-only keeps no extra tail", () => {
  const tailOnly = render("[a]\nb = 1\n");
  assert.equal(tailOnly, atfBlock(MCP, FW) + "\n[a]\nb = 1\n");
  const preOnly = render("top = 1");
  assert.equal(preOnly, "top = 1\n\n" + atfBlock(MCP, FW));
  assert.equal(render(tailOnly), tailOnly);
  assert.equal(render(preOnly), preOnly);
});

test("table headers with spaces, quotes and trailing comments are recognised", () => {
  for (const header of ['[ mcp_servers."playwright" ]', "[mcp_servers.'playwright']", "[mcp_servers.playwright] # mine", '[ mcp_servers . "playwright" . env ]']) {
    const e = thrown(() => render(`${header}\ncommand = "x"\n`));
    assert.match(e.message, /MCP server 'playwright' is rendered by the atf block/, header);
    assert.equal(e.file, CODEX_CONFIG);
    assert.match(e.message, /\.codex\/config\.toml/);
  }
  for (const header of ["[agents]", "[ agents ]", '["agents"]', "[agents.sub]", "[[agents]]", "[agents] # c"]) {
    const e = thrown(() => render(`${header}\nmax_depth = 1\n`));
    assert.match(e.message, /is set by the atf block/, header);
  }
  // another server, a different table, a quoted "#"
  const ok = render('[mcp_servers.mine]\ncommand = "a # b"\n[agents_extra]\nx = 1\n');
  assert.ok(ok.includes("[mcp_servers.mine]"));
});

test("a table in the prelude (before an existing block) is an error", () => {
  const e = thrown(() => render(`[x]\na = 1\n${START}\nweb_search = "disabled"\n${END}\n`));
  assert.match(e.message, /the table \[x\] comes before the atf block/);
  assert.equal(e.file, CODEX_CONFIG);
});

test("a key line after the block, before the tail's first header, is an error", () => {
  const e = thrown(() => render(`${START}\n${END}\nloose = 1\n[t]\n`));
  assert.match(e.message, /'loose' follows the atf block/);
  assert.match(e.message, /move it above the block/);
  // comments and blanks are fine
  assert.doesNotThrow(() => render(`${START}\n${END}\n\n# c\n[t]\n`));
});

test("a prelude key the block also sets is an error", () => {
  const keys = ['web_search = "live"', "agents.max_depth = 1", 'features.web_search = true', 'mcp_servers.x.command = "a"', "agents = { max_depth = 1 }"];
  for (const k of keys) {
    const e = thrown(() => render(`ok = 1\n${k}\n[t]\n`));
    assert.match(e.message, /is set by the atf block/, k);
    assert.match(e.message, /line 2/, k);
    assert.equal(e.file, CODEX_CONFIG);
  }
  // the same keys inside a tail table are the client's own tables
  assert.doesNotThrow(() => render('[features]\nweb_search = true\n'));
  assert.doesNotThrow(() => render('features.other = 1\n'));
});

test("a start marker without an end marker (or the reverse) is an error", () => {
  const e = thrown(() => render(`a = 1\n${START}\nweb_search = "disabled"\n`));
  assert.match(e.message, /start marker has no end marker/);
  assert.equal(e.file, CODEX_CONFIG);
  const e2 = thrown(() => render(`a = 1\n${END}\n`));
  assert.match(e2.message, /end marker .* has no start marker/);
  assert.equal(e2.file, CODEX_CONFIG);
});

test("a marker-looking line inside a string is not a marker; a # in a string is not a comment", () => {
  const text = `s = """\n${START}\n"""\nu = "# not a comment [x]"\n`;
  const out = render(text);
  assert.equal(out.split(START).length, 3); // the string's copy plus ours
  assert.ok(out.startsWith(text));
  assert.equal(render(out), out);
});

test("multi-line arrays and inline tables with [ ] lines are not taken for headers", () => {
  const text = 'list = [\n  [1, 2],\n  [3],\n]\ninline = {\n a = 1 }\n';
  const out = render(text);
  assert.ok(out.startsWith(text));
  assert.equal(render(out), out);
});

test("CRLF files stay CRLF, with no bare LF added", () => {
  const client = 'top = 1\r\n\r\n[t]\r\na = 1\r\n';
  const out = render(client);
  assert.ok(!/(?<!\r)\n/.test(out), "no bare LF");
  assert.ok(out.startsWith("top = 1\r\n\r\n" + START + "\r\n"));
  assert.ok(out.endsWith("[t]\r\na = 1\r\n"));
  assert.equal(render(out), out);
  assert.ok(!/\r/.test(render("top = 1\n[t]\n")));
});

test("output always ends with a newline, even when the client's tail did not", () => {
  assert.ok(render("[t]\na = 1").endsWith("a = 1\n"));
  assert.ok(render(`${START}\n${END}`).endsWith(END + "\n"));
  assert.equal(render(`${START}\n${END}`), atfBlock(MCP, FW));
});
