// Shared by every renderer: the note that marks a file as generated (a YAML comment, so the model never reads it). It
// names the source and the builder from the workspace (`fw`: the framework's path from there, D-085).
//
// What the note tells the reader to do depends on where the source is. In a source checkout (this monorepo, or a scratch
// copy) it is the agent's source and npm run build-agents; that text is committed in every host file here, so it never
// changes (D-018: a reworded note would be drift in all of them). In a client's workspace the framework is installed
// (roots.mjs isInstalled): its sources are inside node_modules and are not the client's to edit, so the note names
// atf sync and what the client does own: the agent's add-on fragment, and config in atf/ (docs/packaging.md §3.4–3.6).
import { expandFw } from "../../roots.mjs";
import { fragmentRel } from "../source.mjs";

export const PACKAGE_NAME = "@testagentic/atf";

export const generatedNote = (name, fw = "", installed = false) =>
  installed
    ? `# GENERATED by atf sync from ${PACKAGE_NAME} (agents/${name}.md) -- do not edit: add instructions in ${fragmentRel(name)}, or config in atf/ (overlays, or npx atf eject config), then run npx atf sync.`
    : expandFw(`# GENERATED from {fw}/agents/${name}.md by {fw}/scripts/build-agents.mjs -- edit the source, then run npm run build-agents.`, fw);

// The framework's generated marker: the note above as the frontmatter's first line, in either wording (and as every
// earlier version wrote it, `# GENERATED from …`). The build tells its own outputs from a client's own agent files by it
// (scripts/build-agents.mjs): a marked file with no source is a stray of ours, an unmarked one is the client's.
const MARKER = /^﻿?---\r?\n# GENERATED (from |by atf sync )/;
export const isGenerated = (text) => MARKER.test(text);

// Frontmatter lines + body -> file text, in the source's line endings.
export const assemble = (lines, body, eol) => ["---", ...lines, "---"].join(eol) + eol + body;
