// The project's Codex config, .codex/config.toml, rendered by scripts/build-agents.mjs (D-115).
//
// The file is shared with the workspace's own Codex settings, so the build owns only one block of it, between two marker
// comments: hosted web search off, `agents.max_depth = 3`, and one `[mcp_servers.<name>]` table per server of
// config/mcp.yaml (`{fw}` expanded). The layout is always
//   prelude   the client's part before any table header: blank lines, comments and top-level `key = value` lines
//   the atf block
//   tail      the client's part from its first table header on
// because TOML wants top-level keys before any table, and the block's last table would swallow a top-level key that
// came after it. On a re-render the old block is found by its markers and replaced; the prelude and the tail come back
// byte for byte (and so does the file's EOL style: CRLF when the file uses it).
//
// Errors (e.file = CODEX_CONFIG; nothing is written), each saying what to move where:
//   - a table header in the prelude (before the atf block)
//   - a non-comment line after the atf block and before the tail's first table header
//   - a top-level key the block also sets: `web_search`, `agents.*`, `features.web_search`, `mcp_servers.*`
//   - a tail table `[agents]`, `[agents.*]`, or `[mcp_servers.<a server the block renders>]`
//   - a block start marker with no end marker (or an end marker with no start)
// Only the shapes config/mcp.yaml uses are rendered: `command`, `args` (a list of strings) and `env` (a map of strings,
// an inline table); anything else in a server definition is an error.
// The line scanner knows TOML strings (basic, literal, multi-line), comments and multi-line arrays/inline tables, so a
// `#` or a `[` inside a value is never taken for a comment or a header.
// UNVERIFIED (Codex spike pending, docs/codex-spike/): the `web_search` key and its value "disabled", `agents.max_depth`,
// and that Codex reads .codex/config.toml's mcp_servers for a trusted project.
// Dependency-free.
import { expandFw } from "./roots.mjs";

export const CODEX_CONFIG = ".codex/config.toml";
const START_MARK = "# >>> atf: generated by build-agents (D-115) -- do not edit inside this block; run npm run build-agents >>>";
const END_MARK = "# <<< atf <<<";
const START_PREFIX = "# >>> atf:";

const fail = (message) => {
  const e = new Error(message);
  e.file = CODEX_CONFIG;
  return e;
};

// ---- TOML output ----

export function tomlString(s) {
  let out = '"';
  for (const ch of String(s)) {
    const c = ch.codePointAt(0);
    if (ch === "\\") out += "\\\\";
    else if (ch === '"') out += '\\"';
    else if (ch === "\b") out += "\\b";
    else if (ch === "\t") out += "\\t";
    else if (ch === "\n") out += "\\n";
    else if (ch === "\f") out += "\\f";
    else if (ch === "\r") out += "\\r";
    else if (c < 0x20 || c === 0x7f) out += `\\u${c.toString(16).toUpperCase().padStart(4, "0")}`;
    else out += ch;
  }
  return out + '"';
}

const tomlKey = (k) => (/^[A-Za-z0-9_-]+$/.test(k) ? k : tomlString(k));
const isMap = (v) => Object.prototype.toString.call(v) === "[object Object]";

function serverTable(name, def, fw) {
  const where = `config/mcp.yaml server '${name}'`;
  if (!isMap(def)) throw fail(`${where} must be a mapping with command, args and env, not ${def === null ? "null" : typeof def}`);
  for (const k of Object.keys(def))
    if (!["command", "args", "env"].includes(k))
      throw fail(`${where}: '${k}' can't be rendered into ${CODEX_CONFIG} (only command, args and env are supported)`);
  const str = (v, what) => {
    if (typeof v !== "string") throw fail(`${where}: ${what} must be a string, not ${v === null ? "null" : typeof v}`);
    return tomlString(expandFw(v, fw));
  };
  const lines = [`[mcp_servers.${tomlKey(name)}]`];
  if (def.command !== undefined) lines.push(`command = ${str(def.command, "command")}`);
  if (def.args !== undefined) {
    if (!Array.isArray(def.args)) throw fail(`${where}: args must be a list of strings`);
    lines.push(`args = [${def.args.map((a, i) => str(a, `args[${i}]`)).join(", ")}]`);
  }
  if (def.env !== undefined) {
    if (!isMap(def.env)) throw fail(`${where}: env must be a mapping of strings`);
    const pairs = Object.entries(def.env).map(([k, v]) => `${tomlKey(k)} = ${str(v, `env.${k}`)}`);
    lines.push(`env = { ${pairs.join(", ")} }`);
  }
  return lines.join("\n");
}

// The block, LF-terminated (renderCodexConfig converts the EOL), from the first marker to the last.
export function atfBlock(mcp, fw = "") {
  const servers = mcp?.servers;
  if (!isMap(servers)) throw fail("config/mcp.yaml: needs a 'servers' mapping");
  const parts = [
    START_MARK,
    'web_search = "disabled"          # UNVERIFIED key (Codex spike pending, docs/codex-spike/): hosted web search is off, the guard can\'t see it',
    "",
    "[agents]",
    "max_depth = 3                    # main session -> orchestrator-agent -> domain orchestrators -> workers",
  ];
  for (const [name, def] of Object.entries(servers)) {
    const [header, ...rest] = serverTable(name, def, fw).split("\n");
    parts.push("", `${header}         # from config/mcp.yaml, {fw} expanded`, ...rest);
  }
  parts.push(END_MARK);
  return parts.join("\n") + "\n";
}

// ---- TOML scanning (just enough to classify the client's lines) ----

// -> [{ kind: "header" | "key" | "comment" | "blank", path: [segments], start, end, line }]; `start`/`end` are offsets
// of the statement's text (end after its EOL), `line` the 1-based line it starts on.
function scan(text) {
  const out = [];
  let i = 0;
  let line = 1;
  const n = text.length;
  const skipEol = () => {
    if (text[i] === "\r" && text[i + 1] === "\n") i += 2;
    else if (text[i] === "\n" || text[i] === "\r") i += 1;
  };
  const toEol = () => {
    while (i < n && text[i] !== "\n" && text[i] !== "\r") i++;
  };
  // a quoted key segment or a bare one, from i; returns the segment text
  const segment = () => {
    const q = text[i];
    if (q === '"' || q === "'") {
      let s = "";
      i++;
      while (i < n && text[i] !== q && text[i] !== "\n") {
        if (q === '"' && text[i] === "\\" && i + 1 < n) {
          s += text[i + 1];
          i += 2;
        } else s += text[i++];
      }
      if (text[i] === q) i++;
      return s;
    }
    let s = "";
    while (i < n && /[A-Za-z0-9_-]/.test(text[i])) s += text[i++];
    return s;
  };
  const ws = () => {
    while (text[i] === " " || text[i] === "\t") i++;
  };
  const dotted = () => {
    const path = [];
    for (;;) {
      ws();
      path.push(segment());
      ws();
      if (text[i] === ".") i++;
      else return path;
    }
  };
  // a value, from i, to the end of the statement (its multi-line strings and brackets included), then to the EOL
  const value = () => {
    let depth = 0;
    while (i < n) {
      const c = text[i];
      if (c === '"' || c === "'") {
        if (text.startsWith(c.repeat(3), i)) {
          i += 3;
          for (;;) {
            if (i >= n) return;
            if (c === '"' && text[i] === "\\") i += 2;
            else if (text.startsWith(c.repeat(3), i)) {
              i += 3;
              while (text[i] === c) i++; // up to two more quotes may close a multi-line string
              break;
            } else i++;
          }
        } else {
          i++;
          while (i < n && text[i] !== c && text[i] !== "\n") i += c === '"' && text[i] === "\\" ? 2 : 1;
          if (text[i] === c) i++;
        }
      } else if (c === "#") toEol();
      else if (c === "[" || c === "{") (depth++, i++);
      else if (c === "]" || c === "}") (depth = Math.max(0, depth - 1), i++);
      else if (c === "\n" || c === "\r") {
        if (depth === 0) return;
        i++;
      } else i++;
    }
  };
  while (i < n) {
    const start = i;
    const startLine = line;
    ws();
    const c = text[i];
    let stmt;
    if (i >= n || c === "\n" || c === "\r") stmt = { kind: "blank", path: [] };
    else if (c === "#") {
      toEol();
      stmt = { kind: "comment", path: [] };
    } else if (c === "[") {
      i += text[i + 1] === "[" ? 2 : 1;
      const path = dotted();
      toEol();
      stmt = { kind: "header", path };
    } else {
      const path = dotted();
      if (text[i] === "=") i++;
      value();
      stmt = { kind: "key", path };
    }
    toEol();
    skipEol();
    for (let k = start; k < i; k++) if (text[k] === "\n") line++;
    out.push({ ...stmt, start, end: i, line: startLine });
  }
  return out;
}

const fix = "fix it, nothing was written";

function checkPrelude(stmts) {
  for (const s of stmts) {
    if (s.kind === "header")
      throw fail(`${CODEX_CONFIG} line ${s.line}: the table [${s.path.join(".")}] comes before the atf block: move every table to after the block's end marker (top-level keys stay above it); ${fix}`);
    if (s.kind !== "key") continue;
    const [a, b] = s.path;
    const clash =
      a === "web_search" ? "web_search" : a === "agents" ? "agents" : a === "mcp_servers" ? "mcp_servers" : a === "features" && b === "web_search" ? "features.web_search" : null;
    if (clash)
      throw fail(`${CODEX_CONFIG} line ${s.line}: the top-level key '${s.path.join(".")}' is set by the atf block (${clash}): ${clash === "mcp_servers" || clash === "agents" ? "mcp servers belong in config/mcp.yaml (the workspace's atf/mcp.yaml overlay), agents settings can't be changed" : "hosted web search stays off"}; remove it from ${CODEX_CONFIG}; ${fix}`);
  }
}

function checkTail(stmts, servers, afterBlock) {
  let seenHeader = false;
  for (const s of stmts) {
    if (s.kind === "header") {
      seenHeader = true;
      const [a, b] = s.path;
      if (a === "agents")
        throw fail(`${CODEX_CONFIG} line ${s.line}: the table [${s.path.join(".")}] is set by the atf block ([agents], max_depth = 3): remove it from ${CODEX_CONFIG}; ${fix}`);
      if (a === "mcp_servers" && b !== undefined && servers.includes(b))
        throw fail(`${CODEX_CONFIG} line ${s.line}: the MCP server '${b}' is rendered by the atf block from config/mcp.yaml: remove this table and change the server in config/mcp.yaml (the workspace's atf/mcp.yaml overlay); ${fix}`);
    } else if (s.kind === "key" && afterBlock && !seenHeader)
      throw fail(`${CODEX_CONFIG} line ${s.line}: the key '${s.path.join(".")}' follows the atf block, so TOML would read it as part of the block's last table: move it above the block's start marker, before any table header; ${fix}`);
  }
}

// The current .codex/config.toml text (or undefined) -> the whole new text, always ending in a newline.
export function renderCodexConfig(currentText, mcp, fw = "") {
  const text = currentText === undefined || currentText.trim() === "" ? "" : currentText; // a blank file is no file
  const eol = text.includes("\r\n") ? "\r\n" : "\n";
  const servers = Object.keys(mcp?.servers ?? {});
  const block = atfBlock(mcp, fw).replaceAll("\n", eol);
  const stmts = scan(text);

  const startAt = stmts.findIndex((s) => s.kind === "comment" && text.slice(s.start, s.end).trim().startsWith(START_PREFIX));
  const endAt = stmts.findIndex((s, k) => k > Math.max(startAt, -1) && s.kind === "comment" && text.slice(s.start, s.end).trim() === END_MARK);
  const strayEnd = startAt < 0 && stmts.some((s) => s.kind === "comment" && text.slice(s.start, s.end).trim() === END_MARK);
  if (startAt >= 0 && endAt < 0)
    throw fail(`${CODEX_CONFIG} line ${stmts[startAt].line}: the atf block's start marker has no end marker ('${END_MARK}'): restore the end marker, or delete the whole block, and run build-agents again; ${fix}`);
  if (strayEnd)
    throw fail(`${CODEX_CONFIG}: the atf block's end marker ('${END_MARK}') has no start marker: delete the stray marker or restore the whole block; ${fix}`);

  let prelude;
  let tail;
  if (startAt >= 0) {
    prelude = text.slice(0, stmts[startAt].start);
    tail = text.slice(stmts[endAt].end);
    checkPrelude(stmts.slice(0, startAt));
    checkTail(stmts.slice(endAt + 1), servers, true);
  } else {
    const firstHeader = stmts.findIndex((s) => s.kind === "header");
    const cut = firstHeader < 0 ? stmts.length : firstHeader;
    prelude = text.slice(0, stmts[cut]?.start ?? text.length);
    tail = text.slice(stmts[cut]?.start ?? text.length);
    checkPrelude(stmts.slice(0, cut));
    checkTail(stmts.slice(cut), servers, false);
  }

  // first render: a blank line between the client's parts and the block; kept as it is on every later one
  let out = prelude;
  if (startAt < 0) {
    if (out !== "" && !/[\r\n]$/.test(out)) out += eol;
    if (out.trim() !== "" && !/(\r?\n){2}$/.test(out)) out += eol;
  }
  out += block;
  if (tail !== "") {
    if (startAt < 0) out += eol;
    out += tail;
    if (!/[\r\n]$/.test(out)) out += eol;
  }
  return out;
}
